const key = (value: string | null | undefined) =>
  (value ?? "").trim().toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");

/**
 * The starter price list is for a clinic without a price list: no
 * categories and no service with a code (the default directions of a new
 * clinic — «Имплантация», «Терапия»… without prices — do not count).
 */
export const isPriceListEmpty = (
  categories: ServiceCategory[],
  rows: Pick<PriceListRow, "code">[],
) => categories.length === 0 && !rows.some((row) => row.code);

/**
 * The services to create: the starter lines in order, after the existing
 * services, skipping a name or a code the clinic already has.
 */
export const starterServices = (
  existing: Pick<PriceListRow, "name" | "code" | "position">[],
): NewService[] => {
  const names = new Set(existing.map((row) => key(row.name)));
  const codes = new Set(
    existing.map((row) => key(row.code)).filter((code) => code),
  );
  let position = existing.reduce((max, row) => Math.max(max, row.position), -1);
  return STARTER_PRICE_LIST.filter(
    ([code, name]) => !names.has(key(name)) && !codes.has(key(code)),
  ).map(([code, name, category, price, unit, duration, specialty]) => ({
    code,
    name,
    category,
    price,
    unit,
    duration_minutes: duration,
    specialty,
    position: ++position,
    is_archived: false,
  }));
};
