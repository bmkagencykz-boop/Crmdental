-- Deals already waiting for an answer when this is deployed do not alert
-- (they show on the board and the dashboard)
insert into public.response_alerts (organization_id, deal_id, waiting_since, level)
select d.organization_id, d.id, w.waiting_since, l.level
from public.deals d
  cross join lateral (select private.deal_waiting_since(d.organization_id, d.id) as waiting_since) w
  cross join (values (1), (2)) as l(level)
where w.waiting_since is not null
on conflict do nothing;

