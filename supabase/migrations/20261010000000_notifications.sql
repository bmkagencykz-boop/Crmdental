--
-- Response time
--

-- Minutes between two moments that fall within the working hours of the
-- clinic (hours_start:00 to hours_end:00, every day, in its time zone).
-- Same as workingMinutes() in providers/commons/responseTime.ts.
CREATE OR REPLACE FUNCTION "private"."working_minutes"("from_at" timestamp with time zone, "to_at" timestamp with time zone, "time_zone" "text", "hours_start" integer DEFAULT 9, "hours_end" integer DEFAULT 21) RETURNS integer
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
  select coalesce(floor(sum(greatest(0, extract(epoch from
      least(to_at, (g.day + make_interval(hours => hours_end)) at time zone z.tz)
      - greatest(from_at, (g.day + make_interval(hours => hours_start)) at time zone z.tz)
    ))) / 60)::integer, 0)
  from (select coalesce(nullif(time_zone, ''), 'Asia/Almaty') as tz) z
    cross join lateral generate_series(
      (from_at at time zone z.tz)::date::timestamp,
      (to_at at time zone z.tz)::date::timestamp,
      interval '1 day') as g(day)
  where from_at < to_at
$$;

-- Since when the patient of a deal waits for an answer: the first inbound
-- message after the last answer of the clinic (null: nobody waits). An
-- automatic message is not an answer. Runs with the caller's rights.
CREATE OR REPLACE FUNCTION "private"."deal_waiting_since"("org_id" bigint, "target_deal_id" bigint) RETURNS timestamp with time zone
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
  select min(m.sent_at)
  from public.messages m
  where m.organization_id = org_id and m.deal_id = target_deal_id and m.direction = 'in'
    and m.sent_at > coalesce((
      select max(r.sent_at)
      from public.messages r
      where r.organization_id = org_id and r.deal_id = target_deal_id and r.direction = 'out'
        and (r.automessage_id is null or r.sales_id is not null)
    ), '-infinity'::timestamp with time zone)
$$;

-- Open deals whose patient waits for an answer, with the working minutes
-- waited and the clinic's limit (overdue: the limit is reached). The board
-- marks the overdue ones, the dashboard lists them.
create or replace view public.deals_waiting with (security_invoker = on) as
select
    d.id,
    d.organization_id,
    d.patient_id,
    d.pipeline_id,
    d.stage_id,
    d.sales_id,
    d.name,
    p.first_name as patient_first_name,
    p.last_name as patient_last_name,
    p.phones[1] as patient_phone,
    w.waiting_since,
    w.waiting_minutes,
    os.response_limit_minutes as limit_minutes,
    w.waiting_minutes >= os.response_limit_minutes as overdue
from public.deals d
    join public.stages s on s.id = d.stage_id and s.kind = 'open'
    join public.patients p on p.organization_id = d.organization_id and p.id = d.patient_id
    join public.organizations o on o.id = d.organization_id
    join public.organization_settings os on os.organization_id = d.organization_id and os.response_control_enabled
    cross join lateral (
        select
            ws.since as waiting_since,
            private.working_minutes(ws.since, now(), o.timezone, os.response_hours_start, os.response_hours_end) as waiting_minutes
        from (select private.deal_waiting_since(d.organization_id, d.id) as since) ws
    ) w
where d.archived_at is null and w.waiting_since is not null;

