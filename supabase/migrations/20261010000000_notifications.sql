alter table public.notification_preferences enable row level security;
alter table public.response_alerts enable row level security;

create policy "Own notifications can be read" on public.notifications for select to authenticated
    using (organization_id = (select private.current_organization_id()) and sales_id = (select private.current_sales_id()));
create policy "Own notifications can be marked read" on public.notifications for update to authenticated
    using (organization_id = (select private.current_organization_id()) and sales_id = (select private.current_sales_id()))
    with check (organization_id = (select private.current_organization_id()) and sales_id = (select private.current_sales_id()));

