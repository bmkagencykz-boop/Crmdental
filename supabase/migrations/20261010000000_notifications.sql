-- "1 сообщение", "2 сообщения", "5 сообщений"
CREATE OR REPLACE FUNCTION "private"."plural_ru"("n" integer, "one" "text", "few" "text", "many" "text") RETURNS "text"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select n || ' ' || case
    when n % 100 between 11 and 14 then many
    when n % 10 = 1 then one
    when n % 10 between 2 and 4 then few
    else many
  end
$$;

-- "Иванова Асель · Имплантация": the patient and what the deal is about
CREATE OR REPLACE FUNCTION "private"."deal_label"("deal" "public"."deals") RETURNS "text"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select concat_ws(' · ',
    coalesce(nullif(btrim(concat_ws(' ', p.last_name, p.first_name)), ''), p.phones[1], 'Пациент'),
    coalesce(nullif(btrim(deal.name), ''), sv.name))
  from (select 1) x
    left join public.patients p on p.organization_id = deal.organization_id and p.id = deal.patient_id
    left join public.services sv on sv.organization_id = deal.organization_id and sv.id = deal.service_id
$$;

-- Active owner and heads of a clinic
CREATE OR REPLACE FUNCTION "private"."clinic_managers"("org_id" bigint) RETURNS bigint[]
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select coalesce(array_agg(s.id order by s.id), '{}'::bigint[])
  from public.sales s
  where s.organization_id = org_id and s.role in ('owner', 'head') and not s.disabled
$$;

-- Who hears about the patients of a deal: its responsible; for an unassigned
-- deal the "first to answer" list (everybody when the list is empty), else
-- the owner and heads
CREATE OR REPLACE FUNCTION "private"."deal_audience"("deal" "public"."deals") RETURNS bigint[]
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  settings public.organization_settings;
  chosen bigint[];
begin
  if deal.sales_id is not null and exists (
    select 1 from public.sales s
    where s.organization_id = deal.organization_id and s.id = deal.sales_id and not s.disabled
  ) then
    return array[deal.sales_id];
  end if;
  select * into settings from public.organization_settings os where os.organization_id = deal.organization_id;
  if deal.sales_id is null and settings.lead_distribution = 'first_response' then
    select coalesce(array_agg(s.id order by s.id), '{}'::bigint[]) into chosen
    from public.sales s
    where s.organization_id = deal.organization_id and not s.disabled
      and (cardinality(settings.lead_distribution_sales_ids) = 0 or s.id = any(settings.lead_distribution_sales_ids));
    if cardinality(chosen) > 0 then
      return chosen;
    end if;
  end if;
  return private.clinic_managers(deal.organization_id);
end;
$$;

-- A notification for an active employee of the clinic (else nothing)
CREATE OR REPLACE FUNCTION "private"."add_notification"("org_id" bigint, "recipient_id" bigint, "notification_kind" "text", "notification_title" "text", "notification_body" "text", "target_deal_id" bigint DEFAULT NULL::bigint, "target_patient_id" bigint DEFAULT NULL::bigint, "target_task_id" bigint DEFAULT NULL::bigint) RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  new_id bigint;
begin
  if recipient_id is null or not exists (
    select 1 from public.sales s
    where s.organization_id = org_id and s.id = recipient_id and not s.disabled
  ) then
    return null;
  end if;
  insert into public.notifications (organization_id, sales_id, kind, title, body, deal_id, patient_id, task_id)
  values (org_id, recipient_id, notification_kind, notification_title, notification_body,
    target_deal_id, target_patient_id, target_task_id)
  returning id into new_id;
  return new_id;
end;
$$;

--
-- Triggers
--

-- lead_assigned: a deal got a responsible (on creation or later) who is not
-- the author of the change. The first answer of "first to answer takes the
-- lead" is the employee's own action too: their message is stored in the
-- same transaction as the assignment.
CREATE OR REPLACE FUNCTION "private"."handle_deal_assignment_notify"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  actor_id bigint := private.current_sales_id();
  actor_name text;
begin
  if new.sales_id is null or (tg_op = 'UPDATE' and new.sales_id is not distinct from old.sales_id)
    or current_setting('crm.notifications', true) = 'off' then
    return null;
  end if;
  if new.sales_id = actor_id then
    return null;
  end if;
  if exists (
    select 1 from public.messages m
    where m.organization_id = new.organization_id and m.deal_id = new.id
      and m.direction = 'out' and m.sales_id = new.sales_id and m.created_at = now()
  ) then
    return null;
  end if;
  select nullif(btrim(concat_ws(' ', s.first_name, s.last_name)), '') into actor_name
  from public.sales s where s.id = actor_id;
  perform private.add_notification(new.organization_id, new.sales_id, 'lead_assigned',
    case when tg_op = 'INSERT' and actor_id is null then 'Новое обращение' else 'Вам передали сделку' end,
    private.deal_label(new) || coalesce(' · от ' || actor_name, ''),
    new.id, new.patient_id, null);
  return null;
end;
$$;

-- patient_message: an inbound message tells the deal's audience. A message
-- of the same deal within 5 minutes of the last one updates the unread
-- notification (count in the title and the body) instead of adding one; a
-- new lead assigned in the same transaction already got "Новое обращение".
CREATE OR REPLACE FUNCTION "private"."handle_message_notify"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  recipient bigint;
  patient_name text;
  excerpt text;
begin
  if current_setting('crm.notifications', true) = 'off' then
    return null;
  end if;
  select d.* into deal from public.deals d
  where d.organization_id = new.organization_id and d.id = new.deal_id;
  if deal.id is null then
    return null;
  end if;
  select coalesce(nullif(btrim(concat_ws(' ', p.last_name, p.first_name)), ''), p.phones[1], 'Пациент')
  into patient_name
  from public.patients p where p.organization_id = new.organization_id and p.id = new.patient_id;
  excerpt := left(coalesce(nullif(btrim(new.text), ''), '[вложение]'), 200);

  foreach recipient in array private.deal_audience(deal) loop
    update public.notifications n
    set message_count = n.message_count + 1,
        title = 'Новые сообщения (' || (n.message_count + 1) || ')',
        body = patient_name || ', ' || private.plural_ru(n.message_count + 1, 'сообщение', 'сообщения', 'сообщений')
          || ': ' || excerpt,
        updated_at = now()
    where n.organization_id = new.organization_id and n.sales_id = recipient
      and n.kind = 'patient_message' and n.deal_id = new.deal_id
      and n.read_at is null and n.updated_at > now() - interval '5 minutes';
    if found then
      continue;
    end if;
    if exists (
      select 1 from public.notifications n
      where n.organization_id = new.organization_id and n.sales_id = recipient
        and n.kind = 'lead_assigned' and n.deal_id = new.deal_id and n.created_at = now()
    ) then
      continue;
    end if;
    perform private.add_notification(new.organization_id, recipient, 'patient_message',
      'Новое сообщение', patient_name || ': ' || excerpt, new.deal_id, new.patient_id, null);
  end loop;
  return null;
end;
$$;

-- A task whose due date moves may be notified again
CREATE OR REPLACE FUNCTION "private"."handle_task_due_changed"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.due_date is distinct from old.due_date then
    new.overdue_notified_at := null;
  end if;
  return new;
end;
$$;

--
-- Periodic job (pg_cron, every minute)
--

-- task_overdue: open tasks that passed their due date within the last day
-- (older ones are not announced, e.g. right after the deployment), once
CREATE OR REPLACE FUNCTION "private"."notify_overdue_tasks"() RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  task record;
  deal public.deals;
  notified integer := 0;
begin
  for task in
    update public.tasks t
    set overdue_notified_at = now()
    where t.done_date is null and t.overdue_notified_at is null
      and t.due_date < now() and t.due_date > now() - interval '1 day'
    returning t.organization_id, t.id, t.deal_id, t.sales_id, t.text
  loop
    select d.* into deal from public.deals d
    where d.organization_id = task.organization_id and d.id = task.deal_id;
    if private.add_notification(task.organization_id, coalesce(task.sales_id, deal.sales_id), 'task_overdue',
      'Задача просрочена',
      coalesce(nullif(btrim(task.text), ''), 'Задача') || ' · ' || private.deal_label(deal),
      task.deal_id, deal.patient_id, task.id) is not null then
      notified := notified + 1;
    end if;
  end loop;
  return notified;
end;
$$;

-- response_overdue: deals waiting longer than the limit of their clinic.
-- Level 1 (the limit) goes to the configured people, level 2 (3x the limit)
-- to the owner and heads; each level once per waiting episode.
CREATE OR REPLACE FUNCTION "private"."notify_response_overdue"() RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  item record;
  reached integer;
  new_level integer;
  recipients bigint[];
  recipient bigint;
  notified integer := 0;
begin
  for item in
    select d as deal, os as settings, w.waiting_since,
      private.working_minutes(w.waiting_since, now(), o.timezone, os.response_hours_start, os.response_hours_end) as minutes
    from public.deals d
      join public.stages s on s.id = d.stage_id and s.kind = 'open'
      join public.organizations o on o.id = d.organization_id
      join public.organization_settings os on os.organization_id = d.organization_id and os.response_control_enabled
      cross join lateral (select private.deal_waiting_since(d.organization_id, d.id) as waiting_since) w
    where d.archived_at is null
      and w.waiting_since is not null
      and w.waiting_since < now() - make_interval(mins => os.response_limit_minutes)
      and not exists (
        select 1 from public.response_alerts a
        where a.organization_id = d.organization_id and a.deal_id = d.id
          and a.waiting_since = w.waiting_since and a.level = 2
      )
  loop
    reached := case
      when item.minutes >= 3 * (item.settings).response_limit_minutes then 2
      when item.minutes >= (item.settings).response_limit_minutes then 1
      else 0
    end;
    recipients := '{}'::bigint[];
    new_level := 0;
    for level_no in 1..reached loop
      insert into public.response_alerts (organization_id, deal_id, waiting_since, level)
      values ((item.deal).organization_id, (item.deal).id, item.waiting_since, level_no)
      on conflict do nothing;
      if not found then
        continue;
      end if;
      new_level := level_no;
      if level_no = 1 then
        if (item.settings).response_alert_responsible then
          recipients := recipients || private.deal_audience(item.deal);
        end if;
        if (item.settings).response_alert_managers then
          recipients := recipients || private.clinic_managers((item.deal).organization_id);
        end if;
        recipients := recipients || (item.settings).response_alert_sales_ids;
      else
        recipients := recipients || private.clinic_managers((item.deal).organization_id);
      end if;
    end loop;
    if new_level = 0 then
      continue;
    end if;
    for recipient in select distinct r from unnest(recipients) r loop
      if private.add_notification((item.deal).organization_id, recipient, 'response_overdue',
        case when new_level = 2 then 'Пациент всё ещё ждёт ответа' else 'Пациент ждёт ответа' end,
        private.deal_label(item.deal) || ' · ждёт ' || item.minutes || ' мин',
        (item.deal).id, (item.deal).patient_id, null) is not null then
        notified := notified + 1;
      end if;
    end loop;
  end loop;
  return notified;
end;
$$;

-- Starts the edge function notifications_dispatch when a linked employee has
-- a notification to receive in Telegram. Needs the Vault secrets project_url
-- and notifications_dispatch_key (= function secret NOTIFICATIONS_DISPATCH_KEY).
CREATE OR REPLACE FUNCTION "private"."request_notifications_dispatch"() RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  project_url text;
  dispatch_key text;
begin
  if not exists (
    select 1 from public.notifications n
      join public.notification_preferences p on p.organization_id = n.organization_id and p.sales_id = n.sales_id
    where n.telegram_status is null and n.created_at > now() - interval '1 hour'
      and p.telegram_enabled and p.telegram_chat_id is not null
  ) then
    return null;
  end if;
  if to_regclass('vault.decrypted_secrets') is null then
    return null;
  end if;
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into project_url using 'project_url';
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into dispatch_key using 'notifications_dispatch_key';
  if project_url is null or dispatch_key is null then
    raise warning 'notifications: Vault secrets project_url and notifications_dispatch_key are not set';
    return null;
  end if;
  return net.http_post(
    url := rtrim(project_url, '/') || '/functions/v1/notifications_dispatch',
    body := '{}'::jsonb,
    params := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || dispatch_key
    ),
    timeout_milliseconds := 5000
  );
end;
$$;

-- The job of pg_cron: overdue tasks, overdue answers, then Telegram
CREATE OR REPLACE FUNCTION "private"."notifications_tick"() RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  tasks integer;
  answers integer;
begin
  tasks := private.notify_overdue_tasks();
  answers := private.notify_response_overdue();
  perform private.request_notifications_dispatch();
  return jsonb_build_object('task_overdue', tasks, 'response_overdue', answers);
end;
$$;

--
-- Telegram (edge functions notifications_dispatch and notify_telegram_webhook,
-- service role only)
--

-- Takes the new notifications of the employees who linked Telegram, at most
-- max_rows, with FOR UPDATE SKIP LOCKED so that two runs never take the same
-- row. A kind the employee switched off is skipped; the others are returned
-- (status sending) with the chat to send to. A run that died while sending
-- leaves failed rows after 10 minutes: better than a message sent twice.
CREATE OR REPLACE FUNCTION "public"."claim_telegram_notifications"("max_rows" integer DEFAULT 100) RETURNS TABLE("notification_id" bigint, "chat_id" "text", "notification_kind" "text", "notification_title" "text", "notification_body" "text", "notification_deal_id" bigint, "clinic_name" "text")
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  job record;
begin
  update public.notifications n
  set telegram_status = 'failed'
  where n.telegram_status = 'sending' and n.telegram_claimed_at < now() - interval '10 minutes';

  for job in
    select n.id, n.kind, n.title, n.body, n.deal_id, p.telegram_chat_id, p.kinds,
      coalesce(nullif(btrim(c.config ->> 'title'), ''), o.name) as clinic
    from public.notifications n
      join public.notification_preferences p on p.organization_id = n.organization_id and p.sales_id = n.sales_id
      join public.organizations o on o.id = n.organization_id
      left join public.configuration c on c.organization_id = n.organization_id
    where n.telegram_status is null and n.created_at > now() - interval '1 hour'
      and p.telegram_enabled and p.telegram_chat_id is not null
    order by n.id
    limit greatest(max_rows, 0)
    for update of n skip locked
  loop
    if not (job.kind = any(job.kinds)) then
      update public.notifications n set telegram_status = 'skipped' where n.id = job.id;
      continue;
    end if;
    update public.notifications n
    set telegram_status = 'sending', telegram_claimed_at = now()
    where n.id = job.id;
    notification_id := job.id;
    chat_id := job.telegram_chat_id;
    notification_kind := job.kind;
    notification_title := job.title;
    notification_body := job.body;
    notification_deal_id := job.deal_id;
    clinic_name := job.clinic;
    return next;
  end loop;
end;
$$;

-- /start <code> from the platform bot: links the chat to the employee who
-- asked for the code (valid 30 minutes, once)
CREATE OR REPLACE FUNCTION "public"."link_telegram_chat"("link_code" "text", "chat_id" "text", "chat_username" "text" DEFAULT NULL::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  linked public.notification_preferences;
begin
  if nullif(btrim(link_code), '') is null or nullif(btrim(chat_id), '') is null then
    return jsonb_build_object('linked', false);
  end if;
  update public.notification_preferences p
  set telegram_chat_id = btrim(link_telegram_chat.chat_id),
      telegram_username = nullif(btrim(chat_username), ''),
      telegram_linked_at = now(),
      telegram_enabled = true,
      telegram_link_code = null,
      telegram_link_expires_at = null,
      updated_at = now()
  where p.telegram_link_code = btrim(link_code) and p.telegram_link_expires_at > now()
  returning p.* into linked;
  if linked.sales_id is null then
    return jsonb_build_object('linked', false);
  end if;
  return (
    select jsonb_build_object('linked', true, 'first_name', s.first_name,
      'clinic', coalesce(nullif(btrim(c.config ->> 'title'), ''), o.name))
    from public.sales s
      join public.organizations o on o.id = s.organization_id
      left join public.configuration c on c.organization_id = s.organization_id
    where s.id = linked.sales_id
  );
end;
$$;

-- /stop from the platform bot, or the bot was blocked: the chat gets nothing
CREATE OR REPLACE FUNCTION "public"."unlink_telegram_chat"("chat_id" "text") RETURNS integer
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  unlinked integer;
begin
  update public.notification_preferences p
  set telegram_chat_id = null, telegram_username = null, telegram_linked_at = null, updated_at = now()
  where p.telegram_chat_id = unlink_telegram_chat.chat_id;
  get diagnostics unlinked = row_count;
  return unlinked;
end;
$$;

--
-- Employee API (the current user only)
--

-- Preferences of the current employee (the defaults when never saved)
CREATE OR REPLACE FUNCTION "public"."get_notification_preferences"() RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  me bigint := private.current_sales_id();
  prefs public.notification_preferences;
begin
  if me is null then
    raise exception 'Not an employee' using errcode = '42501';
  end if;
  select * into prefs from public.notification_preferences p where p.sales_id = me;
  return jsonb_build_object(
    'kinds', to_jsonb(coalesce(prefs.kinds, array['lead_assigned', 'patient_message', 'task_overdue', 'response_overdue'])),
    'browser_enabled', coalesce(prefs.browser_enabled, false),
    'telegram_enabled', coalesce(prefs.telegram_enabled, true),
    'telegram_linked', prefs.telegram_chat_id is not null,
    'telegram_username', prefs.telegram_username,
    'telegram_link_code', case when prefs.telegram_link_expires_at > now() then prefs.telegram_link_code end,
    'telegram_link_expires_at', case when prefs.telegram_link_expires_at > now() then prefs.telegram_link_expires_at end
  );
end;
$$;

-- Saves what the employee receives in the browser and in Telegram
CREATE OR REPLACE FUNCTION "public"."save_notification_preferences"("kinds" "text"[], "browser_enabled" boolean, "telegram_enabled" boolean) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  me bigint := private.current_sales_id();
begin
  if me is null then
    raise exception 'Not an employee' using errcode = '42501';
  end if;
  insert into public.notification_preferences (sales_id, organization_id, kinds, browser_enabled, telegram_enabled)
  values (me, private.current_organization_id(),
    array(select distinct k from unnest(coalesce(save_notification_preferences.kinds, '{}'::text[])) k order by k),
    coalesce(save_notification_preferences.browser_enabled, false),
    coalesce(save_notification_preferences.telegram_enabled, true))
  on conflict (sales_id) do update
  set kinds = excluded.kinds,
      browser_enabled = excluded.browser_enabled,
      telegram_enabled = excluded.telegram_enabled,
      updated_at = now();
  return public.get_notification_preferences();
end;
$$;

-- «Подключить Telegram»: a one-time code for t.me/<bot>?start=<code>
CREATE OR REPLACE FUNCTION "public"."create_telegram_link_code"() RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  me bigint := private.current_sales_id();
  code text := substr(replace(gen_random_uuid()::text, '-', ''), 1, 16);
begin
  if me is null then
    raise exception 'Not an employee' using errcode = '42501';
  end if;
  insert into public.notification_preferences (sales_id, organization_id, telegram_link_code, telegram_link_expires_at)
  values (me, private.current_organization_id(), code, now() + interval '30 minutes')
  on conflict (sales_id) do update
  set telegram_link_code = excluded.telegram_link_code,
      telegram_link_expires_at = excluded.telegram_link_expires_at,
      updated_at = now();
  return code;
end;
$$;

-- «Отключить Telegram»
CREATE OR REPLACE FUNCTION "public"."unlink_telegram"() RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  update public.notification_preferences p
  set telegram_chat_id = null, telegram_username = null, telegram_linked_at = null,
      telegram_link_code = null, telegram_link_expires_at = null, updated_at = now()
  where p.sales_id = private.current_sales_id();
end;
$$;

-- «Прочитать все» (RLS: only the caller's notifications)
CREATE OR REPLACE FUNCTION "public"."mark_all_notifications_read"() RETURNS integer
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  marked integer;
begin
  update public.notifications n
  set read_at = now()
  where n.sales_id = private.current_sales_id() and n.read_at is null;
  get diagnostics marked = row_count;
  return marked;
end;
$$;

