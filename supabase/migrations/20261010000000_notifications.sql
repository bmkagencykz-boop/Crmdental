-- Stage 16: employee notifications (bell, browser, Telegram) and response-time
-- control. Everything is declared in supabase/schemas/16_notifications.sql
-- (copied below); the data statements at the end are not schema.

--
-- Employee notifications and response-time control (stage 16)
--
-- Notifications are rows of public.notifications, one per recipient, created
-- by the database only:
--   lead_assigned     a deal became mine (distribution, reassignment by
--                     somebody else); never for my own action
--   patient_message   an inbound message on a deal I lead (unassigned deals:
--                     the "first to answer" list, else the owner and heads);
--                     a burst of messages of one deal updates one unread row
--   task_overdue      my task passed its due date (once per due date)
--   response_overdue  a patient waits for an answer longer than the clinic's
--                     limit (working minutes), once per waiting episode, and
--                     once more to the owner and heads at 3x the limit
-- Bulk writes (imports, migrations) can switch the triggers off for their
-- transaction: set local crm.notifications = 'off'.
-- pg_cron runs private.notifications_tick() every minute (overdue tasks and
-- answers); it starts the edge function notifications_dispatch, which sends
-- the new notifications to the employees who linked their Telegram (one
-- platform bot, NOTIFY_TELEGRAM_BOT_TOKEN). The bell and the browser
-- notifications of the app read the table.
--
-- "Waiting for an answer": the deal is open, and an inbound message came
-- after the last answer of the clinic (an outbound message by an employee or
-- from the phone; automatic messages are not answers). The wait starts at the
-- first such message and only counts the clinic's working hours
-- (organization_settings.response_hours_*, organizations.timezone). The same
-- rules in the app: providers/commons/responseTime.ts.
--

--
-- Settings of the clinic: response limit, working hours, whom to alert
--

