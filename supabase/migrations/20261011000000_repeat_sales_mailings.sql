begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('mailings-dispatch', '* * * * *', 'select private.request_mailings_dispatch()');
    perform cron.schedule('recalls-daily', '25 3 * * *', 'select private.process_recalls()');
  end if;
end;
$$;
