-- Progress of the mailings: statuses of the queue and of the sent messages
create or replace view public.mailings_summary with (security_invoker = on) as
select
    ml.id,
    ml.organization_id,
    ml.name,
    ml.segment,
    ml.template_id,
    ml.body,
    ml.scheduled_at,
    ml.status,
    ml.recipients_count,
    ml.created_by,
    ml.created_at,
    ml.finished_at,
    coalesce(q.queued, 0) as queued_count,
    coalesce(q.sent, 0) as sent_count,
    coalesce(q.delivered, 0) as delivered_count,
    coalesce(q.read, 0) as read_count,
    coalesce(q.failed, 0) as failed_count,
    coalesce(q.skipped, 0) as skipped_count,
    coalesce(q.cancelled, 0) as cancelled_count
from public.mailings ml
    left join lateral (
        select
            count(*) filter (where mm.status in ('pending', 'sending')) as queued,
            count(*) filter (where mm.status = 'sent') as sent,
            count(*) filter (where mm.status = 'sent' and coalesce(m.status, mm.delivery_status) in ('delivered', 'read')) as delivered,
            count(*) filter (where mm.status = 'sent' and coalesce(m.status, mm.delivery_status) = 'read') as read,
            count(*) filter (where mm.status = 'failed' or (mm.status = 'sent' and coalesce(m.status, mm.delivery_status) = 'error')) as failed,
            count(*) filter (where mm.status = 'skipped') as skipped,
            count(*) filter (where mm.status = 'cancelled') as cancelled
        from public.mailing_messages mm
            left join public.messages m on m.organization_id = mm.organization_id and m.id = mm.message_id
        where mm.organization_id = ml.organization_id and mm.mailing_id = ml.id
    ) q on true;

