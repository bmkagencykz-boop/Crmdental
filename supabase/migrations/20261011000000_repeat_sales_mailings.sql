-- How many mailing messages the clinic may still send at this moment:
-- nothing outside the working hours (clinic time zone), else the rest of the
-- per-minute and per-day limits (rows taken by the dispatcher count)
CREATE OR REPLACE FUNCTION "private"."mailing_allowance"("org_id" bigint, "moment" timestamp with time zone) RETURNS integer
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select case
    when (moment at time zone z.tz)::time < st.work_start or (moment at time zone z.tz)::time >= st.work_end then 0
    else greatest(0, least(
      st.per_minute - (
        select count(*) from public.mailing_messages m
        where m.organization_id = org_id and m.claimed_at > moment - interval '1 minute' and m.claimed_at <= moment),
      st.per_day - (
        select count(*) from public.mailing_messages m
        where m.organization_id = org_id
          and m.claimed_at >= (((moment at time zone z.tz)::date)::timestamp without time zone at time zone z.tz)
          and m.claimed_at <= moment)
    ))::integer
  end
  from (
    select coalesce(nullif(o.timezone, ''), 'Asia/Almaty') as tz
    from public.organizations o where o.id = org_id
  ) z
  cross join lateral (
    select coalesce(s.per_minute, 10) as per_minute, coalesce(s.per_day, 300) as per_day,
      coalesce(s.work_start, time '09:00') as work_start, coalesce(s.work_end, time '21:00') as work_end
    from (select 1) one
      left join public.mailing_settings s on s.organization_id = org_id
  ) st
$$;

-- Template variables of a patient without a deal
