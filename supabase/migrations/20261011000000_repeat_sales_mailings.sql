-- «Стоп», «STOP!», « отписаться » (whole message; any case, trailing
-- punctuation and spaces ignored). Cyrillic is lowered by translate() so
-- that the result does not depend on the database locale.
CREATE OR REPLACE FUNCTION "private"."is_opt_out_text"("value" "text") RETURNS boolean
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select lower(translate(
      regexp_replace(coalesce(value, ''), '^[[:space:][:punct:]]+|[[:space:][:punct:]]+$', '', 'g'),
      'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ',
      'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'))
    in ('стоп', 'stop', 'отписаться')
$$;

-- The system source of the recall deals (created when missing)
CREATE OR REPLACE FUNCTION "private"."repeat_source_id"("org_id" bigint) RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  found_id bigint;
begin
  select s.id into found_id from public.lead_sources s
  where s.organization_id = org_id and s.code = 'repeat';
  if found_id is null then
    insert into public.lead_sources (organization_id, name, code, is_system, position)
    values (org_id, 'Повторное обращение', 'repeat', true,
      coalesce((select max(s.position) + 1 from public.lead_sources s where s.organization_id = org_id), 0))
    returning id into found_id;
  end if;
  return found_id;
end;
$$;

-- Defaults of a clinic (new clinics through the owner trigger, existing ones
-- through the migration): the anti-ban limits and a recall rule
-- «Профгигиена»: 6 months after any won deal, a deal «Повторный визит:
-- Гигиена» on the first stage of the main pipeline (off, no message until a
-- template is chosen). The dictionaries are not touched: the source
-- «Повторное обращение» is added with the first recall deal
-- (private.repeat_source_id), the refusal reason «Не беспокоить» is
-- recognized by its name when the clinic adds it.
CREATE OR REPLACE FUNCTION "private"."seed_repeat_mailings"("org_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  default_pipeline_id bigint;
  first_stage_id bigint;
  hygiene_id bigint;
begin
  insert into public.mailing_settings (organization_id) values (org_id)
  on conflict (organization_id) do nothing;

  if exists (select 1 from public.recall_rules r where r.organization_id = org_id) then
    return;
  end if;
  select p.id into default_pipeline_id from public.pipelines p
  where p.organization_id = org_id and p.is_default;
  if default_pipeline_id is null then
    return;
  end if;
  select s.id into first_stage_id from public.stages s
  where s.pipeline_id = default_pipeline_id
  order by s.position, s.id limit 1;
  select s.id into hygiene_id from public.services s
  where s.organization_id = org_id and s.name in ('Гигиена', 'Профгигиена')
  order by s.position, s.id limit 1;

  insert into public.recall_rules (organization_id, name, service_id, delay_months, pipeline_id, stage_id,
    deal_service_id, template_id, message_mode, is_active, position)
  values (org_id, 'Профгигиена', null, 6, default_pipeline_id, first_stage_id,
    hygiene_id, null, 'confirm', false, 0);
end;
$$;

