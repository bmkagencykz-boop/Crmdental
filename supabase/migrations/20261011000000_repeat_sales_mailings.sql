--
-- Repeat sales and segment mailings (stage 17)
--
-- Repeat sales: a recall rule "a deal won (of a service) -> N months later a
-- new deal" is processed by a daily pg_cron job (private.process_recalls).
-- Every (rule, won deal) is handled once (table recalls): a new deal is
-- created, or the recall is skipped (the patient already has an open deal)
-- or cancelled (the patient opted out). The rule may also message the
-- patient: "show first" reuses the stage 6 queue (automessages row awaiting +
-- task with the «Отправить» button), "auto" goes through the mailing queue.
--
-- Mailings: the owner or the head picks a segment of patients and a text;
-- the recipients are queued in mailing_messages. The edge function
-- mailings_dispatch, started every minute by pg_cron, takes the due rows
-- (public.claim_mailing_messages) within the anti-ban limits of the clinic
-- (per minute, per day, working hours) and sends them through Wazzup24 like
-- the automatic messages, with a random pause between two messages.
--
-- Opt-out: patients.messaging_opt_out (a toggle on the patient card, set
-- automatically by an incoming «стоп» / «stop» / «отписаться», or by a
-- refusal with the reason «Не беспокоить»). Such a patient never gets
-- mailings or recall messages; service messages of open deals still work.
--

alter table public.patients add column messaging_opt_out boolean not null default false;
alter table public.patients add column messaging_opt_out_at timestamp with time zone;

-- Won deal (of service_id, or any) -> delay_months later a new deal in
