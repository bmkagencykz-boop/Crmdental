-- Due recalls between from_at (excluded) and to_at (included), of one clinic
-- (or all): the latest won deal of the patient matching an active rule,
-- delay_months after it was won, not handled yet
CREATE OR REPLACE FUNCTION "private"."recall_candidates"("org_id" bigint, "from_at" timestamp with time zone, "to_at" timestamp with time zone) RETURNS TABLE("organization_id" bigint, "rule_id" bigint, "deal_id" bigint, "patient_id" bigint, "due_at" timestamp with time zone)
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select c.organization_id, c.rule_id, c.deal_id, c.patient_id, c.due_at
  from (
    select r.organization_id, r.id as rule_id, d.id as deal_id, d.patient_id,
      d.closed_at + make_interval(months => r.delay_months) as due_at,
      row_number() over (partition by r.id, d.patient_id order by d.closed_at desc, d.id desc) as rank
    from public.recall_rules r
      join public.deals d on d.organization_id = r.organization_id
      join public.stages s on s.id = d.stage_id
    where r.is_active
      and (org_id is null or r.organization_id = org_id)
      and s.kind = 'won'
      and d.closed_at is not null
      and d.archived_at is null
      and (r.service_id is null or d.service_id = r.service_id)
  ) c
  where c.rank = 1
    and c.due_at > from_at
    and c.due_at <= to_at
    and not exists (select 1 from public.recalls x where x.rule_id = c.rule_id and x.deal_id = c.deal_id)
$$;

-- Daily job (pg_cron): recalls due in the last 30 days are handled once:
--   the patient opted out, or refused with «Не беспокоить» -> cancelled;
--   the patient has an open deal -> skipped;
--   else a deal «Повторный визит: {услуга}» with the source «Повторное
--   обращение», the responsible of the won deal, and the message of the rule.
CREATE OR REPLACE FUNCTION "private"."process_recalls"("moment" timestamp with time zone DEFAULT "now"()) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  candidate record;
  recall_rule public.recall_rules;
  won_deal public.deals;
  target public.patients;
  new_deal public.deals;
  recall_row_id bigint;
  service_name text;
  responsible bigint;
  template_body text;
  rendered text;
  am_id bigint;
  handled integer := 0;
begin
  for candidate in
    select * from private.recall_candidates(null, moment - interval '30 days', moment) c
    order by c.due_at, c.deal_id
  loop
    insert into public.recalls (organization_id, rule_id, deal_id, patient_id, due_at, status)
    values (candidate.organization_id, candidate.rule_id, candidate.deal_id, candidate.patient_id, candidate.due_at, 'created')
    on conflict (rule_id, deal_id) do nothing
    returning id into recall_row_id;
    if recall_row_id is null then
      continue;
    end if;
    handled := handled + 1;

    select * into recall_rule from public.recall_rules r where r.id = candidate.rule_id;
    select * into won_deal from public.deals d
    where d.organization_id = candidate.organization_id and d.id = candidate.deal_id;
    select * into target from public.patients p
    where p.organization_id = candidate.organization_id and p.id = candidate.patient_id;

    if target.messaging_opt_out then
      update public.recalls x set status = 'cancelled', reason = 'Пациент отказался от сообщений'
      where x.id = recall_row_id;
      continue;
    end if;
    if exists (
      select 1 from public.deals d
        join public.stages s on s.id = d.stage_id
        join public.lost_reasons lr on lr.organization_id = d.organization_id and lr.id = d.lost_reason_id
      where d.organization_id = target.organization_id and d.patient_id = target.id
        and s.kind = 'lost' and lower(btrim(lr.name)) in ('не беспокоить', 'Не беспокоить')
    ) then
      update public.recalls x set status = 'cancelled', reason = 'Отказ «Не беспокоить»'
      where x.id = recall_row_id;
      continue;
    end if;
    if exists (
      select 1 from public.deals d
        join public.stages s on s.id = d.stage_id
      where d.organization_id = target.organization_id and d.patient_id = target.id
        and s.kind = 'open' and d.archived_at is null
    ) then
      update public.recalls x set status = 'skipped', reason = 'У пациента уже есть открытая сделка'
      where x.id = recall_row_id;
      continue;
    end if;

    select sv.name into service_name from public.services sv
    where sv.organization_id = recall_rule.organization_id and sv.id = coalesce(recall_rule.deal_service_id, won_deal.service_id);
    select sl.id into responsible from public.sales sl
    where sl.organization_id = recall_rule.organization_id and not sl.disabled
      and sl.id = coalesce(won_deal.sales_id, target.sales_id);

    insert into public.deals (organization_id, patient_id, pipeline_id, stage_id, name, source_id, service_id, sales_id)
    values (recall_rule.organization_id, target.id, recall_rule.pipeline_id, recall_rule.stage_id,
      'Повторный визит: ' || coalesce(service_name, recall_rule.name),
      private.repeat_source_id(recall_rule.organization_id),
      coalesce(recall_rule.deal_service_id, won_deal.service_id),
      responsible)
    returning * into new_deal;
    update public.recalls x set recall_deal_id = new_deal.id where x.id = recall_row_id;

    -- The message of the rule, when the patient can be reached
    if recall_rule.template_id is null or (cardinality(target.phones) = 0 and not exists (
      select 1 from public.patient_chats c where c.organization_id = target.organization_id and c.patient_id = target.id
    )) then
      continue;
    end if;
    select t.body into template_body from public.message_templates t
    where t.organization_id = recall_rule.organization_id and t.id = recall_rule.template_id;
    if recall_rule.message_mode = 'confirm' then
      -- Stage 6 "show first": the task with the text and the «Отправить» button
      rendered := private.render_template(template_body, private.automessage_vars(new_deal));
      insert into public.automessages (organization_id, deal_id, rule_id, stage_id, timing, send_at, status, text, processed_at)
      values (new_deal.organization_id, new_deal.id, null, new_deal.stage_id, 'after_stage', moment, 'awaiting', rendered, moment)
      returning id into am_id;
      insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id, automessage_id)
      values (new_deal.organization_id, new_deal.id, 'message', rendered, moment, new_deal.sales_id, am_id);
    else
      insert into public.mailing_messages (organization_id, recall_id, patient_id, deal_id, body, send_at)
      values (new_deal.organization_id, recall_row_id, target.id, new_deal.id, template_body, moment);
    end if;
  end loop;
  return handled;
end;
$$;

-- Patients of a segment of the clinic, with the reason a patient is left
-- out: opted_out, no_contact (no phone and no messenger chat), duplicate
-- (same first phone as a more recently seen patient), else ok. Filters (all
-- optional, combined with AND):
--   tag_ids + tag_mode: any (default) or all of the tags;
--   service_ids: a deal of one of these services;
--   inactive_months: the last visit or won deal is older than N months;
--   source_ids, sales_ids (responsible): of the patient;
--   has_open_deal: true / false.
CREATE OR REPLACE FUNCTION "private"."mailing_segment"("org_id" bigint, "segment" "jsonb", "moment" timestamp with time zone DEFAULT "now"()) RETURNS TABLE("patient_id" bigint, "status" "text")
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  with f as (
    select
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'tag_ids') = 'array' then segment -> 'tag_ids' else '[]'::jsonb end)::bigint) as tag_ids,
      coalesce(segment ->> 'tag_mode', 'any') as tag_mode,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'service_ids') = 'array' then segment -> 'service_ids' else '[]'::jsonb end)::bigint) as service_ids,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'source_ids') = 'array' then segment -> 'source_ids' else '[]'::jsonb end)::bigint) as source_ids,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'sales_ids') = 'array' then segment -> 'sales_ids' else '[]'::jsonb end)::bigint) as sales_ids,
      nullif(segment ->> 'inactive_months', '')::integer as inactive_months,
      nullif(segment ->> 'has_open_deal', '')::boolean as has_open_deal
  ),
  matched as (
    select p.id, p.phones, p.messaging_opt_out, p.last_seen
    from public.patients p, f
    where p.organization_id = org_id
      and (cardinality(f.tag_ids) = 0
        or (f.tag_mode = 'all' and p.tags @> f.tag_ids)
        or (f.tag_mode <> 'all' and p.tags && f.tag_ids))
      and (cardinality(f.service_ids) = 0 or exists (
        select 1 from public.deals d
        where d.organization_id = p.organization_id and d.patient_id = p.id and d.service_id = any(f.service_ids)))
      and (cardinality(f.source_ids) = 0 or p.source_id = any(f.source_ids))
      and (cardinality(f.sales_ids) = 0 or p.sales_id = any(f.sales_ids))
      and (f.has_open_deal is null or f.has_open_deal = exists (
        select 1 from public.deals d join public.stages s on s.id = d.stage_id
        where d.organization_id = p.organization_id and d.patient_id = p.id
          and s.kind = 'open' and d.archived_at is null))
      and (f.inactive_months is null or (
        select greatest(max(d.visit_at), max(d.closed_at) filter (where s.kind = 'won'))
        from public.deals d join public.stages s on s.id = d.stage_id
        where d.organization_id = p.organization_id and d.patient_id = p.id
      ) < moment - make_interval(months => f.inactive_months))
  ),
  classified as (
    select m.id, m.last_seen,
      case
        when m.messaging_opt_out then 'opted_out'
        when cardinality(m.phones) = 0 and not exists (
          select 1 from public.patient_chats c where c.organization_id = org_id and c.patient_id = m.id
        ) then 'no_contact'
      end as excluded,
      coalesce(m.phones[1], 'patient:' || m.id) as contact_key
    from matched m
  )
  select c.id,
    coalesce(c.excluded,
      case when row_number() over (partition by c.excluded is null, c.contact_key order by c.last_seen desc, c.id desc) > 1
        then 'duplicate' else 'ok' end)
  from classified c
$$;

-- Live count and preview of a segment (owner and head)
CREATE OR REPLACE FUNCTION "public"."mailing_segment_preview"("segment" "jsonb", "preview_limit" integer DEFAULT 20) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  result jsonb;
begin
  if org_id is null or private.current_user_role() not in ('owner', 'head') then
    raise exception 'Рассылки доступны владельцу и руководителю' using errcode = '42501';
  end if;
  select jsonb_build_object(
    'count', count(*) filter (where s.status = 'ok'),
    'matched', count(*),
    'opted_out', count(*) filter (where s.status = 'opted_out'),
    'no_contact', count(*) filter (where s.status = 'no_contact'),
    'duplicates', count(*) filter (where s.status = 'duplicate'),
    'patients', coalesce((
      select jsonb_agg(jsonb_build_object('id', x.id, 'first_name', x.first_name, 'last_name', x.last_name, 'phone', x.phones[1])
        order by x.last_name nulls last, x.first_name, x.id)
      from (
        select p.id, p.first_name, p.last_name, p.phones
        from private.mailing_segment(org_id, segment) q
          join public.patients p on p.organization_id = org_id and p.id = q.patient_id
        where q.status = 'ok'
        order by p.last_name nulls last, p.first_name, p.id
        limit greatest(preview_limit, 0)
      ) x
    ), '[]'::jsonb)
  ) into result
  from private.mailing_segment(org_id, segment) s;
  return result;
end;
$$;

-- A new mailing queues the patients of its segment
CREATE OR REPLACE FUNCTION "private"."handle_mailing_created"() RETURNS "trigger"
