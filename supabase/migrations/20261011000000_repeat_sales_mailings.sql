-- Employees pause, resume and cancel (column grant: status); the system
-- (dispatcher) marks done. Cancelling cancels the rows still waiting.
CREATE OR REPLACE FUNCTION "private"."handle_mailing_update"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.status is distinct from old.status then
    if current_user = 'authenticated' and not (
      (old.status = 'scheduled' and new.status in ('paused', 'cancelled'))
      or (old.status = 'paused' and new.status in ('scheduled', 'cancelled'))
    ) then
      raise exception 'Эту рассылку нельзя перевести в статус «%»', new.status
        using errcode = 'check_violation', hint = 'mailing_status_locked';
    end if;
    if new.status in ('cancelled', 'done') then
      new.finished_at := now();
    end if;
    if new.status = 'cancelled' then
      perform private.cancel_mailing_messages(new.organization_id, new.id);
    end if;
  end if;
  return new;
end;
$$;

-- Opt-out switched on: the waiting mailing and recall messages are cancelled
CREATE OR REPLACE FUNCTION "private"."handle_patient_opt_out"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not new.messaging_opt_out then
    new.messaging_opt_out_at := null;
    return new;
  end if;
  if tg_op = 'UPDATE' and old.messaging_opt_out then
    return new;
  end if;
  new.messaging_opt_out_at := now();
  if tg_op = 'UPDATE' then
    update public.mailing_messages mm
    set status = 'cancelled', error = 'Пациент отказался от сообщений', processed_at = now()
    where mm.organization_id = new.organization_id and mm.patient_id = new.id and mm.status = 'pending';
    update public.automessages a
    set status = 'cancelled', error = 'Пациент отказался от сообщений', processed_at = now()
    where a.organization_id = new.organization_id and a.rule_id is null
      and a.status in ('pending', 'awaiting')
      and a.deal_id in (
        select x.recall_deal_id from public.recalls x
        where x.organization_id = new.organization_id and x.patient_id = new.id
      );
  end if;
  return new;
end;
$$;

