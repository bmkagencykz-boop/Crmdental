  where o.id = org_id
$$;

-- Dispatcher of the mailings (edge function mailings_dispatch, service role
-- only). Per clinic with Wazzup24 connected: at most per_run rows and what
-- the limits allow (private.mailing_allowance); rows of paused or cancelled
-- mailings wait. Opted-out patients and patients without a phone or a chat
-- are skipped; a recall message whose deal is closed is cancelled. The text
-- is rendered now; a mailing message is attached to the latest open deal,
-- else the latest deal, else none (the patient's chat only). Mailings with
-- nothing left are marked done.
CREATE OR REPLACE FUNCTION "public"."claim_mailing_messages"("per_run" integer DEFAULT 4) RETURNS TABLE("id" bigint, "organization_id" bigint, "patient_id" bigint, "deal_id" bigint, "message_text" "text")
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  clinic bigint;
  allowance integer;
  taken integer;
  job public.mailing_messages;
  target_deal public.deals;
  rendered text;
begin
  -- A run that died while sending: rather a failed row than a message sent twice
  update public.mailing_messages mm
  set status = 'failed', error = 'Отправка прервалась, проверьте переписку', processed_at = now()
  where mm.status = 'sending' and mm.claimed_at < now() - interval '10 minutes';

  for clinic in
    select distinct mm.organization_id from public.mailing_messages mm
    where mm.status = 'pending' and mm.send_at <= now()
    order by mm.organization_id
  loop
    if not exists (
      select 1 from public.messenger_integrations i
      where i.organization_id = clinic and i.api_key is not null
    ) then
      continue;
    end if;
    allowance := least(per_run, private.mailing_allowance(clinic, now()));
    taken := 0;
    if allowance <= 0 then
      continue;
    end if;

    for job in
      select mm.* from public.mailing_messages mm
        left join public.mailings ml on ml.organization_id = mm.organization_id and ml.id = mm.mailing_id
      where mm.organization_id = clinic and mm.status = 'pending' and mm.send_at <= now()
        and (mm.mailing_id is null or ml.status = 'scheduled')
      order by mm.send_at, mm.id
      limit 500
      for update of mm skip locked
    loop
      exit when taken >= allowance;

      if exists (
        select 1 from public.patients p
        where p.organization_id = clinic and p.id = job.patient_id and p.messaging_opt_out
      ) then
        update public.mailing_messages mm
        set status = 'skipped', error = 'Пациент отказался от сообщений', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;
      if not exists (
        select 1 from public.patients p
        where p.organization_id = clinic and p.id = job.patient_id and cardinality(p.phones) > 0
      ) and not exists (
        select 1 from public.patient_chats c
        where c.organization_id = clinic and c.patient_id = job.patient_id
      ) then
        update public.mailing_messages mm
        set status = 'skipped', error = 'Нет телефона или чата', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;

      if job.recall_id is not null then
        select d.* into target_deal from public.deals d
          join public.stages s on s.id = d.stage_id
        where d.organization_id = clinic and d.id = job.deal_id
          and s.kind = 'open' and d.archived_at is null;
        if target_deal.id is null then
          update public.mailing_messages mm
          set status = 'cancelled', error = 'Сделка повторной продажи уже закрыта', processed_at = now()
          where mm.id = job.id;
          continue;
        end if;
      else
        select d.* into target_deal from public.deals d
          join public.stages s on s.id = d.stage_id
        where d.organization_id = clinic and d.patient_id = job.patient_id
          and s.kind = 'open' and d.archived_at is null
        order by d.updated_at desc, d.id desc
        limit 1;
        if target_deal.id is null then
          select d.* into target_deal from public.deals d
          where d.organization_id = clinic and d.patient_id = job.patient_id
          order by d.updated_at desc, d.id desc
          limit 1;
        end if;
      end if;

      rendered := private.render_template(job.body,
        case when target_deal.id is not null
          then private.automessage_vars(target_deal)
          else private.mailing_patient_vars(clinic, job.patient_id)
        end);
      if coalesce(rendered, '') = '' then
        update public.mailing_messages mm
        set status = 'failed', error = 'Пустой текст сообщения', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;

      update public.mailing_messages mm
      set status = 'sending', text = rendered, claimed_at = now(), deal_id = target_deal.id
      where mm.id = job.id;
      taken := taken + 1;
      id := job.id;
      organization_id := clinic;
      patient_id := job.patient_id;
      deal_id := target_deal.id;
      message_text := rendered;
      return next;
    end loop;
  end loop;

  update public.mailings ml
  set status = 'done'
  where ml.status = 'scheduled' and ml.scheduled_at <= now()
    and not exists (
      select 1 from public.mailing_messages mm
      where mm.organization_id = ml.organization_id and mm.mailing_id = ml.id
        and mm.status in ('pending', 'sending')
    );
end;
$$;

-- Delivery status of a mailing message sent without a deal (nothing stored
-- in messages): called by wazzup_webhook when update_message_status found
-- no message
CREATE OR REPLACE FUNCTION "public"."update_mailing_message_status"("webhook_token" "text", "external_id" "text", "status" "text", "error" "text" DEFAULT NULL::"text") RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint;
begin
  select i.organization_id into org_id
  from public.messenger_integrations i
  where i.webhook_token = update_mailing_message_status.webhook_token;
  if org_id is null then
    raise exception 'Unknown webhook token' using errcode = '28000';
  end if;
  if update_mailing_message_status.status not in ('sent', 'delivered', 'read', 'error') then
    return false;
  end if;
  update public.mailing_messages mm
  set delivery_status = update_mailing_message_status.status,
      error = case when update_mailing_message_status.status = 'error' then update_mailing_message_status.error else mm.error end
  where mm.organization_id = org_id
    and mm.external_id = update_mailing_message_status.external_id
    and mm.message_id is null;
  return found;
end;
$$;

-- Repeat sales screen (owner and head): recalls due in the next 30 days,
-- recalls handled in the period (created_at), and how many recall deals
-- were won
CREATE OR REPLACE FUNCTION "public"."report_recalls"("period_from" timestamp with time zone DEFAULT NULL::timestamp with time zone, "period_to" timestamp with time zone DEFAULT NULL::timestamp with time zone) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  upcoming jsonb;
  handled jsonb;
  totals jsonb;
begin
  if org_id is null or private.current_user_role() not in ('owner', 'head') then
    raise exception 'Отчёты доступны владельцу и руководителю' using errcode = '42501';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'rule_id', c.rule_id, 'rule_name', r.name, 'deal_id', c.deal_id, 'deal_name', d.name,
      'patient_id', c.patient_id, 'patient_name', btrim(concat_ws(' ', p.last_name, p.first_name)),
      'due_at', c.due_at, 'opted_out', p.messaging_opt_out)
    order by c.due_at, c.deal_id), '[]'::jsonb)
  into upcoming
  from private.recall_candidates(org_id, now(), now() + interval '30 days') c
    join public.recall_rules r on r.id = c.rule_id
    join public.deals d on d.organization_id = c.organization_id and d.id = c.deal_id
    join public.patients p on p.organization_id = c.organization_id and p.id = c.patient_id;

  with period as (
    select x.*, s.kind as recall_kind
    from public.recalls x
      left join public.deals rd on rd.organization_id = x.organization_id and rd.id = x.recall_deal_id
      left join public.stages s on s.id = rd.stage_id
    where x.organization_id = org_id
      and (period_from is null or x.created_at >= period_from)
      and (period_to is null or x.created_at < period_to)
  )
  select jsonb_build_object(
      'created', count(*) filter (where status = 'created'),
      'skipped', count(*) filter (where status = 'skipped'),
      'cancelled', count(*) filter (where status = 'cancelled'),
      'open', count(*) filter (where status = 'created' and recall_kind = 'open'),
      'won', count(*) filter (where status = 'created' and recall_kind = 'won'),
      'lost', count(*) filter (where status = 'created' and recall_kind = 'lost'),
      'upcoming', jsonb_array_length(upcoming))
  into totals
  from period;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', x.id, 'rule_name', r.name, 'patient_id', x.patient_id,
      'patient_name', btrim(concat_ws(' ', p.last_name, p.first_name)),
      'due_at', x.due_at, 'created_at', x.created_at, 'status', x.status, 'reason', x.reason,
      'recall_deal_id', x.recall_deal_id, 'recall_deal_name', rd.name, 'recall_deal_kind', s.kind)
    order by x.created_at desc, x.id desc), '[]'::jsonb)
  into handled
  from (
    select * from public.recalls y
    where y.organization_id = org_id
      and (period_from is null or y.created_at >= period_from)
      and (period_to is null or y.created_at < period_to)
    order by y.created_at desc, y.id desc
    limit 200
  ) x
    left join public.recall_rules r on r.organization_id = x.organization_id and r.id = x.rule_id
    left join public.patients p on p.organization_id = x.organization_id and p.id = x.patient_id
    left join public.deals rd on rd.organization_id = x.organization_id and rd.id = x.recall_deal_id
    left join public.stages s on s.id = rd.stage_id;

  return jsonb_build_object('upcoming', upcoming, 'recalls', handled, 'totals', totals);
end;
$$;

-- Called every minute by pg_cron: starts the edge function mailings_dispatch
-- when something is due. Same Vault secrets as the automatic messages:
-- project_url and automessages_dispatch_key.
CREATE OR REPLACE FUNCTION "private"."request_mailings_dispatch"() RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  project_url text;
  dispatch_key text;
begin
  if not exists (
    select 1 from public.mailing_messages mm
    where (mm.status = 'pending' and mm.send_at <= now())
      or (mm.status = 'sending' and mm.claimed_at < now() - interval '10 minutes')
  ) then
    return null;
  end if;
  if to_regclass('vault.decrypted_secrets') is null then
    return null;
  end if;
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into project_url using 'project_url';
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into dispatch_key using 'automessages_dispatch_key';
  if project_url is null or dispatch_key is null then
    raise warning 'mailings: Vault secrets project_url and automessages_dispatch_key are not set';
    return null;
  end if;
  return net.http_post(
    url := rtrim(project_url, '/') || '/functions/v1/mailings_dispatch',
    body := '{}'::jsonb,
    params := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || dispatch_key
    ),
    timeout_milliseconds := 5000
  );
end;
$$;

