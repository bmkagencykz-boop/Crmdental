-- 11_import_mis.sql: the import fills the custom fields
CREATE OR REPLACE FUNCTION "private"."import_row"("org_id" bigint, "import_kind" "text", "item" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  source_system text := coalesce(nullif(btrim(item ->> 'system'), ''), 'excel');
  p jsonb := coalesce(item -> 'patient', '{}'::jsonb);
  d jsonb := item -> 'deal';
  numbers text[];
  patient_ext text := nullif(btrim(p ->> 'external_id'), '');
  patient_row public.patients;
  saved_patient public.patients;
  patient_outcome text;
  deal_ext text;
  deal_name text;
  deal_row public.deals;
  saved_deal public.deals;
  deal_outcome text;
  target_stage public.stages;
  current_kind text;
  reason_id bigint;
  created timestamp with time zone;
  paid bigint;
  new_tags bigint[];
begin
  numbers := array(
    select distinct n
    from (
      select private.normalize_phone(x) as n
      from jsonb_array_elements_text(coalesce(p -> 'phones', '[]'::jsonb)) as x
    ) as normalized
    where n is not null
    order by n
  );
  if cardinality(numbers) = 0 and patient_ext is null
    and coalesce(nullif(btrim(p ->> 'first_name'), ''), nullif(btrim(p ->> 'last_name'), '')) is null then
    raise exception 'Нет ни имени, ни телефона пациента' using errcode = 'check_violation';
  end if;

  -- The patient: by the id in the source system, then by phone, then (no
  -- phone at all) by full name and birth date
  if patient_ext is not null then
    select pt.* into patient_row
    from public.external_refs r
      join public.patients pt on pt.organization_id = r.organization_id and pt.id = r.entity_id
    where r.organization_id = org_id and r.system = source_system
      and r.entity = 'patient' and r.external_id = patient_ext;
  end if;
  if patient_row.id is null and cardinality(numbers) > 0 then
    select pt.* into patient_row
    from public.patients pt
    where pt.organization_id = org_id and pt.phones && numbers
    order by pt.id
    limit 1;
  end if;
  if patient_row.id is null and cardinality(numbers) = 0 then
    select pt.* into patient_row
    from public.patients pt
    where pt.organization_id = org_id and pt.phones = '{}'::text[]
      and lower(coalesce(pt.last_name, '')) = lower(coalesce(nullif(btrim(p ->> 'last_name'), ''), ''))
      and lower(coalesce(pt.first_name, '')) = lower(coalesce(nullif(btrim(p ->> 'first_name'), ''), ''))
      and lower(coalesce(pt.middle_name, '')) = lower(coalesce(nullif(btrim(p ->> 'middle_name'), ''), ''))
      and pt.birth_date is not distinct from (p ->> 'birth_date')::date
    order by pt.id
    limit 1;
  end if;

  new_tags := array(select t::bigint from jsonb_array_elements_text(coalesce(p -> 'tags', '[]'::jsonb)) as t);
  if patient_row.id is null then
    created := coalesce((p ->> 'created_at')::timestamp with time zone, now());
    insert into public.patients (
      organization_id, first_name, last_name, middle_name, phone_jsonb, birth_date,
      city, source_id, sales_id, tags, background, first_seen, last_seen, custom_values
    )
    values (
      org_id,
      nullif(btrim(p ->> 'first_name'), ''),
      nullif(btrim(p ->> 'last_name'), ''),
      nullif(btrim(p ->> 'middle_name'), ''),
      coalesce((select jsonb_agg(jsonb_build_object('number', n, 'type', 'Mobile')) from unnest(numbers) as n), '[]'::jsonb),
      (p ->> 'birth_date')::date,
      nullif(btrim(p ->> 'city'), ''),
      (p ->> 'source_id')::bigint,
      (p ->> 'sales_id')::bigint,
      new_tags,
      nullif(btrim(p ->> 'background'), ''),
      created,
      created,
      case when jsonb_typeof(p -> 'custom_values') = 'object' then p -> 'custom_values' else '{}'::jsonb end
    )
    returning * into saved_patient;
    patient_outcome := 'created';
  else
    -- Fill what is missing, never overwrite what the clinic already has
    update public.patients pt
    set first_name = coalesce(pt.first_name, nullif(btrim(p ->> 'first_name'), '')),
        last_name = coalesce(pt.last_name, nullif(btrim(p ->> 'last_name'), '')),
        middle_name = coalesce(pt.middle_name, nullif(btrim(p ->> 'middle_name'), '')),
        phone_jsonb = pt.phone_jsonb || coalesce((
          select jsonb_agg(jsonb_build_object('number', n, 'type', 'Mobile'))
          from unnest(numbers) as n
          where not n = any(pt.phones)
        ), '[]'::jsonb),
        birth_date = coalesce(pt.birth_date, (p ->> 'birth_date')::date),
        city = coalesce(pt.city, nullif(btrim(p ->> 'city'), '')),
        source_id = coalesce(pt.source_id, (p ->> 'source_id')::bigint),
        sales_id = coalesce(pt.sales_id, (p ->> 'sales_id')::bigint),
        tags = pt.tags || array(select t from unnest(new_tags) as t where not t = any(pt.tags)),
        background = coalesce(nullif(pt.background, ''), nullif(btrim(p ->> 'background'), '')),
        custom_values = case
          when jsonb_typeof(p -> 'custom_values') = 'object' then (p -> 'custom_values') || pt.custom_values
          else pt.custom_values
        end
    where pt.organization_id = org_id and pt.id = patient_row.id
    returning * into saved_patient;
    patient_outcome := case
      when to_jsonb(saved_patient) is distinct from to_jsonb(patient_row) then 'updated'
      else 'skipped'
    end;
  end if;
  if patient_ext is not null then
    insert into public.external_refs (organization_id, entity, entity_id, system, external_id)
    values (org_id, 'patient', saved_patient.id, source_system, patient_ext)
    on conflict (organization_id, system, entity, external_id)
    do update set entity_id = excluded.entity_id;
  end if;

  if import_kind <> 'deals' or d is null or jsonb_typeof(d) <> 'object' then
    return jsonb_build_object('patient', patient_outcome, 'patient_id', saved_patient.id);
  end if;

  -- The deal: by the id in the source system, else by patient and name
  deal_ext := nullif(btrim(d ->> 'external_id'), '');
  deal_name := coalesce(nullif(btrim(d ->> 'name'), ''), 'Обращение');
  if deal_ext is not null then
    select dl.* into deal_row
    from public.external_refs r
      join public.deals dl on dl.organization_id = r.organization_id and dl.id = r.entity_id
    where r.organization_id = org_id and r.system = source_system
      and r.entity = 'deal' and r.external_id = deal_ext;
  else
    select dl.* into deal_row
    from public.deals dl
    where dl.organization_id = org_id and dl.patient_id = saved_patient.id
      and lower(btrim(coalesce(dl.name, ''))) = lower(deal_name)
    order by dl.id
    limit 1;
  end if;

  if (d ->> 'stage_id') is not null then
    select s.* into target_stage
    from public.stages s
    where s.organization_id = org_id and s.id = (d ->> 'stage_id')::bigint;
    if target_stage.id is null then
      raise exception 'Этап не найден' using errcode = 'foreign_key_violation';
    end if;
  end if;
  -- A refused deal needs a reason: the file's, else "Другое", else the first one
  reason_id := (d ->> 'lost_reason_id')::bigint;
  if target_stage.kind = 'lost' and reason_id is null then
    select lr.id into reason_id
    from public.lost_reasons lr
    where lr.organization_id = org_id
    order by lr.name = 'Другое' desc, lr.position, lr.id
    limit 1;
  end if;
  new_tags := array(select t::bigint from jsonb_array_elements_text(coalesce(d -> 'tags', '[]'::jsonb)) as t);
  paid := coalesce(round((d ->> 'paid_amount')::numeric), 0)::bigint;
  created := (d ->> 'created_at')::timestamp with time zone;

  if deal_row.id is null then
    insert into public.deals (
      organization_id, patient_id, pipeline_id, stage_id, name, source_id, service_id,
      plan_amount, sales_id, lost_reason_id, tags, description, created_at, custom_values
    )
    values (
      org_id,
      saved_patient.id,
      target_stage.pipeline_id,
      target_stage.id,
      deal_name,
      (d ->> 'source_id')::bigint,
      (d ->> 'service_id')::bigint,
      coalesce(round((d ->> 'plan_amount')::numeric), 0)::bigint,
      (d ->> 'sales_id')::bigint,
      reason_id,
      new_tags,
      nullif(btrim(d ->> 'description'), ''),
      coalesce(created, now()),
      case when jsonb_typeof(d -> 'custom_values') = 'object' then d -> 'custom_values' else '{}'::jsonb end
    )
    returning * into saved_deal;
    -- The dates of the file, not of the import
    if created is not null then
      update public.deals dl
      set stage_changed_at = created,
          closed_at = case when dl.closed_at is not null then created end
      where dl.organization_id = org_id and dl.id = saved_deal.id;
    end if;
    deal_outcome := 'created';
  else
    select s.kind into current_kind from public.stages s where s.id = deal_row.stage_id;
    update public.deals dl
    set plan_amount = coalesce(round((d ->> 'plan_amount')::numeric)::bigint, dl.plan_amount),
        source_id = coalesce(dl.source_id, (d ->> 'source_id')::bigint),
        service_id = coalesce(dl.service_id, (d ->> 'service_id')::bigint),
        sales_id = coalesce(dl.sales_id, (d ->> 'sales_id')::bigint),
        tags = dl.tags || array(select t from unnest(new_tags) as t where not t = any(dl.tags)),
        description = coalesce(nullif(dl.description, ''), nullif(btrim(d ->> 'description'), '')),
        -- Custom fields: what the deal does not have yet
        custom_values = case
          when jsonb_typeof(d -> 'custom_values') = 'object' then (d -> 'custom_values') || dl.custom_values
          else dl.custom_values
        end,
        -- The stage of the file, within the same pipeline; a refusal stays
        stage_id = case
          when target_stage.id is not null and target_stage.pipeline_id = dl.pipeline_id
            and current_kind <> 'lost' then target_stage.id
          else dl.stage_id
        end,
        lost_reason_id = case
          when target_stage.kind = 'lost' and target_stage.pipeline_id = dl.pipeline_id
            and current_kind <> 'lost' then coalesce(dl.lost_reason_id, reason_id)
          else dl.lost_reason_id
        end
    where dl.organization_id = org_id and dl.id = deal_row.id
    returning * into saved_deal;
    deal_outcome := case
      when (to_jsonb(saved_deal) - 'updated_at') is distinct from (to_jsonb(deal_row) - 'updated_at') then 'updated'
      else 'skipped'
    end;
  end if;

  -- "Paid" of the file: a payment for what the deal does not have yet
  if paid > saved_deal.paid_amount then
    insert into public.deal_payments (organization_id, deal_id, amount, paid_at, comment)
    values (org_id, saved_deal.id, paid - saved_deal.paid_amount,
      coalesce(created, now())::date, 'Импорт');
    if deal_outcome = 'skipped' then
      deal_outcome := 'updated';
    end if;
  end if;

  if deal_ext is not null then
    insert into public.external_refs (organization_id, entity, entity_id, system, external_id)
    values (org_id, 'deal', saved_deal.id, source_system, deal_ext)
    on conflict (organization_id, system, entity, external_id)
    do update set entity_id = excluded.entity_id;
  end if;

  return jsonb_build_object(
    'patient', patient_outcome, 'patient_id', saved_patient.id,
    'deal', deal_outcome, 'deal_id', saved_deal.id
  );
end;
$$;
