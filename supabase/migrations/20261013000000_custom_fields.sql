-- 02_functions.sql: the deal log records the custom fields
CREATE OR REPLACE FUNCTION "public"."handle_deal_after_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  tracked text[] := array[
    'name', 'patient_id', 'pipeline_id', 'sales_id', 'source_id', 'service_id',
    'plan_amount', 'paid_amount', 'lost_reason_id', 'lost_comment',
    'appointment_at', 'visit_at', 'tags', 'archived_at',
    'doctor_id', 'consultation_amount'
  ];
  field text;
  old_json jsonb;
  new_json jsonb;
  changes jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.deal_events (organization_id, deal_id, type, to_stage_id, sales_id)
    values (new.organization_id, new.id, 'created', new.stage_id, private.current_sales_id());

    if new.source_id is not null then
      update public.patients
      set source_id = new.source_id
      where organization_id = new.organization_id
        and id = new.patient_id
        and source_id is null;
    end if;
    if new.sales_id is not null then
      update public.patients
      set sales_id = new.sales_id
      where organization_id = new.organization_id
        and id = new.patient_id
        and sales_id is null;
    end if;
    perform private.create_rule_tasks(new, 'deal_created', null);
    perform private.create_rule_tasks(new, 'stage_entered', new.stage_id);
    return null;
  end if;

  -- A responsible assigned later (first answer, by hand) takes the
  -- unassigned open tasks of the deal
  if new.sales_id is not null and old.sales_id is null then
    update public.tasks
    set sales_id = new.sales_id
    where organization_id = new.organization_id and deal_id = new.id
      and sales_id is null and done_date is null;
    update public.patients
    set sales_id = new.sales_id
    where organization_id = new.organization_id
      and id = new.patient_id
      and sales_id is null;
  end if;
  if new.stage_id is distinct from old.stage_id then
    perform private.create_rule_tasks(new, 'stage_entered', new.stage_id);
  end if;

  old_json := to_jsonb(old);
  new_json := to_jsonb(new);
  foreach field in array tracked loop
    if old_json -> field is distinct from new_json -> field then
      changes := changes || jsonb_build_object(field, jsonb_build_array(old_json -> field, new_json -> field));
    end if;
  end loop;
  -- Custom fields (19_custom_fields.sql): one entry per field, "cf:<id>"
  changes := changes || private.custom_values_diff(old_json -> 'custom_values', new_json -> 'custom_values');

  if new.stage_id is distinct from old.stage_id then
    insert into public.deal_events (organization_id, deal_id, type, from_stage_id, to_stage_id, changes, sales_id)
    values (new.organization_id, new.id, 'stage_changed', old.stage_id, new.stage_id, changes, private.current_sales_id());
  elsif changes <> '{}'::jsonb then
    insert into public.deal_events (organization_id, deal_id, type, changes, sales_id)
    values (new.organization_id, new.id, 'updated', changes, private.current_sales_id());
  end if;
  return null;
end;
$$;

-- 15_audit.sql: one line per custom field in the audit log
CREATE OR REPLACE FUNCTION "private"."audit_diff"("old_row" "jsonb", "new_row" "jsonb", "fields" "text"[]) RETURNS "jsonb"
    LANGUAGE "plpgsql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
declare
  field text;
  before jsonb;
  after jsonb;
  changes jsonb := '{}'::jsonb;
begin
  foreach field in array fields loop
    -- Custom fields (19_custom_fields.sql): one entry per field, "cf:<id>"
    if field = 'custom_values' then
      changes := changes || private.custom_values_diff(old_row -> field, new_row -> field);
      continue;
    end if;
    before := nullif(old_row -> field, 'null'::jsonb);
    after := nullif(new_row -> field, 'null'::jsonb);
    if old_row is null and after = '[]'::jsonb then
      after := null;
    end if;
    if new_row is null and before = '[]'::jsonb then
      before := null;
    end if;
    if before is distinct from after then
      changes := changes || jsonb_build_object(field, jsonb_build_array(before, after));
    end if;
  end loop;
  return changes;
end;
$$;

CREATE OR REPLACE FUNCTION "private"."audit_deal_event"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  diff jsonb := coalesce(new.changes, '{}'::jsonb);
  event_action text;
  actor record;
begin
  select * into deal from public.deals d
  where d.organization_id = new.organization_id and d.id = new.deal_id;

  if new.type = 'created' then
    event_action := 'create';
    diff := private.audit_diff(null, to_jsonb(deal),
      array['name', 'pipeline_id', 'stage_id', 'sales_id', 'source_id', 'service_id', 'plan_amount', 'custom_values']);
    if diff -> 'plan_amount' ->> 1 = '0' then
      diff := diff - 'plan_amount';
    end if;
  elsif new.type = 'stage_changed' then
    event_action := 'stage_change';
    diff := jsonb_build_object('stage_id', jsonb_build_array(new.from_stage_id, new.to_stage_id)) || diff;
  elsif diff ? 'archived_at' then
    event_action := case when diff -> 'archived_at' ->> 1 is null then 'unarchive' else 'archive' end;
  else
    event_action := 'update';
  end if;

  select * into actor from private.audit_actor(new.organization_id);
  actor.actor_id := coalesce(new.sales_id, actor.actor_id);
  -- The deal changed by another trigger (payments total, first answer)
  if pg_trigger_depth() > 2 then
    actor.actor_id := null;
    actor.actor_source := 'automation';
  elsif new.sales_id is not null and actor.actor_source in ('system', 'webhook') then
    actor.actor_source := 'user';
  end if;

  insert into public.audit_log (organization_id, at, sales_id, source, entity, entity_id, action, changes, deal_id, patient_id)
  values (new.organization_id, new.created_at, actor.actor_id, actor.actor_source, 'deal', new.deal_id,
    event_action, diff, new.deal_id, deal.patient_id);
  return null;
end;
$$;

