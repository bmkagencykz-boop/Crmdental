--
-- Custom fields (stage 19): «Дополнительные поля» of deals and patients, as
-- in amoCRM.
--
-- public.custom_fields holds the definitions of a clinic, per entity (deal or
-- patient): name, type, options of the lists, required flag, order, active
-- flag, and for the deals whether the kanban card shows the field (two at
-- most). The owner and the head edit them (Settings → Поля), every employee
-- reads them. An archived field (is_active = false) is hidden, its values
-- stay. Name, entity and type identify a field for the templates
-- ({поле:Название}), the import and the CSV export: the name is unique in the
-- entity, the type and the entity never change.
--
-- The values live in deals.custom_values and patients.custom_values, a jsonb
-- object keyed by the field id: { "12": "Инстаграм", "15": true }.
--   text, textarea, phone, url, select, date ("YYYY-MM-DD"),
--   datetime (ISO, UTC)       → a string
--   number, money (tenge)     → a number (money: a whole number ≥ 0)
--   checkbox                  → true / false
--   multiselect               → an array of options, in the order of the list
-- An empty value is no key. The trigger private.handle_custom_values
-- normalizes the values that changed (private.custom_value), drops the keys of
-- unknown fields, keeps the values of archived fields as they were, and checks
-- the required fields. Same rules in the app: customFields/customFields.ts.
--
-- Required fields are checked when an employee saves (not the webhooks, the
-- automations, nor the import):
--   * a deal outside the first stage of its pipeline (like amoCRM, a new lead
--     can come in empty) and not refused — when it is created there, moves to
--     another stage or its custom fields change;
--   * a patient — when its custom fields change (the quick creation of a
--     patient from a deal and the incoming requests are not blocked).
-- A required checkbox must be ticked.
--
-- deals_summary and patients_summary are declared here: they show the values,
-- and the columns are added by this file. The functions of earlier files that
-- read the values (deal log, audit diff, template variables, import) are
-- plpgsql, whose bodies are resolved when they run.
--

create table public.custom_fields (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    entity text not null,
    name text not null,
    type text not null,
    options jsonb not null default '[]'::jsonb,
    required boolean not null default false,
    position integer not null default 0,
    is_active boolean not null default true,
    show_on_card boolean not null default false,
    created_at timestamp with time zone not null default now(),
    constraint custom_fields_entity_check check (entity in ('deal', 'patient')),
    constraint custom_fields_type_check check (type in (
        'text', 'textarea', 'number', 'money', 'date', 'datetime',
        'checkbox', 'select', 'multiselect', 'phone', 'url'
    )),
    constraint custom_fields_name_not_blank check (btrim(name) <> ''),
    -- {поле:Название} of the templates
    constraint custom_fields_name_no_braces check (name !~ '[{}]'),
    constraint custom_fields_options_array check (jsonb_typeof(options) = 'array'),
    constraint custom_fields_card_deal_only check (not show_on_card or entity = 'deal')
);

alter table public.custom_fields add constraint custom_fields_organization_id_id_key unique (organization_id, id);

alter table public.custom_fields
    add constraint custom_fields_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade;

create index custom_fields_organization_id_idx on public.custom_fields using btree (organization_id, entity, position);
create unique index custom_fields_name_key on public.custom_fields using btree (organization_id, entity, lower(name));

-- The values, keyed by field id
alter table public.deals add column custom_values jsonb not null default '{}'::jsonb;
alter table public.deals add constraint deals_custom_values_object check (jsonb_typeof(custom_values) = 'object');
alter table public.patients add column custom_values jsonb not null default '{}'::jsonb;
alter table public.patients add constraint patients_custom_values_object check (jsonb_typeof(custom_values) = 'object');

-- Filters of the lists: custom_values @> '{"12": "Инстаграм"}'
create index deals_custom_values_idx on public.deals using gin (custom_values jsonb_path_ops);
create index patients_custom_values_idx on public.patients using gin (custom_values jsonb_path_ops);

