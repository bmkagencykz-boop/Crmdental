-- Clinic filters for everybody, personal ones for their author only; the
-- owner and the head manage the clinic filters
create policy "Employees read clinic filters and their own" on public.saved_filters for select to authenticated
    using (organization_id = (select private.current_organization_id()) and (sales_id is null or sales_id = (select private.current_sales_id())));
create policy "Own or clinic filters by role can be inserted" on public.saved_filters for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and ((sales_id is null and (select private.current_user_role()) in ('owner', 'head')) or sales_id = (select private.current_sales_id())));
create policy "Own or clinic filters by role can be updated" on public.saved_filters for update to authenticated
    using (organization_id = (select private.current_organization_id()) and ((sales_id is null and (select private.current_user_role()) in ('owner', 'head')) or sales_id = (select private.current_sales_id())))
    with check (organization_id = (select private.current_organization_id()) and ((sales_id is null and (select private.current_user_role()) in ('owner', 'head')) or sales_id = (select private.current_sales_id())));
create policy "Own or clinic filters by role can be deleted" on public.saved_filters for delete to authenticated
    using (organization_id = (select private.current_organization_id()) and ((sales_id is null and (select private.current_user_role()) in ('owner', 'head')) or sales_id = (select private.current_sales_id())));

-- The plan is for the owner and the head, like the reports
create policy "Owner and head can read" on public.sales_plans for select to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));
create policy "Owner and head can insert" on public.sales_plans for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));
