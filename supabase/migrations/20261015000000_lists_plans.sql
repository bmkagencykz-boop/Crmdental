-- Deals with what the board and the lists display
create or replace view public.deals_summary with (security_invoker = on) as
select
    d.id,
    d.organization_id,
    d.patient_id,
    d.pipeline_id,
    d.stage_id,
    d.name,
    d.source_id,
    d.service_id,
    d.plan_amount,
    d.paid_amount,
    d.sales_id,
    d.lost_reason_id,
    d.lost_comment,
    d.appointment_at,
    d.visit_at,
    d.tags,
    d.description,
    d.index,
    d.created_at,
    d.updated_at,
    d.stage_changed_at,
    d.closed_at,
    d.first_response_at,
    d.archived_at,
    s.kind as stage_kind,
    p.first_name as patient_first_name,
    p.last_name as patient_last_name,
    p.phones[1] as patient_phone,
    lower(concat_ws(' ', d.name, p.last_name, p.first_name, p.middle_name, array_to_string(p.phones, ' '))) as search_text,
    (
        select count(*)
        from public.tasks t
        where t.organization_id = d.organization_id and t.deal_id = d.id and t.done_date is null
    ) as nb_open_tasks,
    (
        select min(t.due_date)
        from public.tasks t
        where t.organization_id = d.organization_id and t.deal_id = d.id and t.done_date is null
    ) as next_task_due_at,
    (
        select count(*)
        from public.messages m
        where m.organization_id = d.organization_id and m.deal_id = d.id and m.direction = 'in' and m.read_at is null
    ) as nb_unread_messages,
    (
        select max(m.sent_at)
        from public.messages m
        where m.organization_id = d.organization_id and m.deal_id = d.id
    ) as last_message_at,
    (
        select m.text
        from public.messages m
        where m.organization_id = d.organization_id and m.deal_id = d.id
        order by m.sent_at desc, m.id desc
        limit 1
    ) as last_message_text,
    d.doctor_id,
    dr.name as doctor_name,
    d.consultation_amount,
    (
        select coalesce(sum(pay.amount), 0)::bigint
        from public.deal_payments pay
        where pay.organization_id = d.organization_id and pay.deal_id = d.id and pay.kind = 'prepayment'
    ) as prepayment_amount,
    d.unsorted_at,
    d.custom_values,
    -- Deal list (stage 21): the latest change or message, the nearest open task
    greatest(d.updated_at, (
        select max(m.sent_at)
        from public.messages m
        where m.organization_id = d.organization_id and m.deal_id = d.id
    )) as last_activity_at,
    (
        select t.text
        from public.tasks t
        where t.organization_id = d.organization_id and t.deal_id = d.id and t.done_date is null
        order by t.due_date, t.id
        limit 1
    ) as next_task_text
from public.deals d
    join public.stages s on s.id = d.stage_id
    join public.patients p on p.organization_id = d.organization_id and p.id = d.patient_id
    left join public.doctors dr on dr.organization_id = d.organization_id and dr.id = d.doctor_id;

-- Patients of a segment of the clinic, with the reason a patient is left
-- out: opted_out, no_contact (no phone and no messenger chat), duplicate
-- (same first phone as a more recently seen patient), else ok. Filters (all
-- optional, combined with AND):
--   tag_ids + tag_mode: any (default) or all of the tags;
--   service_ids: a deal of one of these services;
--   inactive_months: the last visit or won deal is older than N months;
--   source_ids, sales_ids (responsible): of the patient;
--   has_open_deal: true / false;
--   deal_ids: the patients of these deals (bulk action on the deal list;
--     an empty list matches nobody).
CREATE OR REPLACE FUNCTION "private"."mailing_segment"("org_id" bigint, "segment" "jsonb", "moment" timestamp with time zone DEFAULT "now"()) RETURNS TABLE("patient_id" bigint, "status" "text")
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  with f as (
    select
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'tag_ids') = 'array' then segment -> 'tag_ids' else '[]'::jsonb end)::bigint) as tag_ids,
      coalesce(segment ->> 'tag_mode', 'any') as tag_mode,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'service_ids') = 'array' then segment -> 'service_ids' else '[]'::jsonb end)::bigint) as service_ids,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'source_ids') = 'array' then segment -> 'source_ids' else '[]'::jsonb end)::bigint) as source_ids,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'sales_ids') = 'array' then segment -> 'sales_ids' else '[]'::jsonb end)::bigint) as sales_ids,
      nullif(segment ->> 'inactive_months', '')::integer as inactive_months,
      nullif(segment ->> 'has_open_deal', '')::boolean as has_open_deal,
      segment ? 'deal_ids' as by_deals,
      array(select jsonb_array_elements_text(case when jsonb_typeof(segment -> 'deal_ids') = 'array' then segment -> 'deal_ids' else '[]'::jsonb end)::bigint) as deal_ids
  ),
  matched as (
    select p.id, p.phones, p.messaging_opt_out, p.last_seen
    from public.patients p, f
    where p.organization_id = org_id
      and (cardinality(f.tag_ids) = 0
        or (f.tag_mode = 'all' and p.tags @> f.tag_ids)
        or (f.tag_mode <> 'all' and p.tags && f.tag_ids))
      and (cardinality(f.service_ids) = 0 or exists (
        select 1 from public.deals d
        where d.organization_id = p.organization_id and d.patient_id = p.id and d.service_id = any(f.service_ids)))
      and (cardinality(f.source_ids) = 0 or p.source_id = any(f.source_ids))
      and (cardinality(f.sales_ids) = 0 or p.sales_id = any(f.sales_ids))
      and (not f.by_deals or exists (
        select 1 from public.deals d
        where d.organization_id = p.organization_id and d.patient_id = p.id and d.id = any(f.deal_ids)))
      and (f.has_open_deal is null or f.has_open_deal = exists (
        select 1 from public.deals d join public.stages s on s.id = d.stage_id
        where d.organization_id = p.organization_id and d.patient_id = p.id
          and s.kind = 'open' and d.archived_at is null))
      and (f.inactive_months is null or (
        select greatest(max(d.visit_at), max(d.closed_at) filter (where s.kind = 'won'))
        from public.deals d join public.stages s on s.id = d.stage_id
        where d.organization_id = p.organization_id and d.patient_id = p.id
      ) < moment - make_interval(months => f.inactive_months))
  ),
  classified as (
    select m.id, m.last_seen,
      case
        when m.messaging_opt_out then 'opted_out'
        when cardinality(m.phones) = 0 and not exists (
          select 1 from public.patient_chats c where c.organization_id = org_id and c.patient_id = m.id
        ) then 'no_contact'
      end as excluded,
      coalesce(m.phones[1], 'patient:' || m.id) as contact_key
    from matched m
  )
  select c.id,
    coalesce(c.excluded,
      case when row_number() over (partition by c.excluded is null, c.contact_key order by c.last_seen desc, c.id desc) > 1
        then 'duplicate' else 'ok' end)
  from classified c
$$;


-- A new mailing queues the patients of its segment. A mailing to chosen
-- deals (segment deal_ids) attaches each message to the patient's deal among
-- them (the latest updated one when a patient has several).
CREATE OR REPLACE FUNCTION "private"."handle_mailing_created"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  queued integer;
begin
  insert into public.mailing_messages (organization_id, mailing_id, patient_id, deal_id, body, send_at)
  select new.organization_id, new.id, s.patient_id,
    case when new.segment ? 'deal_ids' then (
      select d.id from public.deals d
      where d.organization_id = new.organization_id and d.patient_id = s.patient_id
        and d.id in (select jsonb_array_elements_text(new.segment -> 'deal_ids')::bigint)
      order by d.updated_at desc, d.id desc
      limit 1
    ) end,
    new.body, new.scheduled_at
  from private.mailing_segment(new.organization_id, new.segment) s
  where s.status = 'ok'
  order by s.patient_id;
  get diagnostics queued = row_count;
  update public.mailings ml set recipients_count = queued where ml.id = new.id;
  return null;
end;
$$;


-- Dispatcher of the mailings (edge function mailings_dispatch, service role
-- only). Per clinic with Wazzup24 connected: at most per_run rows and what
-- the limits allow (private.mailing_allowance); rows of paused or cancelled
-- mailings wait. Opted-out patients and patients without a phone or a chat
-- are skipped; a recall message whose deal is closed is cancelled. The text
-- is rendered now; a mailing message is attached to its deal when it was
-- queued for one (mailing to chosen deals), else to the latest open deal,
-- else the latest deal, else none (the patient's chat only). Mailings with
-- nothing left are marked done.
CREATE OR REPLACE FUNCTION "public"."claim_mailing_messages"("per_run" integer DEFAULT 4) RETURNS TABLE("id" bigint, "organization_id" bigint, "patient_id" bigint, "deal_id" bigint, "message_text" "text")
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  clinic bigint;
  allowance integer;
  taken integer;
  job public.mailing_messages;
  target_deal public.deals;
  rendered text;
begin
  -- A run that died while sending: rather a failed row than a message sent twice
  update public.mailing_messages mm
  set status = 'failed', error = 'Отправка прервалась, проверьте переписку', processed_at = now()
  where mm.status = 'sending' and mm.claimed_at < now() - interval '10 minutes';

  for clinic in
    select distinct mm.organization_id from public.mailing_messages mm
    where mm.status = 'pending' and mm.send_at <= now()
    order by mm.organization_id
  loop
    if not exists (
      select 1 from public.messenger_integrations i
      where i.organization_id = clinic and i.api_key is not null
    ) then
      continue;
    end if;
    allowance := least(per_run, private.mailing_allowance(clinic, now()));
    taken := 0;
    if allowance <= 0 then
      continue;
    end if;

    for job in
      select mm.* from public.mailing_messages mm
        left join public.mailings ml on ml.organization_id = mm.organization_id and ml.id = mm.mailing_id
      where mm.organization_id = clinic and mm.status = 'pending' and mm.send_at <= now()
        and (mm.mailing_id is null or ml.status = 'scheduled')
      order by mm.send_at, mm.id
      limit 500
      for update of mm skip locked
    loop
      exit when taken >= allowance;

      if exists (
        select 1 from public.patients p
        where p.organization_id = clinic and p.id = job.patient_id and p.messaging_opt_out
      ) then
        update public.mailing_messages mm
        set status = 'skipped', error = 'Пациент отказался от сообщений', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;
      if not exists (
        select 1 from public.patients p
        where p.organization_id = clinic and p.id = job.patient_id and cardinality(p.phones) > 0
      ) and not exists (
        select 1 from public.patient_chats c
        where c.organization_id = clinic and c.patient_id = job.patient_id
      ) then
        update public.mailing_messages mm
        set status = 'skipped', error = 'Нет телефона или чата', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;

      if job.recall_id is not null then
        select d.* into target_deal from public.deals d
          join public.stages s on s.id = d.stage_id
        where d.organization_id = clinic and d.id = job.deal_id
          and s.kind = 'open' and d.archived_at is null;
        if target_deal.id is null then
          update public.mailing_messages mm
          set status = 'cancelled', error = 'Сделка повторной продажи уже закрыта', processed_at = now()
          where mm.id = job.id;
          continue;
        end if;
      else
        target_deal := null;
        if job.deal_id is not null then
          select d.* into target_deal from public.deals d
          where d.organization_id = clinic and d.id = job.deal_id;
        end if;
        if target_deal.id is null then
          select d.* into target_deal from public.deals d
            join public.stages s on s.id = d.stage_id
          where d.organization_id = clinic and d.patient_id = job.patient_id
            and s.kind = 'open' and d.archived_at is null
          order by d.updated_at desc, d.id desc
          limit 1;
        end if;
        if target_deal.id is null then
          select d.* into target_deal from public.deals d
          where d.organization_id = clinic and d.patient_id = job.patient_id
          order by d.updated_at desc, d.id desc
          limit 1;
        end if;
      end if;

      rendered := private.render_template(job.body,
        case when target_deal.id is not null
          then private.automessage_vars(target_deal)
          else private.mailing_patient_vars(clinic, job.patient_id)
        end);
      if coalesce(rendered, '') = '' then
        update public.mailing_messages mm
        set status = 'failed', error = 'Пустой текст сообщения', processed_at = now()
        where mm.id = job.id;
        continue;
      end if;

      update public.mailing_messages mm
      set status = 'sending', text = rendered, claimed_at = now(), deal_id = target_deal.id
      where mm.id = job.id;
      taken := taken + 1;
      id := job.id;
      organization_id := clinic;
      patient_id := job.patient_id;
      deal_id := target_deal.id;
      message_text := rendered;
      return next;
    end loop;
  end loop;

  update public.mailings ml
  set status = 'done'
  where ml.status = 'scheduled' and ml.scheduled_at <= now()
    and not exists (
      select 1 from public.mailing_messages mm
      where mm.organization_id = ml.organization_id and mm.mailing_id = ml.id
        and mm.status in ('pending', 'sending')
    );
end;
$$;

