-- Configuration rights: owner, head and integrator
CREATE OR REPLACE FUNCTION "private"."can_configure"() RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return coalesce(private.current_user_role() in ('owner', 'head', 'integrator'), false);
end;
$$;

-- Message texts: every employee, an integrator only with «доступ к переписке»
CREATE OR REPLACE FUNCTION "private"."can_read_messages"() RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return coalesce((
    select s.role <> 'integrator' or s.can_read_messages
    from public.sales s
    where s.user_id = auth.uid() and not s.disabled
      and (s.access_expires_at is null or s.access_expires_at > now())
  ), false);
end;
$$;

-- The owner sets the access of an integrator: until when (null: no limit)
-- and whether the conversations are visible
CREATE OR REPLACE FUNCTION "public"."set_integrator_access"("target_sales_id" bigint, "expires_at" timestamp with time zone, "read_messages" boolean) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
begin
  if org_id is null or private.current_user_role() is distinct from 'owner' then
    raise exception 'Доступ интегратора настраивает владелец клиники' using errcode = '42501';
  end if;
  update public.sales s
  set access_expires_at = expires_at, can_read_messages = coalesce(read_messages, false)
  where s.organization_id = org_id and s.id = target_sales_id and s.role = 'integrator';
  if not found then
    raise exception 'Интегратор не найден' using errcode = 'P0002';
  end if;
end;
$$;

-- Scopes of an API key: its own, or those of a stage 20 key
CREATE OR REPLACE FUNCTION "private"."api_key_scopes"("key_row" "public"."api_keys") RETURNS "text"[]
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case
    when cardinality(key_row.scopes) > 0 then key_row.scopes
    when key_row.scope = 'write' then array['deals:read', 'deals:write', 'patients:read', 'patients:write', 'settings:read']
    else array['deals:read', 'patients:read', 'settings:read']
  end
$$;

-- The clinic of an API key that has the scope (see private.api_authenticate:
-- 401, 429). 403 read_only_key for a write with a read key of stage 20,
-- 403 insufficient_scope otherwise.
CREATE OR REPLACE FUNCTION "private"."api_authorize"("api_key" "text", "need_scope" "text") RETURNS "public"."api_keys"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  key_row public.api_keys := private.api_authenticate(api_key, false);
begin
  if need_scope = any(private.api_key_scopes(key_row)) then
    return key_row;
  end if;
  if cardinality(key_row.scopes) = 0 and key_row.scope = 'read' then
    raise exception 'Ключ только для чтения' using errcode = 'PT403', hint = 'read_only_key';
  end if;
  raise exception 'У ключа нет доступа %', need_scope using errcode = 'PT403', hint = 'insufficient_scope';
end;
$$;

-- Normalizes an app before it is saved; its scopes and webhook only change
-- while it is not installed (the key and the webhook were made from them)
CREATE OR REPLACE FUNCTION "private"."handle_developer_app_saved"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.slug := lower(btrim(new.slug));
  new.name := btrim(new.name);
  new.developer_name := btrim(new.developer_name);
  new.description := nullif(btrim(coalesce(new.description, '')), '');
  new.developer_contact := nullif(btrim(coalesce(new.developer_contact, '')), '');
  new.website_url := nullif(btrim(coalesce(new.website_url, '')), '');
  new.settings_url := nullif(btrim(coalesce(new.settings_url, '')), '');
  new.webhook_url := nullif(btrim(coalesce(new.webhook_url, '')), '');
  new.scopes := coalesce((select array_agg(distinct s order by s) from unnest(new.scopes) as s), '{}'::text[]);
  new.webhook_events := coalesce((select array_agg(distinct e order by e) from unnest(new.webhook_events) as e), '{}'::text[]);
  if tg_op = 'UPDATE' and old.installed_at is not null and new.installed_at is not null
    and (new.scopes is distinct from old.scopes or new.webhook_url is distinct from old.webhook_url
      or new.webhook_events is distinct from old.webhook_events or new.slug is distinct from old.slug) then
    raise exception 'Отключите приложение, чтобы изменить доступы или вебхук'
      using errcode = 'check_violation', hint = 'app_installed';
  end if;
  return new;
end;
$$;

-- A deleted app takes its webhooks (foreign key); its key is revoked
CREATE OR REPLACE FUNCTION "private"."handle_developer_app_deleted"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  update public.api_keys k
  set revoked_at = now()
  where k.organization_id = old.organization_id and k.app_id = old.id and k.revoked_at is null;
  return old;
end;
$$;

-- Installs an app (owner, head, integrator): an API key with the scopes of
-- the app and, with the scope 'webhooks', its webhook. Returns the key and
-- the webhook secret, once.
CREATE OR REPLACE FUNCTION "public"."install_developer_app"("target_app_id" bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  app public.developer_apps;
  new_key text := 'dcrm_' || replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  key_row public.api_keys;
  hook public.webhooks;
begin
  if org_id is null or not private.can_configure() then
    raise exception 'Приложения устанавливает владелец, руководитель или интегратор' using errcode = '42501';
  end if;
  select * into app from public.developer_apps a
  where a.organization_id = org_id and a.id = target_app_id
  for update;
  if not found then
    raise exception 'Приложение не найдено' using errcode = 'P0002';
  end if;
  if app.installed_at is not null then
    raise exception 'Приложение уже установлено' using errcode = 'check_violation', hint = 'app_installed';
  end if;

  insert into public.api_keys (organization_id, name, prefix, key_hash, scope, scopes, app_id, created_by)
  values (org_id, left('Приложение «' || app.name || '»', 200), left(new_key, 12), private.api_key_hash(new_key),
    case when exists (select 1 from unnest(app.scopes) as s where s like '%:write' or s in ('tasks', 'webhooks'))
      then 'write' else 'read' end,
    app.scopes, app.id, private.current_sales_id())
  returning * into key_row;

  if 'webhooks' = any(app.scopes) and app.webhook_url is not null and cardinality(app.webhook_events) > 0 then
    insert into public.webhooks (organization_id, name, url, events, app_id)
    values (org_id, left(app.name, 200), app.webhook_url, app.webhook_events, app.id)
    returning * into hook;
  end if;

  update public.developer_apps a
  set installed_at = now(), installed_by = private.current_sales_id(), api_key_id = key_row.id, uninstalled_at = null
  where a.id = app.id;

  return jsonb_build_object('app_id', app.id, 'key', new_key, 'key_prefix', key_row.prefix,
    'scopes', to_jsonb(key_row.scopes), 'webhook_id', hook.id, 'webhook_secret', hook.secret);
end;
$$;

-- Uninstalls an app: its key is revoked, its webhooks deleted
CREATE OR REPLACE FUNCTION "public"."uninstall_developer_app"("target_app_id" bigint) RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
begin
  if org_id is null or not private.can_configure() then
    raise exception 'Приложения отключает владелец, руководитель или интегратор' using errcode = '42501';
  end if;
  update public.developer_apps a
  set installed_at = null, api_key_id = null, uninstalled_at = now()
  where a.organization_id = org_id and a.id = target_app_id and a.installed_at is not null;
  if not found then
    return false;
  end if;
  update public.api_keys k
  set revoked_at = now()
  where k.organization_id = org_id and k.app_id = target_app_id and k.revoked_at is null;
  delete from public.webhooks w
  where w.organization_id = org_id and w.app_id = target_app_id;
  return true;
end;
$$;

-- An app from its manifest (JSON exported in another clinic): created, or
-- updated while it is not installed. Returns its id; installing is a
-- separate step (the scopes are shown to the user first).
--   { "manifest_version": 1, "id": "roistat-analytics", "name": "...",
--     "description": "...", "developer": { "name", "contact", "website" },
--     "settings_url": "https://...", "scopes": ["deals:read", ...],
--     "webhook": { "url": "https://...", "events": ["deal.created", ...] } }
CREATE OR REPLACE FUNCTION "public"."import_app_manifest"("manifest" "jsonb") RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  saved_id bigint;
  app_scopes text[];
  app_events text[];
begin
  if org_id is null or not private.can_configure() then
    raise exception 'Приложения добавляет владелец, руководитель или интегратор' using errcode = '42501';
  end if;
  if manifest is null or jsonb_typeof(manifest) <> 'object' then
    raise exception 'Манифест: ожидается JSON-объект' using errcode = '22023';
  end if;
  if coalesce(manifest ->> 'manifest_version', '1') <> '1' then
    raise exception 'Манифест: неизвестная версия %', manifest ->> 'manifest_version' using errcode = '22023';
  end if;
  if jsonb_typeof(manifest -> 'scopes') is distinct from 'array' then
    raise exception 'Манифест: scopes — массив доступов' using errcode = '22023';
  end if;
  if manifest ? 'webhook' and jsonb_typeof(manifest -> 'webhook') not in ('object', 'null') then
    raise exception 'Манифест: webhook — объект { url, events }' using errcode = '22023';
  end if;
  select coalesce(array_agg(x), '{}'::text[]) into app_scopes from jsonb_array_elements_text(manifest -> 'scopes') as x;
  select coalesce(array_agg(x), '{}'::text[]) into app_events
  from jsonb_array_elements_text(case when jsonb_typeof(manifest #> '{webhook,events}') = 'array'
    then manifest #> '{webhook,events}' else '[]'::jsonb end) as x;

  insert into public.developer_apps as a (organization_id, slug, name, description, developer_name, developer_contact,
    website_url, settings_url, scopes, webhook_url, webhook_events, created_by)
  values (org_id, coalesce(manifest ->> 'id', ''), coalesce(manifest ->> 'name', ''), manifest ->> 'description',
    coalesce(manifest #>> '{developer,name}', ''), manifest #>> '{developer,contact}', manifest #>> '{developer,website}',
    manifest ->> 'settings_url', app_scopes, manifest #>> '{webhook,url}', app_events, private.current_sales_id())
  on conflict (organization_id, slug) do update
    set name = excluded.name, description = excluded.description, developer_name = excluded.developer_name,
        developer_contact = excluded.developer_contact, website_url = excluded.website_url,
        settings_url = excluded.settings_url, scopes = excluded.scopes, webhook_url = excluded.webhook_url,
        webhook_events = excluded.webhook_events
    where a.installed_at is null
  returning a.id into saved_id;
  if saved_id is null then
    raise exception 'Приложение «%» уже установлено: отключите его, чтобы обновить', manifest ->> 'name'
      using errcode = 'check_violation', hint = 'app_installed';
  end if;
  return saved_id;
end;
$$;

