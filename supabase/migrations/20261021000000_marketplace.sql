$$;

CREATE OR REPLACE FUNCTION "public"."api_add_deal_note"("api_key" "text", "deal_id" bigint, "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'deals:write')).organization_id;
  note_text text := nullif(btrim(coalesce(body ->> 'text', '')), '');
  note public.deal_notes;
begin
  if note_text is null then
    raise exception 'Укажите text' using errcode = '22023';
  end if;
  if not exists (select 1 from public.deals d where d.organization_id = org_id and d.id = api_add_deal_note.deal_id) then
    raise exception 'Сделка не найдена' using errcode = 'PT404', hint = 'not_found';
  end if;
  insert into public.deal_notes (organization_id, deal_id, type, text, sales_id)
  values (org_id, api_add_deal_note.deal_id, 'api', left(note_text, 10000), null)
  returning * into note;
  return jsonb_build_object('data', jsonb_build_object('id', note.id, 'deal_id', note.deal_id, 'text', note.text, 'date', note.date));
end;
$$;

CREATE OR REPLACE FUNCTION "public"."api_list_pipelines"("api_key" "text") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'settings:read')).organization_id;
begin
  return jsonb_build_object('data', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', p.id, 'name', p.name, 'is_default', p.is_default, 'position', p.position,
      'stages', coalesce((
        select jsonb_agg(jsonb_build_object('id', s.id, 'name', s.name, 'position', s.position,
          'kind', s.kind, 'color', s.color) order by s.position, s.id)
        from public.stages s where s.pipeline_id = p.id
      ), '[]'::jsonb)) order by p.position, p.id)
    from public.pipelines p
    where p.organization_id = org_id
  ), '[]'::jsonb));
end;
$$;
