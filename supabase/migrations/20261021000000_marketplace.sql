  new_stage_id := (body ->> 'stage_id')::bigint;
  if new_stage_id is not null and new_pipeline_id is null then
    select s.pipeline_id into new_pipeline_id from public.stages s
    where s.organization_id = org_id and s.id = new_stage_id;
    if new_pipeline_id is null then
      raise exception 'Этап не найден' using errcode = '23503';
    end if;
  end if;

  insert into public.deals (organization_id, patient_id, pipeline_id, stage_id, name, source_id, service_id,
    doctor_id, sales_id, plan_amount, consultation_amount, appointment_at, visit_at, description, tags)
  values (org_id, new_patient_id, new_pipeline_id, new_stage_id,
    nullif(btrim(body ->> 'name'), ''),
    (body ->> 'source_id')::bigint,
    (body ->> 'service_id')::bigint,
    (body ->> 'doctor_id')::bigint,
    (body ->> 'sales_id')::bigint,
    coalesce((body ->> 'plan_amount')::bigint, 0),
    (body ->> 'consultation_amount')::bigint,
    (body ->> 'appointment_at')::timestamp with time zone,
    (body ->> 'visit_at')::timestamp with time zone,
    body ->> 'description',
    private.api_tag_ids(org_id, body -> 'tags'))
  returning * into new_deal;

  -- The row after the triggers (distribution, automations)
  select * into new_deal from public.deals d where d.organization_id = org_id and d.id = new_deal.id;
  return jsonb_build_object('data', private.deal_json(new_deal), 'created_patient', created_patient);
end;
$$;

