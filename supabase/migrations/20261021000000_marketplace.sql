CREATE OR REPLACE FUNCTION "public"."api_list_deals"("api_key" "text", "params" "jsonb" DEFAULT '{}'::"jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'deals:read')).organization_id;
  page_number integer := (private.api_page(params)).page;
  page_size integer := (private.api_page(params)).per_page;
  f_pipeline bigint := (params ->> 'pipeline_id')::bigint;
  f_stage bigint := (params ->> 'stage_id')::bigint;
  f_patient bigint := (params ->> 'patient_id')::bigint;
  f_updated timestamp with time zone := (params ->> 'updated_since')::timestamp with time zone;
  total bigint;
  items jsonb;
begin
  select count(*) into total
  from public.deals d
  where d.organization_id = org_id
    and (f_pipeline is null or d.pipeline_id = f_pipeline)
    and (f_stage is null or d.stage_id = f_stage)
    and (f_patient is null or d.patient_id = f_patient)
    and (f_updated is null or d.updated_at >= f_updated);
  select coalesce(jsonb_agg(private.deal_json(p.d) order by (p.d).updated_at, (p.d).id), '[]'::jsonb) into items
  from (
    select d from public.deals d
    where d.organization_id = org_id
      and (f_pipeline is null or d.pipeline_id = f_pipeline)
      and (f_stage is null or d.stage_id = f_stage)
      and (f_patient is null or d.patient_id = f_patient)
      and (f_updated is null or d.updated_at >= f_updated)
    order by d.updated_at, d.id
    limit page_size offset (page_number - 1) * page_size
  ) p;
  return jsonb_build_object('data', items,
    'meta', jsonb_build_object('page', page_number, 'per_page', page_size, 'total', total));
end;
$$;

