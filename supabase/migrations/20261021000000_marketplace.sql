CREATE OR REPLACE FUNCTION "public"."api_create_deal"("api_key" "text", "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'deals:write')).organization_id;
  new_patient_id bigint;
  new_pipeline_id bigint;
  new_stage_id bigint;
  new_deal public.deals;
  created_patient boolean := false;
  found_patient jsonb;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  new_patient_id := (body ->> 'patient_id')::bigint;
  if new_patient_id is null and body ? 'patient' then
    found_patient := private.api_find_or_create_patient(org_id, body -> 'patient');
    new_patient_id := (found_patient ->> 'patient_id')::bigint;
    created_patient := (found_patient ->> 'created')::boolean;
  end if;
  if new_patient_id is null then
    raise exception 'Укажите patient_id или patient' using errcode = '22023';
  end if;
  if not exists (select 1 from public.patients p where p.organization_id = org_id and p.id = new_patient_id) then
    raise exception 'Пациент не найден' using errcode = 'PT404', hint = 'not_found';
