-- A pipeline with its stages
CREATE OR REPLACE FUNCTION "private"."api_pipeline_json"("org_id" bigint, "target_pipeline_id" bigint) RETURNS "jsonb"
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
  select jsonb_build_object(
    'id', p.id, 'name', p.name, 'is_default', p.is_default, 'position', p.position,
    'stages', coalesce((
      select jsonb_agg(jsonb_build_object('id', s.id, 'pipeline_id', s.pipeline_id, 'name', s.name,
        'position', s.position, 'kind', s.kind, 'color', s.color, 'script', s.script) order by s.position, s.id)
      from public.stages s where s.organization_id = org_id and s.pipeline_id = p.id
    ), '[]'::jsonb))
  from public.pipelines p
  where p.organization_id = org_id and p.id = target_pipeline_id
$$;

-- GET /api/account: the clinic, its users and its pipelines
CREATE OR REPLACE FUNCTION "public"."api_get_account"("api_key" "text") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'settings:read')).organization_id;
begin
  return jsonb_build_object('data', (
    select jsonb_build_object(
      'id', o.id, 'name', o.name, 'timezone', o.timezone, 'currency', o.currency,
      'users', coalesce((
        select jsonb_agg(jsonb_build_object('id', s.id, 'first_name', s.first_name, 'last_name', s.last_name,
          'email', s.email, 'role', s.role, 'disabled', s.disabled) order by s.id)
        from public.sales s where s.organization_id = org_id
      ), '[]'::jsonb),
      'pipelines', coalesce((
        select jsonb_agg(private.api_pipeline_json(org_id, p.id) order by p.position, p.id)
        from public.pipelines p where p.organization_id = org_id
      ), '[]'::jsonb))
    from public.organizations o where o.id = org_id));
end;
$$;

-- POST /api/pipelines { name, stages?: [{ name, kind, color }] }: without
-- stages, «Новый лид», «Успешно», «Отказ» (as in the settings)
CREATE OR REPLACE FUNCTION "public"."api_create_pipeline"("api_key" "text", "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'pipelines:write')).organization_id;
  new_id bigint;
  item jsonb;
  item_position integer := 0;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  if nullif(btrim(coalesce(body ->> 'name', '')), '') is null then
    raise exception 'Укажите name' using errcode = '22023';
  end if;
  if body ? 'stages' and jsonb_typeof(body -> 'stages') <> 'array' then
    raise exception 'stages: ожидается массив этапов' using errcode = '22023';
  end if;
  insert into public.pipelines (organization_id, name, position)
  values (org_id, btrim(body ->> 'name'),
    coalesce((select max(p.position) + 1 from public.pipelines p where p.organization_id = org_id), 0))
  returning id into new_id;
  if jsonb_array_length(coalesce(body -> 'stages', '[]'::jsonb)) = 0 then
    insert into public.stages (organization_id, pipeline_id, name, position, kind, color)
    values
      (org_id, new_id, 'Новый лид', 0, 'open', '#83A2DB'),
      (org_id, new_id, 'Успешно', 1, 'won', '#8CC9A7'),
      (org_id, new_id, 'Отказ', 2, 'lost', '#FD8E8C');
  else
    for item in select * from jsonb_array_elements(body -> 'stages') loop
      insert into public.stages (organization_id, pipeline_id, name, position, kind, color)
      values (org_id, new_id, btrim(coalesce(item ->> 'name', '')), item_position, coalesce(item ->> 'kind', 'open'),
        coalesce(nullif(item ->> 'color', ''), '#83A2DB'));
      item_position := item_position + 1;
    end loop;
  end if;
  return jsonb_build_object('data', private.api_pipeline_json(org_id, new_id));
end;
$$;

-- PATCH /api/pipelines/:id { name, position, is_default }
CREATE OR REPLACE FUNCTION "public"."api_update_pipeline"("api_key" "text", "pipeline_id" bigint, "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'pipelines:write')).organization_id;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  if not exists (select 1 from public.pipelines p where p.organization_id = org_id and p.id = api_update_pipeline.pipeline_id) then
    raise exception 'Воронка не найдена' using errcode = 'PT404', hint = 'not_found';
  end if;
  if (body ->> 'is_default')::boolean then
    update public.pipelines p set is_default = false
    where p.organization_id = org_id and p.is_default and p.id <> api_update_pipeline.pipeline_id;
  end if;
  update public.pipelines p
  set name = case when body ? 'name' then btrim(coalesce(body ->> 'name', '')) else p.name end,
