--
-- Integrations marketplace, developer apps, fine API scopes and integrator
-- access (stage 25)
--
-- Developer apps («Приложения разработчиков»): an integrator (agency) or the
-- owner / head registers an app in the clinic — name, developer, links,
-- the scopes it needs and the webhook events it wants. Installing it
-- (public.install_developer_app) creates an API key bound to the app with
-- exactly these scopes (public.api_keys.app_id) and, with the scope
-- 'webhooks', a webhook subscription (public.webhooks.app_id). Uninstalling
-- revokes the key and deletes the webhooks. A manifest (JSON) carries the
-- same definition to other clinics (public.import_app_manifest).
--
-- Fine API scopes: api_keys.scopes lists them; a key without scopes is a key
-- of stage 20 and keeps its rights (read: deals:read, patients:read,
-- settings:read; write: plus deals:write and patients:write). Every public
-- api_* function asks private.api_authorize for the scope it needs.
--
-- Integrator (sales.role = 'integrator'): a technical account of an agency.
-- It configures the clinic (pipelines, stages, digital pipeline, automations,
-- auto-messages, quick replies, custom fields, integrations, API) and only
-- reads deals and patients; no money (payments, reports, plans), no staff,
-- no deleting. Message texts are hidden unless the owner turns on
-- sales.can_read_messages. After sales.access_expires_at the account
-- behaves as disabled (private.current_organization_id() and the other
-- helpers of 01_tables.sql return null). Rights are granted here, in one
-- place: permissive policies "Integrator can ..." next to the owner and head
-- ones for the configuration tables, restrictive policies "Integrators
-- cannot ..." / "Integrators do not see ..." on the operational tables.
--

--
-- Tables
--

-- Integrator access: until when, and whether the conversations are visible
