-- POST /api/stages { pipeline_id, name, kind, color, position, script }:
-- without position, the stage goes before the won and lost stages
CREATE OR REPLACE FUNCTION "public"."api_create_stage"("api_key" "text", "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'pipelines:write')).organization_id;
  target_pipeline bigint := (body ->> 'pipeline_id')::bigint;
  new_position integer;
  new_stage public.stages;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  if target_pipeline is null or not exists (
    select 1 from public.pipelines p where p.organization_id = org_id and p.id = target_pipeline
  ) then
    raise exception 'Воронка не найдена' using errcode = '23503';
  end if;
  new_position := coalesce((body ->> 'position')::integer, (
    select min(s.position) from public.stages s
    where s.organization_id = org_id and s.pipeline_id = target_pipeline and s.kind <> 'open'
  ), (select max(s.position) + 1 from public.stages s where s.organization_id = org_id and s.pipeline_id = target_pipeline), 0);
  -- Room for the new stage
  update public.stages s set position = s.position + 1
  where s.organization_id = org_id and s.pipeline_id = target_pipeline and s.position >= new_position;
  insert into public.stages (organization_id, pipeline_id, name, position, kind, color, script)
  values (org_id, target_pipeline, btrim(coalesce(body ->> 'name', '')), new_position, coalesce(body ->> 'kind', 'open'),
    coalesce(nullif(body ->> 'color', ''), '#83A2DB'), nullif(body ->> 'script', ''))
  returning * into new_stage;
  return jsonb_build_object('data', jsonb_build_object('id', new_stage.id, 'pipeline_id', new_stage.pipeline_id,
    'name', new_stage.name, 'position', new_stage.position, 'kind', new_stage.kind, 'color', new_stage.color,
    'script', new_stage.script));
end;
$$;

