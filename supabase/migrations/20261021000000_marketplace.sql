CREATE OR REPLACE FUNCTION "private"."manager_deal_visibility"() RETURNS "text"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  -- The integrator (stage 25) reads every deal to test the automations
  if private.current_user_role() in ('owner', 'head', 'integrator') then
    return 'all';
  end if;
  return coalesce((
    select s.manager_deal_visibility
    from public.organization_settings s
    where s.organization_id = private.current_organization_id()
  ), 'all');
end;
$$;

