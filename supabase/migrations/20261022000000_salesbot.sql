CREATE OR REPLACE FUNCTION "private"."salesbot_log"("session" "public"."salesbot_sessions", "step" "jsonb", "log_kind" "text", "log_text" "text" DEFAULT NULL::"text", "log_details" "jsonb" DEFAULT '{}'::"jsonb") RETURNS "void"
    LANGUAGE "sql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  insert into public.salesbot_logs (organization_id, session_id, deal_id, step_id, step_type, kind, text, details)
  values (session.organization_id, session.id, session.deal_id, step ->> 'id', step ->> 'type', log_kind,
    left(log_text, 2000), coalesce(log_details, '{}'::jsonb))
$$;

-- Ends a session. A stopped one (replaced, stopped by an employee, a human
-- took over) cancels the messages it still has in the queue.
CREATE OR REPLACE FUNCTION "private"."salesbot_finish"("target_session_id" bigint, "final_status" "text", "reason" "text" DEFAULT NULL::"text") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  session public.salesbot_sessions;
begin
  update public.salesbot_sessions s
  set status = final_status, stopped_reason = reason, wait_until = null, finished_at = now(), updated_at = now(),
      state = s.state - 'wait'
  where s.id = target_session_id and s.status in ('running', 'waiting')
  returning * into session;
  if not found then
    return;
  end if;
  if final_status = 'stopped' then
    update public.automessages a
    set status = 'cancelled', error = coalesce(reason, 'Бот остановлен'), processed_at = now()
    where a.organization_id = session.organization_id and a.salesbot_session_id = session.id
      and a.status = 'pending';
  end if;
  perform private.salesbot_log(session, null,
    case when final_status in ('done', 'stopped', 'failed') then final_status else 'handoff' end, reason);
end;
$$;

-- One action of a «set» step; returns what changed, raises when it cannot be
-- done (the stage checklist, a value of the wrong type...)
CREATE OR REPLACE FUNCTION "private"."salesbot_apply_set"("action" "jsonb", "deal" "public"."deals", "reply" "text") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := deal.organization_id;
  value text := replace(coalesce(action ->> 'value', ''), '{ответ}', coalesce(reply, ''));
  target_id bigint;
  target_kind text;
  new_sales_id bigint;
begin
  case action ->> 'kind'
  when 'stage' then
    target_id := (action ->> 'stage_id')::bigint;
    select s.kind into target_kind from public.stages s
    where s.organization_id = org_id and s.id = target_id and s.pipeline_id = deal.pipeline_id;
    if target_kind is null then
      raise exception 'Этап не найден в воронке сделки' using errcode = '22023';
    end if;
    if target_kind = 'lost' then
      raise exception 'Перевести в отказ может только сотрудник: нужна причина' using errcode = '22023';
    end if;
    if deal.stage_id = target_id then
      return jsonb_build_object('unchanged', true, 'stage_id', target_id);
    end if;
    update public.deals d set stage_id = target_id where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_stage_id', deal.stage_id, 'to_stage_id', target_id);

  when 'responsible' then
    new_sales_id := coalesce((action ->> 'sales_id')::bigint, private.next_responsible(org_id));
    if new_sales_id is null or not exists (
      select 1 from public.sales s where s.organization_id = org_id and s.id = new_sales_id and not s.disabled
    ) then
      raise exception 'Некому назначить' using errcode = '22023';
    end if;
    if deal.sales_id is not distinct from new_sales_id then
      return jsonb_build_object('unchanged', true, 'sales_id', new_sales_id);
    end if;
    update public.deals d set sales_id = new_sales_id where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_sales_id', deal.sales_id, 'to_sales_id', new_sales_id);

  when 'tag_add', 'tag_remove' then
    target_id := (action ->> 'tag_id')::bigint;
    if not exists (select 1 from public.tags t where t.organization_id = org_id and t.id = target_id) then
      raise exception 'Тег не найден' using errcode = '22023';
    end if;
    if (target_id = any(deal.tags)) = (action ->> 'kind' = 'tag_add') then
      return jsonb_build_object('unchanged', true, 'tag_id', target_id);
    end if;
    update public.deals d
    set tags = case when action ->> 'kind' = 'tag_add' then array_append(d.tags, target_id) else array_remove(d.tags, target_id) end
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('tag_id', target_id);

  when 'field' then
    target_id := (action ->> 'field_id')::bigint;
    if not exists (
      select 1 from public.custom_fields f
      where f.organization_id = org_id and f.id = target_id and f.entity = 'deal' and f.is_active
    ) then
      raise exception 'Поле не найдено' using errcode = '22023';
    end if;
    update public.deals d
    set custom_values = case when btrim(value) = '' then d.custom_values - target_id::text
      else d.custom_values || jsonb_build_object(target_id::text, btrim(value)) end
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('field_id', target_id, 'value', btrim(value));

  when 'deal_field' then
    value := nullif(btrim(value), '');
    case action ->> 'field'
    when 'service_id' then
      update public.deals d set service_id = value::bigint where d.organization_id = org_id and d.id = deal.id;
    when 'doctor_id' then
      update public.deals d set doctor_id = value::bigint where d.organization_id = org_id and d.id = deal.id;
    when 'source_id' then
      update public.deals d set source_id = value::bigint where d.organization_id = org_id and d.id = deal.id;
    when 'plan_amount' then
      update public.deals d set plan_amount = coalesce(regexp_replace(value, '[^0-9]', '', 'g')::bigint, 0)
      where d.organization_id = org_id and d.id = deal.id;
    when 'name' then
      update public.deals d set name = left(value, 200) where d.organization_id = org_id and d.id = deal.id;
    else
      raise exception 'Поле сделки нельзя изменить' using errcode = '22023';
    end case;
    return jsonb_build_object('field', action ->> 'field', 'value', value);

  when 'patient_field' then
    value := left(nullif(btrim(value), ''), 200);
    case action ->> 'field'
    when 'first_name' then
      update public.patients p set first_name = value where p.organization_id = org_id and p.id = deal.patient_id;
    when 'last_name' then
      update public.patients p set last_name = value where p.organization_id = org_id and p.id = deal.patient_id;
    when 'middle_name' then
      update public.patients p set middle_name = value where p.organization_id = org_id and p.id = deal.patient_id;
    when 'city' then
      update public.patients p set city = value where p.organization_id = org_id and p.id = deal.patient_id;
    else
      raise exception 'Поле пациента нельзя изменить' using errcode = '22023';
    end case;
    return jsonb_build_object('field', action ->> 'field', 'value', value);
  else
    raise exception 'Неизвестное действие' using errcode = '22023';
  end case;
end;
$$;

-- Runs the steps of a running session until it waits (a reply, a delay) or
-- ends. At most 50 steps per call and 30 messages per session (loop
-- protection). The changes are automatic (crm.automation_depth one level
-- deeper, audit source 'automation'); an action that fails is logged
-- (skipped for the stage checklist, failed otherwise) and the scenario goes
-- on. Returns the status of the session.
CREATE OR REPLACE FUNCTION "private"."salesbot_advance"("target_session_id" bigint) RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  session public.salesbot_sessions;
  deal public.deals;
  step jsonb;
  branch jsonb;
  action jsonb;
  step_type text;
  next_id text;
  outgoing text;
  send_at timestamp with time zone;
  wait_from timestamp with time zone;
  zone text;
  new_id bigint;
  result jsonb;
  steps_done integer := 0;
  recipient bigint;
  recipients bigint[];
  handoff_note text;
  queued integer;
  error_hint text;
  error_message text;
  final_status text;
  final_reason text;
  depth integer := coalesce(nullif(current_setting('crm.automation_depth', true), '')::integer, 0);
  previous_source text := coalesce(current_setting('crm.audit_source', true), '');
  previous_session text := coalesce(current_setting('crm.salesbot_session', true), '');
begin
  select * into session from public.salesbot_sessions s where s.id = target_session_id for update;
  if not found or session.status <> 'running' then
    return session.status;
  end if;
  select o.timezone into zone from public.organizations o where o.id = session.organization_id;

  perform set_config('crm.automation_depth', (depth + 1)::text, true);
  perform set_config('crm.audit_source', 'automation', true);
  perform set_config('crm.salesbot_session', session.id::text, true);

  loop
    if session.current_step is null then
      final_status := 'done';
      final_reason := null;
      exit;
    end if;
    step := private.salesbot_step(session.scenario, session.current_step);
    if step is null then
      final_status := 'failed';
      final_reason := 'Шаг сценария не найден';
      exit;
    end if;
    steps_done := steps_done + 1;
    if steps_done > 50 then
      final_status := 'failed';
      final_reason := 'Слишком много шагов подряд: проверьте, нет ли в сценарии петли';
      exit;
    end if;
    select * into deal from public.deals d
    where d.organization_id = session.organization_id and d.id = session.deal_id;
    if not found or deal.archived_at is not null then
      final_status := 'stopped';
      final_reason := 'Сделка в архиве';
      exit;
    end if;

    step_type := step ->> 'type';
    next_id := nullif(step ->> 'next', '');

    if step_type = 'send_message' then
      if session.messages_sent >= 30 then
        final_status := 'failed';
        final_reason := 'Бот отправил слишком много сообщений';
        exit;
      end if;
      outgoing := private.salesbot_message_text(step, deal, session.last_reply);
      if coalesce(outgoing, '') = '' then
        perform private.salesbot_log(session, step, 'skipped', 'Пустой текст сообщения');
      else
        send_at := private.automessage_send_time(now(), zone);
        insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at,
          text, salesbot_session_id)
        values (session.organization_id, deal.id, null, null, deal.stage_id, 'after_stage', send_at,
          outgoing, session.id)
        returning id into new_id;
        session.messages_sent := session.messages_sent + 1;
        session.state := session.state || jsonb_build_object('last_send_at', send_at,
          'buttons', coalesce(case when jsonb_typeof(step -> 'buttons') = 'array' then step -> 'buttons' end, '[]'::jsonb));
        perform private.salesbot_log(session, step, 'sent', outgoing,
          jsonb_build_object('automessage_id', new_id, 'send_at', send_at));
      end if;
      session.current_step := next_id;

    elsif step_type = 'wait_reply' then
      -- The timeout counts from the moment the last message goes out (quiet hours)
      wait_from := greatest(now(), coalesce((session.state ->> 'last_send_at')::timestamp with time zone, now()));
      session.status := 'waiting';
      session.wait_until := wait_from + make_interval(mins => (step ->> 'timeout_minutes')::integer);
      session.state := session.state || '{"wait": "reply"}'::jsonb;
      perform private.salesbot_log(session, step, 'waiting', null, jsonb_build_object('until', session.wait_until));
      exit;

    elsif step_type = 'delay' then
      session.status := 'waiting';
      session.wait_until := now() + make_interval(mins => (step ->> 'minutes')::integer);
      session.state := session.state || '{"wait": "delay"}'::jsonb;
      perform private.salesbot_log(session, step, 'delay', null, jsonb_build_object('until', session.wait_until));
      exit;

    elsif step_type = 'condition' then
      next_id := null;
      for branch in select b.value from jsonb_array_elements(step -> 'branches') with ordinality as b order by b.ordinality loop
        if (branch ->> 'match' in ('keywords', 'option', 'regex', 'any')
              and private.salesbot_reply_matches(branch, session.last_reply, session.state -> 'buttons'))
          or (branch ->> 'match' in ('stage', 'tag', 'source', 'field') and private.salesbot_deal_matches(branch, deal)) then
          next_id := branch ->> 'next';
          exit;
        end if;
      end loop;
      perform private.salesbot_log(session, step, 'branch', session.last_reply,
        jsonb_build_object('next', coalesce(next_id, step ->> 'else_next'), 'matched', next_id is not null));
      session.current_step := coalesce(next_id, nullif(step ->> 'else_next', ''));

    elsif step_type = 'set' then
      for action in select a.value from jsonb_array_elements(step -> 'actions') with ordinality as a order by a.ordinality loop
        select * into deal from public.deals d
        where d.organization_id = session.organization_id and d.id = session.deal_id;
        begin
          result := private.salesbot_apply_set(action, deal, session.last_reply);
          perform private.salesbot_log(session, step, 'set', null, jsonb_build_object('action', action, 'result', result));
        exception when others then
          get stacked diagnostics error_hint = pg_exception_hint, error_message = message_text;
          perform private.salesbot_log(session, step,
            case when error_hint = 'stage_checklist_incomplete' then 'skipped' else 'failed' end,
            error_message, jsonb_build_object('action', action));
        end;
      end loop;
      session.current_step := next_id;

    elsif step_type = 'create_task' then
      begin
        insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id)
        values (deal.organization_id, deal.id, step ->> 'task_type',
          private.render_template(step ->> 'text',
            private.automessage_vars(deal) || jsonb_build_object('ответ', coalesce(session.last_reply, ''))),
          now() + make_interval(mins => coalesce((step ->> 'due_minutes')::integer, 0)), deal.sales_id)
        returning id into new_id;
        perform private.salesbot_log(session, step, 'task', step ->> 'text', jsonb_build_object('task_id', new_id));
      exception when others then
        get stacked diagnostics error_message = message_text;
        perform private.salesbot_log(session, step, 'failed', error_message);
      end;
      session.current_step := next_id;

    elsif step_type = 'handoff' then
      handoff_note := nullif(btrim(coalesce(step ->> 'text', '')), '');
      if coalesce((step ->> 'create_task')::boolean, false) then
        insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id)
        values (deal.organization_id, deal.id, 'message',
          coalesce(nullif(btrim(coalesce(step ->> 'task_text', '')), ''), 'Ответить пациенту: бот передал диалог'),
          now(), deal.sales_id)
        returning id into new_id;
      else
        new_id := null;
      end if;
      if current_setting('crm.notifications', true) is distinct from 'off' then
        recipients := case when deal.sales_id is not null then array[deal.sales_id] else private.deal_audience(deal) end;
        foreach recipient in array coalesce(recipients, '{}'::bigint[]) loop
          perform private.add_notification(deal.organization_id, recipient, 'bot_handoff', 'Бот передал диалог',
            private.deal_label(deal) || coalesce(': ' || handoff_note, ''), deal.id, deal.patient_id, new_id);
        end loop;
      end if;
      final_status := 'handed_off';
      final_reason := handoff_note;
      exit;

    elsif step_type = 'webhook' then
      queued := private.enqueue_webhook(deal.organization_id, 'salesbot',
        jsonb_build_object('deal_id', deal.id, 'patient_id', deal.patient_id,
          'salesbot', jsonb_build_object('id', session.bot_id, 'name', session.bot_name, 'session_id', session.id,
            'step', step ->> 'id', 'last_reply', session.last_reply, 'replies', coalesce(session.state -> 'replies', '[]'::jsonb)),
          'deal', private.deal_json(deal)),
        (step ->> 'webhook_id')::bigint);
      perform private.salesbot_log(session, step, case when queued > 0 then 'webhook' else 'failed' end,
        case when queued > 0 then null else 'Вебхук выключен или удалён' end,
        jsonb_build_object('webhook_id', (step ->> 'webhook_id')::bigint));
      session.current_step := next_id;

    elsif step_type = 'stop' then
      final_status := 'done';
      final_reason := null;
      exit;

    else
      final_status := 'failed';
      final_reason := 'Неизвестный шаг сценария';
      exit;
    end if;
  end loop;

  -- Save where it stopped, then end it when the scenario is over
  update public.salesbot_sessions s
  set current_step = session.current_step, state = session.state, status = session.status,
      wait_until = session.wait_until, messages_sent = session.messages_sent, updated_at = now()
  where s.id = session.id and s.status = 'running';
  if final_status is not null then
    perform private.salesbot_finish(session.id, final_status, final_reason);
  end if;

  perform set_config('crm.automation_depth', depth::text, true);
  perform set_config('crm.audit_source', previous_source, true);
  perform set_config('crm.salesbot_session', previous_session, true);
  select s.status into session.status from public.salesbot_sessions s where s.id = session.id;
  return session.status;
end;
$$;

-- Starts a bot on a deal (trigger: new_lead, keyword, pipeline, manual) and
-- runs its first steps. The running session of the deal is stopped first
-- (one session per deal). Returns the session, or null when nothing starts:
-- an import, an unsorted deal (automatic starts; a manual one raises).
CREATE OR REPLACE FUNCTION "private"."salesbot_start"("target_bot_id" bigint, "target_deal_id" bigint, "start_trigger" "text", "actor_id" bigint DEFAULT NULL::bigint) RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  bot public.salesbots;
  deal public.deals;
  session public.salesbot_sessions;
  previous public.salesbot_sessions;
begin
  if current_setting('crm.importing', true) = 'on' then
    return null;
  end if;
  select * into deal from public.deals d where d.id = target_deal_id;
  if not found then
    raise exception 'Сделка не найдена' using errcode = '22023', hint = 'salesbot_deal_unknown';
  end if;
  if deal.unsorted_at is not null then
    if start_trigger = 'manual' then
      raise exception 'Сначала примите заявку из «Неразобранного»' using errcode = 'check_violation', hint = 'salesbot_unsorted';
    end if;
    return null;
  end if;
  if deal.archived_at is not null then
    raise exception 'Сделка в архиве' using errcode = 'check_violation', hint = 'salesbot_archived';
  end if;
  -- A bot changing the deal cannot start another bot on it (loop protection)
  if coalesce(current_setting('crm.salesbot_session', true), '') <> '' then
    raise exception 'Бот уже ведёт эту сделку' using errcode = 'check_violation', hint = 'salesbot_busy';
  end if;
  select * into bot from public.salesbots b
  where b.organization_id = deal.organization_id and b.id = target_bot_id;
  if not found then
    raise exception 'Бот не найден' using errcode = '22023', hint = 'salesbot_unknown';
  end if;
  if not bot.is_active then
    raise exception 'Бот выключен' using errcode = 'check_violation', hint = 'salesbot_inactive';
  end if;

  for previous in
    select * from public.salesbot_sessions s
    where s.organization_id = deal.organization_id and s.deal_id = deal.id and s.status in ('running', 'waiting')
    for update
  loop
    perform private.salesbot_finish(previous.id, 'stopped', 'Запущен бот «' || bot.name || '»');
  end loop;

  insert into public.salesbot_sessions (organization_id, deal_id, bot_id, bot_name, bot_version, scenario,
    current_step, trigger, started_by)
  values (deal.organization_id, deal.id, bot.id, bot.name, bot.version, bot.scenario,
    bot.scenario ->> 'start', start_trigger, actor_id)
  returning * into session;
  perform private.salesbot_log(session, null, 'started', bot.name,
    jsonb_build_object('trigger', start_trigger, 'bot_id', bot.id, 'version', bot.version, 'sales_id', actor_id));
  perform private.salesbot_advance(session.id);
  return session.id;
end;
$$;

-- An inbound message of a deal: resumes its waiting session with the reply;
-- without a session, starts the new-lead bot (first message of the deal) or
-- a keyword bot. A session whose deal is closed follows the patient to the
-- new deal of the reply (a patient answering a reactivation).
CREATE OR REPLACE FUNCTION "private"."salesbot_on_inbound"("message" "public"."messages") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  session public.salesbot_sessions;
  step jsonb;
  bot_id bigint;
  reply text := coalesce(message.text, '');
  answer text := private.salesbot_normalize(message.text);
begin
  select * into deal from public.deals d where d.organization_id = message.organization_id and d.id = message.deal_id;
  if not found or deal.unsorted_at is not null or deal.archived_at is not null then
    return;
  end if;

  select * into session from public.salesbot_sessions s
  where s.organization_id = deal.organization_id and s.deal_id = deal.id and s.status in ('running', 'waiting')
  for update;
  if not found then
    select s.* into session from public.salesbot_sessions s
      join public.deals d on d.organization_id = s.organization_id and d.id = s.deal_id
      join public.stages st on st.id = d.stage_id
    where s.organization_id = deal.organization_id and d.patient_id = deal.patient_id and d.id <> deal.id
      and s.status = 'waiting' and st.kind in ('won', 'lost')
    order by s.updated_at desc, s.id desc
    limit 1
    for update of s;
    if found then
      update public.salesbot_sessions s set deal_id = deal.id, updated_at = now()
      where s.id = session.id
      returning * into session;
      perform private.salesbot_log(session, null, 'moved', null, jsonb_build_object('deal_id', deal.id));
    end if;
  end if;

  if session.id is not null then
    session.state := jsonb_set(session.state, '{replies}',
      (coalesce(session.state -> 'replies', '[]'::jsonb) || to_jsonb(left(reply, 1000)))
        - case when jsonb_array_length(coalesce(session.state -> 'replies', '[]'::jsonb)) >= 20 then 0 else 1000 end);
    step := private.salesbot_step(session.scenario, session.current_step);
    if session.status = 'waiting' and session.state ->> 'wait' = 'reply' then
      update public.salesbot_sessions s
      set last_reply = reply, state = session.state - 'wait', status = 'running', wait_until = null,
          current_step = nullif(step ->> 'next', ''), updated_at = now()
      where s.id = session.id
      returning * into session;
      perform private.salesbot_log(session, step, 'reply', reply, jsonb_build_object('message_id', message.id));
      perform private.salesbot_advance(session.id);
    else
      -- A delay is running: the reply is kept for the next condition
      update public.salesbot_sessions s set last_reply = reply, state = session.state, updated_at = now()
      where s.id = session.id
      returning * into session;
      perform private.salesbot_log(session, step, 'reply', reply, jsonb_build_object('message_id', message.id));
    end if;
    return;
  end if;

  -- The first message of a new deal
  if not exists (
    select 1 from public.messages m
    where m.organization_id = message.organization_id and m.deal_id = message.deal_id and m.id <> message.id
  ) then
    select b.id into bot_id from public.salesbots b
    where b.organization_id = deal.organization_id and b.is_active and b.trigger_new_lead
      and (cardinality(b.trigger_transports) = 0 or message.transport = any(b.trigger_transports))
      and (cardinality(b.trigger_source_ids) = 0 or deal.source_id = any(b.trigger_source_ids))
    order by b.position, b.id
    limit 1;
    if bot_id is not null then
      perform private.salesbot_start(bot_id, deal.id, 'new_lead');
      return;
    end if;
  end if;

  if answer <> '' then
    select b.id into bot_id from public.salesbots b
    where b.organization_id = deal.organization_id and b.is_active
      and exists (
        select 1 from unnest(b.trigger_keywords) as k
        where btrim(k) <> '' and position(private.salesbot_normalize(btrim(k)) in answer) > 0
      )
    order by b.position, b.id
    limit 1;
    if bot_id is not null then
      perform private.salesbot_start(bot_id, deal.id, 'keyword');
    end if;
  end if;
end;
$$;

-- Messages: an inbound one goes to the bots, an employee's own outbound one
-- (not an auto-message) stops the bot: a human took over. A problem of the
-- bots never refuses the message.
CREATE OR REPLACE FUNCTION "private"."handle_message_salesbot"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  active_id bigint;
begin
  if current_setting('crm.importing', true) = 'on' or new.deal_id is null then
    return null;
  end if;
  if new.direction = 'out' then
    if new.sales_id is not null and new.automessage_id is null then
      select s.id into active_id from public.salesbot_sessions s
      where s.organization_id = new.organization_id and s.deal_id = new.deal_id and s.status in ('running', 'waiting');
      if active_id is not null then
        perform private.salesbot_finish(active_id, 'stopped', 'Сотрудник ответил сам');
      end if;
    end if;
    return null;
  end if;
  begin
    perform private.salesbot_on_inbound(new);
  exception when others then
    raise warning 'salesbot: message % not handled: %', new.id, sqlerrm;
  end;
  return null;
end;
$$;

-- Deals: an accepted unsorted lead starts the new-lead bot of its first
-- message; an archived deal stops its bot
CREATE OR REPLACE FUNCTION "private"."handle_deal_salesbot"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  first_message public.messages;
  active_id bigint;
  bot_id bigint;
begin
  if current_setting('crm.importing', true) = 'on' then
    return null;
  end if;
  if new.archived_at is not null and old.archived_at is null then
    select s.id into active_id from public.salesbot_sessions s
    where s.organization_id = new.organization_id and s.deal_id = new.id and s.status in ('running', 'waiting');
    if active_id is not null then
      perform private.salesbot_finish(active_id, 'stopped', 'Сделка в архиве');
    end if;
    return null;
  end if;
  if old.unsorted_at is null or new.unsorted_at is not null
    or (select s.kind from public.stages s where s.id = new.stage_id) <> 'open' then
    return null;
  end if;
  select * into first_message from public.messages m
  where m.organization_id = new.organization_id and m.deal_id = new.id and m.direction = 'in'
  order by m.sent_at, m.id
  limit 1;
  if first_message.id is null then
    return null;
  end if;
  select b.id into bot_id from public.salesbots b
  where b.organization_id = new.organization_id and b.is_active and b.trigger_new_lead
    and (cardinality(b.trigger_transports) = 0 or first_message.transport = any(b.trigger_transports))
    and (cardinality(b.trigger_source_ids) = 0 or new.source_id = any(b.trigger_source_ids))
  order by b.position, b.id
  limit 1;
  if bot_id is not null then
    begin
      perform private.salesbot_start(bot_id, new.id, 'new_lead');
    exception when others then
      raise warning 'salesbot: deal % not started: %', new.id, sqlerrm;
    end;
  end if;
  return null;
end;
$$;

-- Timeouts of the replies and ends of the delays, run by pg_cron every minute
-- (and by the tests with a moment). At most 500 sessions per run; a broken
-- session fails alone.
CREATE OR REPLACE FUNCTION "private"."salesbot_tick"("moment" timestamp with time zone DEFAULT "now"()) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  session public.salesbot_sessions;
  step jsonb;
  resumed integer := 0;
begin
  for session in
    select * from public.salesbot_sessions s
    where s.status = 'waiting' and s.wait_until <= moment
    order by s.wait_until, s.id
    limit 500
    for update skip locked
  loop
    step := private.salesbot_step(session.scenario, session.current_step);
    begin
      update public.salesbot_sessions s
      set status = 'running', wait_until = null, state = s.state - 'wait', updated_at = now(),
          current_step = nullif(case when session.state ->> 'wait' = 'reply' then step ->> 'timeout_next' else step ->> 'next' end, '')
      where s.id = session.id
      returning * into session;
      if step ->> 'type' = 'wait_reply' then
        perform private.salesbot_log(session, step, 'timeout');
      end if;
      perform private.salesbot_advance(session.id);
      resumed := resumed + 1;
    exception when others then
      perform private.salesbot_finish(session.id, 'failed', left(sqlerrm, 500));
    end;
  end loop;
  return resumed;
end;
$$;

-- Normalizes a bot on save and checks its scenario: a broken structure is
-- refused, an active bot must have no error. The version grows when the
-- scenario changes.
CREATE OR REPLACE FUNCTION "private"."handle_salesbot_saved"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  errors jsonb := private.salesbot_errors(new.scenario);
begin
  new.name := btrim(new.name);
  new.trigger_keywords := coalesce((
    select array_agg(distinct k order by k)
    from (select btrim(private.salesbot_normalize(x)) as k from unnest(new.trigger_keywords) as x) w
    where k <> ''
  ), '{}'::text[]);
  if tg_op = 'INSERT' then
    new.version := 1;
    new.created_by := coalesce(new.created_by, private.current_sales_id());
  else
    new.version := old.version + case when new.scenario is distinct from old.scenario then 1 else 0 end;
    new.created_at := old.created_at;
    new.updated_at := now();
  end if;
  if exists (select 1 from jsonb_array_elements(errors) as e where e.value ->> 'code' in ('invalid', 'duplicate_id', 'unknown_type')) then
    raise exception 'Сценарий бота повреждён' using errcode = 'check_violation', hint = 'salesbot_invalid';
  end if;
  if new.is_active and jsonb_array_length(errors) > 0 then
    raise exception 'Исправьте ошибки сценария перед включением бота (%)',
      (select string_agg(distinct e.value ->> 'code', ', ') from jsonb_array_elements(errors) as e)
      using errcode = 'check_violation', hint = 'salesbot_invalid';
  end if;
  return new;
end;
$$;

