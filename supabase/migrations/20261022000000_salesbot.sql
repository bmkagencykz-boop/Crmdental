-- Lowercase, ё → е (whatever the collation of the database). Same as
-- normalizeText() in salesbot/engine.ts.
CREATE OR REPLACE FUNCTION "private"."salesbot_normalize"("value" "text") RETURNS "text"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select replace(
    translate(lower(coalesce(value, '')),
      'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯӘҒҚҢӨҰҮҺІ',
      'абвгдеёжзийклмнопрстуфхцчшщъыьэюяәғқңөұүһі'),
    'ё', 'е')
$$;

-- The errors of a scenario, [{ code, step }]: invalid, no_steps,
-- duplicate_id, unknown_type, no_start, dangling_next, missing_target,
-- missing_param, empty_message, bad_timeout, bad_delay, invalid_regex,
-- unreachable. Same as validateScenario() in salesbot/engine.ts.
CREATE OR REPLACE FUNCTION "private"."salesbot_errors"("scenario" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql" IMMUTABLE
    SET "search_path" TO ''
    AS $_$
declare
  errors jsonb := '[]'::jsonb;
  step jsonb;
  branch jsonb;
  action jsonb;
  ids text[] := '{}'::text[];
  step_id text;
  step_type text;
  optional_targets text[];
  required_targets text[];
  target text;
  edges jsonb := '{}'::jsonb;
  reachable text[] := '{}'::text[];
  frontier text[];
  next_frontier text[];
  start_id text;
begin
  if scenario is null or jsonb_typeof(scenario) <> 'object'
    or jsonb_typeof(scenario -> 'steps') is distinct from 'array' then
    return '[{"code": "invalid", "step": null}]'::jsonb;
  end if;
  if jsonb_array_length(scenario -> 'steps') = 0 then
    return '[{"code": "no_steps", "step": null}]'::jsonb;
  end if;

  for step in select e.value from jsonb_array_elements(scenario -> 'steps') as e loop
    step_id := case when jsonb_typeof(step) = 'object' then nullif(btrim(coalesce(step ->> 'id', '')), '') end;
    if step_id is null then
      errors := errors || jsonb_build_array(jsonb_build_object('code', 'invalid', 'step', null));
      continue;
    end if;
    if step_id = any(ids) then
      errors := errors || jsonb_build_array(jsonb_build_object('code', 'duplicate_id', 'step', step_id));
    end if;
    ids := ids || step_id;
  end loop;

  start_id := scenario ->> 'start';
  if start_id is null or not (start_id = any(ids)) then
    errors := errors || jsonb_build_array(jsonb_build_object('code', 'no_start', 'step', null));
  end if;

  for step in select e.value from jsonb_array_elements(scenario -> 'steps') as e where jsonb_typeof(e.value) = 'object' loop
    step_id := nullif(btrim(coalesce(step ->> 'id', '')), '');
    continue when step_id is null;
    step_type := step ->> 'type';
    optional_targets := '{}'::text[];
    required_targets := '{}'::text[];
    case step_type
    when 'send_message' then
      if btrim(coalesce(step ->> 'text', '')) = '' and coalesce(step ->> 'template_id', '') !~ '^\d+$' then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'empty_message', 'step', step_id));
      end if;
      if step ? 'buttons' and step -> 'buttons' <> 'null'::jsonb and (jsonb_typeof(step -> 'buttons') <> 'array'
        or exists (select 1 from jsonb_array_elements(step -> 'buttons') as b
                   where jsonb_typeof(b.value) <> 'string' or btrim(b.value #>> '{}') = '')) then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
      end if;
      optional_targets := array[step ->> 'next'];
    when 'wait_reply' then
      if coalesce(step ->> 'timeout_minutes', '') !~ '^\d+$' or (step ->> 'timeout_minutes')::bigint < 1 then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'bad_timeout', 'step', step_id));
      end if;
      required_targets := array[step ->> 'next', step ->> 'timeout_next'];
    when 'condition' then
      if jsonb_typeof(step -> 'branches') is distinct from 'array' or jsonb_array_length(step -> 'branches') = 0 then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
      else
        for branch in select b.value from jsonb_array_elements(step -> 'branches') as b loop
          if jsonb_typeof(branch) <> 'object' or coalesce(branch ->> 'match', '') not in
              ('keywords', 'option', 'regex', 'any', 'stage', 'tag', 'source', 'field')
            or (branch ->> 'match' in ('keywords', 'regex') and btrim(coalesce(branch ->> 'value', '')) = '')
            or (branch ->> 'match' = 'option' and coalesce(branch ->> 'value', '') !~ '^\s*\d+\s*$')
            or (branch ->> 'match' = 'stage' and coalesce(branch ->> 'stage_id', '') !~ '^\d+$')
            or (branch ->> 'match' = 'tag' and coalesce(branch ->> 'tag_id', '') !~ '^\d+$')
            or (branch ->> 'match' = 'source' and coalesce(branch ->> 'source_id', '') !~ '^\d+$')
            or (branch ->> 'match' = 'field' and coalesce(branch ->> 'field_id', '') !~ '^\d+$') then
            errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
          elsif branch ->> 'match' = 'regex' then
            begin
              perform '' ~ (branch ->> 'value');
            exception when others then
              errors := errors || jsonb_build_array(jsonb_build_object('code', 'invalid_regex', 'step', step_id));
            end;
          end if;
          required_targets := required_targets || case when jsonb_typeof(branch) = 'object' then branch ->> 'next' end;
        end loop;
      end if;
      required_targets := required_targets || (step ->> 'else_next');
    when 'set' then
      if jsonb_typeof(step -> 'actions') is distinct from 'array' or jsonb_array_length(step -> 'actions') = 0 then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
      else
        for action in select a.value from jsonb_array_elements(step -> 'actions') as a loop
          if jsonb_typeof(action) <> 'object' or coalesce(action ->> 'kind', '') not in
              ('stage', 'responsible', 'tag_add', 'tag_remove', 'field', 'deal_field', 'patient_field')
            or (action ->> 'kind' = 'stage' and coalesce(action ->> 'stage_id', '') !~ '^\d+$')
            or (action ->> 'kind' in ('tag_add', 'tag_remove') and coalesce(action ->> 'tag_id', '') !~ '^\d+$')
            or (action ->> 'kind' = 'field' and coalesce(action ->> 'field_id', '') !~ '^\d+$')
            or (action ->> 'kind' = 'deal_field' and coalesce(action ->> 'field', '') not in
              ('service_id', 'doctor_id', 'source_id', 'plan_amount', 'name'))
            or (action ->> 'kind' = 'patient_field' and coalesce(action ->> 'field', '') not in
              ('first_name', 'last_name', 'middle_name', 'city')) then
            errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
          end if;
        end loop;
      end if;
      optional_targets := array[step ->> 'next'];
    when 'create_task' then
      if btrim(coalesce(step ->> 'text', '')) = ''
        or coalesce(step ->> 'task_type', '') not in ('call', 'message', 'reminder', 'other', 'meeting')
        or (step ? 'due_minutes' and coalesce(step ->> 'due_minutes', '0') !~ '^\d+$') then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
      end if;
      optional_targets := array[step ->> 'next'];
    when 'handoff' then
      null;
    when 'webhook' then
      if coalesce(step ->> 'webhook_id', '') !~ '^\d+$' then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_param', 'step', step_id));
      end if;
      optional_targets := array[step ->> 'next'];
    when 'delay' then
      if coalesce(step ->> 'minutes', '') !~ '^\d+$' or (step ->> 'minutes')::bigint < 1 then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'bad_delay', 'step', step_id));
      end if;
      optional_targets := array[step ->> 'next'];
    when 'stop' then
      null;
    else
      errors := errors || jsonb_build_array(jsonb_build_object('code', 'unknown_type', 'step', step_id));
    end case;

    foreach target in array optional_targets loop
      if nullif(target, '') is not null and not (target = any(ids)) then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'dangling_next', 'step', step_id));
      end if;
    end loop;
    foreach target in array required_targets loop
      if nullif(target, '') is null then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'missing_target', 'step', step_id));
      elsif not (target = any(ids)) then
        errors := errors || jsonb_build_array(jsonb_build_object('code', 'dangling_next', 'step', step_id));
      end if;
    end loop;
    edges := edges || jsonb_build_object(step_id, to_jsonb(array_remove(optional_targets || required_targets, null)));
  end loop;

  -- Every step is reachable from the start
  if start_id = any(ids) then
    frontier := array[start_id];
    while cardinality(frontier) > 0 loop
      reachable := reachable || frontier;
      select coalesce(array_agg(distinct t.value), '{}'::text[]) into next_frontier
      from unnest(frontier) as f(id)
        cross join lateral jsonb_array_elements_text(coalesce(edges -> f.id, '[]'::jsonb)) as t(value)
      where not (t.value = any(reachable));
      frontier := next_frontier;
    end loop;
    for step_id in select distinct x from unnest(ids) as x where not (x = any(reachable)) order by 1 loop
      errors := errors || jsonb_build_array(jsonb_build_object('code', 'unreachable', 'step', step_id));
    end loop;
  end if;
  return errors;
end;
$_$;

-- A step of a scenario by id
CREATE OR REPLACE FUNCTION "private"."salesbot_step"("scenario" "jsonb", "step_id" "text") RETURNS "jsonb"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select e.value
  from jsonb_array_elements(coalesce(scenario -> 'steps', '[]'::jsonb)) as e
  where e.value ->> 'id' = step_id
  limit 1
$$;

-- Does the last reply match a branch of a condition. keywords: one of the
-- comma separated words or phrases, as whole words; option: the number N
-- ("1", "1.", "1 — да") or the text of button N; regex: on the lowercased
-- reply; any: there is a reply. Same as replyMatches() in salesbot/engine.ts.
CREATE OR REPLACE FUNCTION "private"."salesbot_reply_matches"("branch" "jsonb", "reply" "text", "buttons" "jsonb") RETURNS boolean
    LANGUAGE "plpgsql" IMMUTABLE
    SET "search_path" TO ''
    AS $_$
declare
  answer text := btrim(private.salesbot_normalize(reply));
  word text;
  option_number integer;
  letters constant text := 'a-z0-9а-яәғқңөұүһі';
begin
  if reply is null then
    return false;
  end if;
  case branch ->> 'match'
  when 'any' then
    return true;
  when 'keywords' then
    foreach word in array string_to_array(private.salesbot_normalize(branch ->> 'value'), ',') loop
      word := btrim(word);
      continue when word = '';
      if answer ~ ('(^|[^' || letters || '])'
        || regexp_replace(word, '([.^$*+?()\[\]{}|\\-])', '\\\1', 'g')
        || '([^' || letters || ']|$)') then
        return true;
      end if;
    end loop;
    return false;
  when 'option' then
    option_number := btrim(branch ->> 'value')::integer;
    return answer ~ ('^' || option_number || '([^0-9]|$)')
      or (jsonb_typeof(buttons) = 'array' and option_number between 1 and jsonb_array_length(buttons)
        and answer = btrim(private.salesbot_normalize(buttons ->> (option_number - 1))));
  when 'regex' then
    begin
      return answer ~ (branch ->> 'value');
    exception when others then
      return false;
    end;
  else
    return false;
  end case;
end;
$_$;

-- Does the deal match a branch on its data (stage, tag, source, custom field)
CREATE OR REPLACE FUNCTION "private"."salesbot_deal_matches"("branch" "jsonb", "deal" "public"."deals") RETURNS boolean
    LANGUAGE "plpgsql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
declare
  stored jsonb;
  expected text := btrim(private.salesbot_normalize(branch ->> 'value'));
begin
  case branch ->> 'match'
  when 'stage' then
    return deal.stage_id = (branch ->> 'stage_id')::bigint;
  when 'tag' then
    return (branch ->> 'tag_id')::bigint = any(deal.tags);
  when 'source' then
    return coalesce(deal.source_id = (branch ->> 'source_id')::bigint, false);
  when 'field' then
    stored := deal.custom_values -> (branch ->> 'field_id');
    if stored is null or stored = 'null'::jsonb then
      return false;
    end if;
    if expected = '' then
      return true;
    end if;
    if jsonb_typeof(stored) = 'array' then
      return exists (select 1 from jsonb_array_elements_text(stored) as v where btrim(private.salesbot_normalize(v)) = expected);
    end if;
    if jsonb_typeof(stored) = 'boolean' then
      return (stored = 'true'::jsonb) = (expected in ('true', '1', 'да', 'yes', '+'));
    end if;
    return btrim(private.salesbot_normalize(stored #>> '{}')) = expected;
  else
    return false;
  end case;
end;
$$;

-- Text of a message step for a deal: the template or the text, the template
-- variables, {ответ} (the last reply), then the numbered buttons
CREATE OR REPLACE FUNCTION "private"."salesbot_message_text"("step" "jsonb", "deal" "public"."deals", "reply" "text") RETURNS "text"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  body text := step ->> 'text';
  rendered text;
  buttons text;
begin
  if coalesce(step ->> 'template_id', '') ~ '^\d+$' then
    select t.body into body from public.message_templates t
    where t.organization_id = deal.organization_id and t.id = (step ->> 'template_id')::bigint;
  end if;
  rendered := private.render_template(body,
    private.automessage_vars(deal) || jsonb_build_object('ответ', coalesce(reply, '')));
  if jsonb_typeof(step -> 'buttons') = 'array' and jsonb_array_length(step -> 'buttons') > 0 then
    select string_agg(b.ordinality || ' — ' || btrim(b.value), E'\n' order by b.ordinality) into buttons
    from jsonb_array_elements_text(step -> 'buttons') with ordinality as b;
    rendered := btrim(concat_ws(E'\n\n', nullif(rendered, ''), buttons), E' \n');
  end if;
  return rendered;
end;
$$;

