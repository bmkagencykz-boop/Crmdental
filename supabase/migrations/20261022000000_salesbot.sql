--
-- «Салесбот» (stage 26): chat bot scenarios, their sessions and log, the
-- digital pipeline action «Запустить салесбот», bot messages through the
-- auto-message queue, the notification «Бот передал диалог».
-- Source of truth: supabase/schemas/26_salesbot.sql (+ the functions of
-- 08_automessages.sql, 16_notifications.sql and 20_digital_pipeline.sql
-- copied below).
--
--
-- «Салесбот» (stage 26): chat bot scenarios, as in amoCRM
--
-- A bot (public.salesbots) is a scenario: a graph of steps stored as jsonb
--   { "start": "<step id>", "steps": [ { "id", "type", ...params, "next" } ] }
-- Step types (the same in the app: salesbot/engine.ts, the pure twin that
-- powers the «Тест» mode of the editor and the demo):
--   send_message  text (template variables + {ответ}) or template_id, optional
--                 numbered answer buttons appended as "1 — Записаться" lines
--   wait_reply    timeout_minutes; next (a reply came), timeout_next
--   condition     branches [{ match, value | stage_id | tag_id | source_id |
--                 field_id, next }] tried in order, else_next. Matches on the
--                 last reply: keywords (comma separated, whole words), option
--                 (number N or the text of button N), regex, any; on the deal:
--                 stage, tag, source, field (custom field value, empty value =
--                 filled)
--   set           actions [{ kind: stage | responsible | tag_add | tag_remove |
--                 field | deal_field | patient_field, ... }]; a value may be
--                 {ответ} (the last reply)
--   create_task   task_type, text, due_minutes
--   handoff       stops the bot: notification «Бот передал диалог» to the
--                 responsible (+ an optional task)
--   webhook       webhook_id: fire-and-forget through the stage 20 webhook
--                 queue (event 'salesbot'); the response is not read
--   delay         minutes
--   stop          the scenario ends
-- The scenario is checked on save (private.salesbot_errors): a broken
-- structure is refused, and an active bot must have no error at all.
--
-- Runtime: one session per deal at a time (public.salesbot_sessions, with a
-- snapshot of the scenario, so editing a bot never breaks a conversation in
-- progress), every step logged in public.salesbot_logs (deal feed,
-- debugging). private.salesbot_advance runs the steps synchronously until the
-- scenario waits (wait_reply, delay) or ends. Messages go through the
-- auto-message queue of stage 6 (automessages.salesbot_session_id, text
-- ready): the dispatcher sends them, quiet hours apply (a bot reply at night
-- waits until 9:00, the reply timeout counts from that moment).
--
-- Starts: a new deal's first inbound message (bots with trigger_new_lead,
-- optionally for some channels / sources), a keyword of an inbound message,
-- the digital pipeline action «Запустить салесбот», or an employee
-- (public.start_salesbot). A new start replaces the running session. Nothing
-- starts on unsorted deals (accepting one runs the new-lead bots) nor during
-- an import. An inbound message resumes a waiting session; an employee's own
-- message stops it; pg_cron runs private.salesbot_tick every minute for the
-- timeouts and the delays. Loop protection: 50 steps per activation, 30
-- messages per session.
--

--
-- Rights helper
--

-- May the current user configure the clinic (bots, triggers...). One place to
-- extend with new roles.
CREATE OR REPLACE FUNCTION "private"."can_configure"() RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return coalesce(private.current_user_role() in ('owner', 'head'), false);
end;
$$;

