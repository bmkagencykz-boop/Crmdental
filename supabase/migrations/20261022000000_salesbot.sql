-- The action of a trigger on a deal; returns what changed (shown in the deal
-- feed). Raises when the action cannot be done (the caller logs it).
CREATE OR REPLACE FUNCTION "private"."apply_stage_trigger_action"("trigger_row" "public"."stage_triggers", "deal" "public"."deals") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := deal.organization_id;
  new_sales_id bigint;
  new_id bigint;
  zone text;
  template_body text;
  rendered text;
  old_value jsonb;
  queued integer;
begin
  case trigger_row.action
  when 'move_stage' then
    if deal.stage_id = trigger_row.target_stage_id then
      return jsonb_build_object('unchanged', true);
    end if;
    update public.deals d
    set stage_id = trigger_row.target_stage_id
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_stage_id', deal.stage_id, 'to_stage_id', trigger_row.target_stage_id);

  when 'set_responsible' then
    new_sales_id := coalesce(trigger_row.target_sales_id, private.next_responsible(org_id));
    if new_sales_id is null then
      raise exception 'Некому назначить: распределение по очереди не настроено' using errcode = '22023';
    end if;
    if exists (select 1 from public.sales s where s.id = new_sales_id and s.disabled) then
      raise exception 'Сотрудник отключён' using errcode = '22023';
    end if;
    if deal.sales_id is not distinct from new_sales_id then
      return jsonb_build_object('unchanged', true);
    end if;
    update public.deals d
    set sales_id = new_sales_id
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_sales_id', deal.sales_id, 'to_sales_id', new_sales_id);

  when 'add_tag' then
    if trigger_row.tag_id = any(deal.tags) then
      return jsonb_build_object('unchanged', true, 'tag_id', trigger_row.tag_id);
    end if;
    update public.deals d
    set tags = array_append(d.tags, trigger_row.tag_id)
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('tag_id', trigger_row.tag_id);

  when 'remove_tag' then
    if not trigger_row.tag_id = any(deal.tags) then
      return jsonb_build_object('unchanged', true, 'tag_id', trigger_row.tag_id);
    end if;
    update public.deals d
    set tags = array_remove(d.tags, trigger_row.tag_id)
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('tag_id', trigger_row.tag_id);

  when 'create_task' then
    -- Same as the task rules (private.create_rule_tasks)
    insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id)
    values (org_id, deal.id, trigger_row.task_type, btrim(trigger_row.task_text),
      now() + make_interval(mins => trigger_row.task_due_minutes), deal.sales_id)
    returning id into new_id;
    return jsonb_build_object('task_id', new_id);

  when 'send_template' then
    -- The stage 6 queue: "show first" becomes the task with the text and the
    -- «Отправить» button right away; "auto" is sent by the dispatcher
    -- (quiet hours apply, leaving the stage cancels it)
    if coalesce(trigger_row.message_mode, 'auto') = 'confirm' then
      select t.body into template_body from public.message_templates t
      where t.organization_id = org_id and t.id = trigger_row.template_id;
      rendered := private.render_template(template_body, private.automessage_vars(deal));
      insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at, status, text, processed_at)
      values (org_id, deal.id, null, trigger_row.template_id, deal.stage_id, 'after_stage', now(), 'awaiting', rendered, now())
      returning id into new_id;
      insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id, automessage_id)
      values (org_id, deal.id, 'message', rendered, now(), deal.sales_id, new_id);
    else
      select o.timezone into zone from public.organizations o where o.id = org_id;
      insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at)
      values (org_id, deal.id, null, trigger_row.template_id, deal.stage_id, 'after_stage',
        private.automessage_send_time(now(), zone))
      returning id into new_id;
    end if;
    return jsonb_build_object('automessage_id', new_id, 'template_id', trigger_row.template_id,
      'mode', coalesce(trigger_row.message_mode, 'auto'));

  when 'send_webhook' then
    queued := private.enqueue_webhook(org_id, 'automation',
      jsonb_build_object('deal_id', deal.id, 'patient_id', deal.patient_id,
        'trigger', jsonb_build_object('id', trigger_row.id, 'name', trigger_row.name, 'event', trigger_row.event),
        'deal', private.deal_json(deal)),
      trigger_row.webhook_id);
    if queued = 0 then
      raise exception 'Вебхук выключен' using errcode = '22023';
    end if;
    return jsonb_build_object('webhook_id', trigger_row.webhook_id);

  when 'start_salesbot' then
    -- «Запустить салесбот» (26_salesbot.sql): replaces the bot of the deal
    new_id := private.salesbot_start(trigger_row.salesbot_id, deal.id, 'pipeline');
    if new_id is null then
      raise exception 'Бот не запущен' using errcode = '22023';
    end if;
    return jsonb_build_object('salesbot_id', trigger_row.salesbot_id, 'session_id', new_id);

  when 'set_field' then
    old_value := to_jsonb(deal) -> trigger_row.field_name;
    if trigger_row.field_name = 'plan_amount' then
      update public.deals d set plan_amount = trigger_row.plan_amount
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'plan_amount', 'from', old_value, 'to', trigger_row.plan_amount);
    elsif trigger_row.field_name = 'doctor_id' then
      update public.deals d set doctor_id = trigger_row.doctor_id
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'doctor_id', 'from', old_value, 'to', trigger_row.doctor_id);
    else
      update public.deals d set service_id = trigger_row.service_id
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'service_id', 'from', old_value, 'to', trigger_row.service_id);
    end if;
  end case;
  return '{}'::jsonb;
end;
$$;

-- 08_automessages.sql: the messages of a salesbot (text ready, not tied to the stage)

-- Cancels the queued messages of a deal (statuses: which ones; only_timing:
-- only the rows of this timing)
CREATE OR REPLACE FUNCTION "private"."cancel_automessages"("org_id" bigint, "target_deal_id" bigint, "statuses" "text"[], "only_timing" "text", "reason" "text") RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  cancelled integer;
begin
  -- The messages of a salesbot (26_salesbot.sql) belong to its conversation:
  -- leaving the stage does not cancel them, stopping the bot does
  update public.automessages a
  set status = 'cancelled', error = reason, processed_at = now()
  where a.organization_id = org_id
    and a.deal_id = target_deal_id
    and a.status = any(statuses)
    and (only_timing is null or a.timing = only_timing)
    and a.salesbot_session_id is null;
  get diagnostics cancelled = row_count;
  return cancelled;
end;
$$;

-- Dispatcher (edge function automessages_dispatch, service role only): takes
-- the due rows, at most per_clinic per clinic, with FOR UPDATE SKIP LOCKED so
-- that two runs never take the same row. Returns the rows to send through
-- Wazzup24 (status sending); "show first" rows become a task (awaiting);
-- rows whose deal left the stage or whose rule is off are cancelled; a
-- clinic without messengers gets a failed row with the reason.
CREATE OR REPLACE FUNCTION "public"."claim_automessages"("per_clinic" integer DEFAULT 20) RETURNS TABLE("id" bigint, "organization_id" bigint, "deal_id" bigint, "patient_id" bigint, "message_text" "text")
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  job public.automessages;
  job_deal public.deals;
  job_rule public.automessage_rules;
  template_body text;
  rendered text;
  taken jsonb := '{}'::jsonb;
begin
  -- A run that died while sending: rather a failed row than a message sent twice
  update public.automessages a
  set status = 'failed', error = 'Отправка прервалась, проверьте переписку', processed_at = now()
  where a.status = 'sending' and a.claimed_at < now() - interval '10 minutes';

  for job in
    select a.* from public.automessages a
    where a.status = 'pending' and a.send_at <= now()
    order by a.send_at, a.id
    limit 1000
    for update skip locked
  loop
    if coalesce((taken ->> job.organization_id::text)::integer, 0) >= per_clinic then
      continue;
    end if;
    select d.* into job_deal from public.deals d
    where d.organization_id = job.organization_id and d.id = job.deal_id;
    select r.* into job_rule from public.automessage_rules r
    where r.organization_id = job.organization_id and r.id = job.rule_id;

    -- A message of a salesbot (stage 26) has its text and stays when the
    -- deal changes stage (the bot moves it itself)
    if (job.salesbot_session_id is null and job_deal.stage_id is distinct from job.stage_id)
      or job_deal.archived_at is not null then
      update public.automessages a
      set status = 'cancelled', error = 'Сделка ушла с этапа', processed_at = now()
      where a.id = job.id;
      continue;
    end if;
    -- A row queued by a stage trigger (stage 20) has its template, no rule
    if job.salesbot_session_id is null and job.template_id is null
      and (job_rule.id is null or not job_rule.is_active) then
      update public.automessages a
      set status = 'cancelled', error = 'Правило выключено или удалено', processed_at = now()
      where a.id = job.id;
      continue;
    end if;

    if job.salesbot_session_id is not null then
      rendered := job.text;
    else
      select t.body into template_body from public.message_templates t
      where t.organization_id = job.organization_id and t.id = coalesce(job.template_id, job_rule.template_id);
      rendered := private.render_template(template_body, private.automessage_vars(job_deal));
    end if;
    if coalesce(rendered, '') = '' then
      update public.automessages a
      set status = 'failed', error = 'Пустой текст сообщения', processed_at = now()
      where a.id = job.id;
      continue;
    end if;

    if job_rule.mode = 'confirm' then
      insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id, automessage_id)
      values (job.organization_id, job.deal_id, 'message', rendered, now(), job_deal.sales_id, job.id);
      update public.automessages a
      set status = 'awaiting', text = rendered, processed_at = now()
      where a.id = job.id;
      continue;
    end if;

    if not exists (
      select 1 from public.messenger_integrations i
      where i.organization_id = job.organization_id and i.api_key is not null
    ) and not exists (
      select 1 from public.telegram_bots b
      where b.organization_id = job.organization_id and b.bot_token is not null
    ) then
      update public.automessages a
      set status = 'failed', text = rendered, processed_at = now(),
          error = 'Мессенджеры не подключены (Настройки → Мессенджеры)'
      where a.id = job.id;
      continue;
    end if;

    update public.automessages a
    set status = 'sending', text = rendered, claimed_at = now()
    where a.id = job.id;
    taken := jsonb_set(taken, array[job.organization_id::text],
      to_jsonb(coalesce((taken ->> job.organization_id::text)::integer, 0) + 1));
    id := job.id;
    organization_id := job.organization_id;
    deal_id := job.deal_id;
    patient_id := job_deal.patient_id;
    message_text := rendered;
    return next;
  end loop;
end;
$$;

