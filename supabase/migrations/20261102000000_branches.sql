create table public.branches (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    address text,
    phone text,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint branches_name_not_blank check (btrim(name) <> ''),
    constraint branches_address_length check (address is null or char_length(address) <= 500),
    constraint branches_phone_length check (phone is null or char_length(phone) <= 50)
);

create table public.sales_branches (
    organization_id bigint not null default private.current_organization_id(),
    sales_id bigint not null,
    branch_id bigint not null,
    created_at timestamp with time zone not null default now(),
    constraint sales_branches_pkey primary key (organization_id, sales_id, branch_id)
);

