-- «Терапия / Лечение кариеса»: the path of a category, null when unknown
CREATE OR REPLACE FUNCTION "private"."service_category_path"("org_id" bigint, "target_category_id" bigint) RETURNS "text"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return (
    select case when p.id is null then c.name else p.name || ' / ' || c.name end
    from public.service_categories c
      left join public.service_categories p on p.organization_id = c.organization_id and p.id = c.parent_id
    where c.organization_id = org_id and c.id = target_category_id
  );
end;
$$;

-- The category of a path «Раздел / Подраздел» (case and spaces ignored),
-- created when missing; null for an empty path. Deeper levels are ignored.
CREATE OR REPLACE FUNCTION "private"."resolve_service_category"("org_id" bigint, "path" "text") RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  parts text[];
  part text;
  parent bigint := null;
  found bigint;
  level integer := 0;
begin
  select array_agg(btrim(regexp_replace(p, '\s+', ' ', 'g')) order by n)
  into parts
  from unnest(regexp_split_to_array(coalesce(path, ''), '\s*[/>→]\s*')) with ordinality as t(p, n)
  where btrim(p) <> '';
  if parts is null then
    return null;
  end if;
  foreach part in array parts loop
    level := level + 1;
    exit when level > 2;
    select c.id into found
    from public.service_categories c
    where c.organization_id = org_id and c.parent_id is not distinct from parent
      and lower(btrim(c.name)) = lower(part);
    if found is null then
      insert into public.service_categories (organization_id, parent_id, name, position)
      values (org_id, parent, left(part, 100), coalesce((
        select max(c.position) + 1 from public.service_categories c
        where c.organization_id = org_id and c.parent_id is not distinct from parent), 0))
      returning id into found;
    end if;
    parent := found;
  end loop;
  return parent;
end;
$$;

-- Whether deals, visits, treatment plans, recall rules or stage triggers
-- use a service (such a service is archived, not deleted)
CREATE OR REPLACE FUNCTION "private"."service_in_use"("org_id" bigint, "target_service_id" bigint) RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return exists (select 1 from public.deals d where d.organization_id = org_id and d.service_id = target_service_id)
    or exists (select 1 from public.visits v where v.organization_id = org_id and v.service_id = target_service_id)
    or exists (select 1 from public.treatment_plan_items i where i.organization_id = org_id and i.service_id = target_service_id)
    or exists (select 1 from public.recall_rules r where r.organization_id = org_id
      and (r.service_id = target_service_id or r.deal_service_id = target_service_id))
    or exists (select 1 from public.stage_triggers t where t.organization_id = org_id and t.service_id = target_service_id);
end;
$$;

-- A price after a bulk change: rounded to 100 ₸ (half up), never below 0
CREATE OR REPLACE FUNCTION "private"."round_price"("value" numeric) RETURNS numeric
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select greatest(0, round(value / 100) * 100)
$$;

-- Before a service is written: its category and the path in services.category
-- stay together, whichever of the two the writer gave
CREATE OR REPLACE FUNCTION "private"."handle_service_category"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  new.specialty := nullif(btrim(new.specialty), '');
  new.materials_note := nullif(btrim(new.materials_note), '');
  if tg_op = 'INSERT' or new.category_id is distinct from old.category_id then
    if new.category_id is not null then
      new.category := private.service_category_path(new.organization_id, new.category_id);
      if new.category is null then
        raise exception 'Раздел прайса не найден' using errcode = '23503';
      end if;
    elsif nullif(btrim(new.category), '') is not null
      and (tg_op = 'INSERT' or new.category is distinct from old.category) then
      new.category_id := private.resolve_service_category(new.organization_id, new.category);
      new.category := private.service_category_path(new.organization_id, new.category_id);
    else
      new.category := null;
    end if;
  elsif new.category is distinct from old.category then
    if nullif(btrim(new.category), '') is null then
      new.category_id := null;
      new.category := null;
    elsif new.category_id is null
      or new.category is distinct from private.service_category_path(new.organization_id, new.category_id) then
      new.category_id := private.resolve_service_category(new.organization_id, new.category);
      new.category := private.service_category_path(new.organization_id, new.category_id);
    end if;
  end if;
  return new;
end;
$$;

-- After a price changes (the first price too): a row of the price history
CREATE OR REPLACE FUNCTION "private"."handle_service_price_history"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'INSERT' and new.price is null then
    return null;
  end if;
  if tg_op = 'UPDATE' and new.price is not distinct from old.price then
    return null;
  end if;
  insert into public.service_price_history (organization_id, service_id, old_price, new_price, sales_id)
  values (new.organization_id, new.id, case when tg_op = 'UPDATE' then old.price end, new.price, private.current_sales_id());
  return null;
end;
$$;

-- Before a category is written: a trimmed name, at most two levels
CREATE OR REPLACE FUNCTION "private"."handle_service_category_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  new.name := btrim(regexp_replace(new.name, '\s+', ' ', 'g'));
  if new.parent_id is not null and (tg_op = 'INSERT' or new.parent_id is distinct from old.parent_id) then
    if exists (select 1 from public.service_categories p
      where p.organization_id = new.organization_id and p.id = new.parent_id and p.parent_id is not null) then
      raise exception 'В прайсе два уровня: раздел и подраздел' using errcode = '22023';
    end if;
    if tg_op = 'UPDATE' and exists (select 1 from public.service_categories c
      where c.organization_id = new.organization_id and c.parent_id = new.id) then
      raise exception 'Раздел с подразделами не может стать подразделом' using errcode = '22023';
    end if;
  end if;
  return new;
end;
$$;

-- After a category is renamed or moved: the paths of its services (and of
-- the services of its subsections)
CREATE OR REPLACE FUNCTION "private"."handle_service_category_after_update"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  update public.services s
  set category = private.service_category_path(s.organization_id, s.category_id)
  where s.organization_id = new.organization_id
    and s.category_id in (
      select c.id from public.service_categories c
      where c.organization_id = new.organization_id and (c.id = new.id or c.parent_id = new.id))
    and s.category is distinct from private.service_category_path(s.organization_id, s.category_id);
  return null;
end;
$$;

-- Before a category is deleted: the services of a subsection go to its
-- section, those of a section (and of its subsections) lose the category
CREATE OR REPLACE FUNCTION "private"."handle_service_category_delete"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  target bigint := null;
begin
  if old.parent_id is not null and exists (select 1 from public.service_categories p
    where p.organization_id = old.organization_id and p.id = old.parent_id) then
    target := old.parent_id;
  end if;
  update public.services s
  set category_id = target
  where s.organization_id = old.organization_id
    and s.category_id in (
      select c.id from public.service_categories c
      where c.organization_id = old.organization_id and (c.id = old.id or c.parent_id = old.id));
  return old;
end;
$$;

-- «Себестоимость» of a service: null removes it. Owner and head only.
CREATE OR REPLACE FUNCTION "public"."set_service_cost"("target_service_id" bigint, "cost" numeric) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
begin
  if private.current_user_role() is distinct from 'owner' and private.current_user_role() is distinct from 'head' then
    raise exception 'Себестоимость видят и меняют только владелец и руководитель' using errcode = '42501';
  end if;
  if not exists (select 1 from public.services s where s.organization_id = org_id and s.id = target_service_id) then
    raise exception 'Услуга не найдена' using errcode = 'P0002';
  end if;
  if cost is null then
    delete from public.service_costs c where c.organization_id = org_id and c.service_id = target_service_id;
  else
    insert into public.service_costs (organization_id, service_id, cost_price, updated_by, updated_at)
    values (org_id, target_service_id, cost, private.current_sales_id(), now())
    on conflict (organization_id, service_id)
    do update set cost_price = excluded.cost_price, updated_by = excluded.updated_by, updated_at = excluded.updated_at;
  end if;
end;
$$;

-- Bulk actions of the price list on the given services of the clinic:
--   move            to target_category_id (null: «Без раздела»)
--   price_percent   price × (100 + amount) / 100, rounded to 100 ₸
--   price_amount    price + amount, rounded to 100 ₸
--   archive, restore
--   delete          unused services are deleted, used ones archived
-- Returns {"updated": n, "deleted": n, "archived": n}.
CREATE OR REPLACE FUNCTION "public"."bulk_services"("service_ids" bigint[], "bulk_action" "text", "amount" numeric DEFAULT NULL::numeric, "target_category_id" bigint DEFAULT NULL::bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  updated integer := 0;
  deleted integer := 0;
  archived integer := 0;
begin
  if coalesce(private.current_user_role(), '') not in ('owner', 'head', 'integrator') then
    raise exception 'Прайс меняют владелец и руководитель клиники' using errcode = '42501';
  end if;
  if bulk_action = 'move' then
    if target_category_id is not null and not exists (select 1 from public.service_categories c
      where c.organization_id = org_id and c.id = target_category_id) then
      raise exception 'Раздел прайса не найден' using errcode = '23503';
    end if;
    update public.services s set category_id = target_category_id
    where s.organization_id = org_id and s.id = any(service_ids)
      and s.category_id is distinct from target_category_id;
    get diagnostics updated = row_count;
  elsif bulk_action in ('price_percent', 'price_amount') then
    if amount is null or (bulk_action = 'price_percent' and (amount <= -100 or amount > 1000)) then
      raise exception 'Неверное изменение цены' using errcode = '22023';
    end if;
    update public.services s
    set price = private.round_price(case when bulk_action = 'price_percent'
      then s.price * (100 + amount) / 100 else s.price + amount end)
    where s.organization_id = org_id and s.id = any(service_ids) and s.price is not null
      and s.price is distinct from private.round_price(case when bulk_action = 'price_percent'
        then s.price * (100 + amount) / 100 else s.price + amount end);
    get diagnostics updated = row_count;
  elsif bulk_action in ('archive', 'restore') then
    update public.services s set is_archived = (bulk_action = 'archive')
    where s.organization_id = org_id and s.id = any(service_ids)
      and s.is_archived is distinct from (bulk_action = 'archive');
    get diagnostics updated = row_count;
  elsif bulk_action = 'delete' then
    update public.services s set is_archived = true
    where s.organization_id = org_id and s.id = any(service_ids)
      and private.service_in_use(org_id, s.id) and not s.is_archived;
    get diagnostics archived = row_count;
    delete from public.services s
    where s.organization_id = org_id and s.id = any(service_ids)
      and not private.service_in_use(org_id, s.id);
    get diagnostics deleted = row_count;
  else
    raise exception 'Неизвестное действие: %', bulk_action using errcode = '22023';
  end if;
  return jsonb_build_object('updated', updated, 'deleted', deleted, 'archived', archived);
end;
$$;

