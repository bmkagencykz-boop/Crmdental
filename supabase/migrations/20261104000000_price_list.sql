--
-- The clinic price list «Прайс» (stage 35): a main section of the app, like
-- the price list of a dental MIS.
--
--   service_categories      the tree of the price list: sections and their
--                           subsections (two levels: «Терапия → Лечение
--                           кариеса»), ordered by position. Names are unique
--                           among siblings and contain no «/» (the path
--                           separator of the import and export files).
--   services                the same table as before (deals, visits,
--                           treatment plans, reports): category_id, the unit
--                           (зуб / челюсть / посещение / услуга), the
--                           duration in minutes (the default length of a
--                           visit of this service), the direction or
--                           specialty and a note on the materials.
--                           services.category (stage 29) stays: it is kept
--                           equal to the path of category_id («Терапия /
--                           Лечение кариеса»), and a writer that only knows
--                           the text (the stage-29 import, the API) gets its
--                           category found or created from the path.
--   service_costs           the cost price «себестоимость» of a service: a
--                           table of its own so that RLS hides it from
--                           everybody but the owner and the head (managers
--                           read the prices to talk to the patients, not the
--                           margins; the integrator configures the price
--                           list but sees no money).
--   service_price_history   every price change (the first price too): who,
--                           when, old → new. Written by a trigger, read by
--                           every member of the clinic.
--   price_list              the view of the page: the services with their
--                           cost price (null where RLS hides it), whether
--                           they are used (deals, visits, treatment plans,
--                           recall rules, stage triggers) and the time of the
--                           last price change.
--
-- Treatment plans keep the price they were made with: an item copies the
-- unit price (treatment_plan_items.unit_price), a new price changes nothing
-- in existing plans.
--
-- Bulk actions (public.bulk_services): move to a category, change the price
-- by a percentage or by an amount (rounded to 100 ₸, never below 0),
-- archive, restore, delete (unused services only: the used ones are
-- archived instead, so deals, visits and plans keep their service).
--
-- Rights: the owner and the head edit the price list and the categories (the
-- integrator too, as in stage 25); every member reads them. The cost price:
-- the owner and the head only.
--

--
-- Tables and columns
--

create table public.service_categories (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    -- null: a section; else the section of this subsection
    parent_id bigint,
    name text not null,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint service_categories_name_not_blank check (btrim(name) <> ''),
    constraint service_categories_name_check check (char_length(name) <= 100 and strpos(name, '/') = 0),
    constraint service_categories_parent_check check (parent_id is null or parent_id <> id)
);

create table public.service_costs (
    organization_id bigint not null default private.current_organization_id(),
    service_id bigint not null,
    cost_price numeric(12,2) not null,
    updated_by bigint default private.current_sales_id(),
    updated_at timestamp with time zone not null default now(),
    constraint service_costs_pkey primary key (organization_id, service_id),
    constraint service_costs_cost_price_check check (cost_price >= 0)
);

create table public.service_price_history (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    service_id bigint not null,
    old_price numeric(12,2),
    new_price numeric(12,2),
    sales_id bigint,
