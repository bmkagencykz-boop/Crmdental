-- The page «Прайс»: the cost price is null where RLS hides service_costs
create or replace view public.price_list with (security_invoker = on) as
select
    s.id,
    s.organization_id,
    s.name,
    s.code,
    s.category,
    s.category_id,
    s.price,
    s.unit,
    s.duration_minutes,
    s.specialty,
    s.materials_note,
    s.position,
    s.is_archived,
    sc.cost_price,
    private.service_in_use(s.organization_id, s.id) as in_use,
    (select max(h.changed_at) from public.service_price_history h
     where h.organization_id = s.organization_id and h.service_id = s.id) as price_changed_at
from public.services s
    left join public.service_costs sc on sc.organization_id = s.organization_id and sc.service_id = s.id;

