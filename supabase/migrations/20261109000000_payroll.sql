-- The scheme of a doctor or an employee on a day: the last one effective
CREATE OR REPLACE FUNCTION "private"."payroll_scheme_at"("org_id" bigint, "target_doctor_id" bigint, "target_sales_id" bigint, "day" "date") RETURNS "public"."payroll_schemes"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  scheme public.payroll_schemes;
begin
  select * into scheme
  from public.payroll_schemes s
  where s.organization_id = org_id
    and s.doctor_id is not distinct from target_doctor_id
    and s.sales_id is not distinct from target_sales_id
    and s.effective_from <= day
  order by s.effective_from desc, s.id desc
  limit 1;
  return scheme;
end;
$$;

-- The percentage of a scheme for a service category: the category's own
-- rate, else its section's, else the default. Twin: percentFor()
CREATE OR REPLACE FUNCTION "private"."payroll_percent"("scheme" "public"."payroll_schemes", "category_id" bigint, "section_id" bigint) RETURNS numeric
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select coalesce(
    (select (r ->> 'percent')::numeric from jsonb_array_elements(scheme.category_rates) r
     where category_id is not null and (r ->> 'category_id')::bigint = category_id limit 1),
    (select (r ->> 'percent')::numeric from jsonb_array_elements(scheme.category_rates) r
     where section_id is not null and (r ->> 'category_id')::bigint = section_id limit 1),
    scheme.percent,
    0);
$$;

-- a × b / c rounded half away from zero, 0 when c is 0. Twin: mulDiv()
CREATE OR REPLACE FUNCTION "private"."payroll_mul_div"("a" numeric, "b" numeric, "c" numeric) RETURNS bigint
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case when c = 0 then 0::bigint else round(a * b / c)::bigint end;
$$;

-- Every line of a month (month_start: its first day), computed from the
-- work: see the header. SECURITY DEFINER: the whole clinic's work, whatever
-- deals the caller sees; the public functions check the rights.
CREATE OR REPLACE FUNCTION "private"."payroll_compute"("org_id" bigint, "month_start" "date") RETURNS TABLE("doctor_id" bigint, "sales_id" bigint, "scheme_id" bigint, "source" "text", "source_id" bigint, "work_day" "date", "patient_id" bigint, "patient_name" "text", "service_name" "text", "category_name" "text", "amount" bigint, "materials" bigint, "base" bigint, "percent" numeric, "accrued" bigint)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
#variable_conflict use_column
declare
  tz text := coalesce((select nullif(o.timezone, '') from public.organizations o where o.id = org_id), 'Asia/Almaty');
  month_end date := (month_start + interval '1 month')::date;
  from_at timestamp with time zone := month_start::timestamp at time zone tz;
  to_at timestamp with time zone := month_end::timestamp at time zone tz;
  rec record;
  scheme public.payroll_schemes;
  pct numeric;
  net bigint;
  line_base bigint;
  person record;
  total bigint;
  -- Σ accrued per person so far: { "d<doctor id>" | "s<sales id>": amount }
  totals jsonb := '{}'::jsonb;
  person_key text;
begin
  -- Done plan items
  for rec in
    with plans as (
      select distinct i.plan_id
      from public.treatment_plan_items i
      where i.organization_id = org_id and i.done and i.done_at >= from_at and i.done_at < to_at
    ),
    stage_sums as (
      select s.id, s.discount_percent, coalesce(sum(i.line_total), 0)::bigint as lines
      from public.treatment_stages s
        left join public.treatment_plan_items i on i.organization_id = s.organization_id and i.stage_id = s.id
      where s.organization_id = org_id and s.plan_id in (select plan_id from plans)
      group by s.id, s.discount_percent
    ),
    plan_sums as (
      select p.id, private.treatment_plan_subtotal(org_id, p.id) as subtotal, p.discount_percent, p.discount_amount,
        p.is_main, p.deal_id, p.patient_id, p.doctor_id
      from public.treatment_plans p
      where p.organization_id = org_id and p.id in (select plan_id from plans) and p.status <> 'declined'
    ),
    done as (
      select i.id, i.plan_id, i.service_id, i.name, i.quantity, i.done_at,
        coalesce(i.doctor_id, s.doctor_id, ps.doctor_id) as doctor_id, ps.patient_id,
        private.payroll_mul_div(
          i.line_total::numeric * private.treatment_stage_total(ss.lines, ss.discount_percent),
          private.treatment_plan_total(ps.subtotal, ps.discount_percent, ps.discount_amount),
          ss.lines::numeric * ps.subtotal) as amount
      from public.treatment_plan_items i
        join public.treatment_stages s on s.organization_id = i.organization_id and s.id = i.stage_id
        join stage_sums ss on ss.id = s.id
        join plan_sums ps on ps.id = i.plan_id
      where i.organization_id = org_id and i.done and i.done_at is not null and s.status <> 'cancelled'
    ),
    shares as (
      select d.plan_id, sum(d.amount)::bigint as done_amount,
        coalesce((
          select sum(o.paid_delta) from public.account_operations o
          where o.organization_id = org_id
            and (o.plan_id = d.plan_id or (ps.is_main and o.deal_id = ps.deal_id and o.plan_id is null))
        ), 0)::bigint as paid
      from done d join plan_sums ps on ps.id = d.plan_id
      group by d.plan_id, ps.is_main, ps.deal_id
    )
    select d.*, sh.done_amount, sh.paid,
      sv.category_id, c.parent_id as section_id, coalesce(sec.name, c.name) as category_name,
      coalesce(round(sc.cost_price * d.quantity)::bigint, 0) as cost,
      private.clinic_date(org_id, d.done_at) as day,
      nullif(btrim(concat_ws(' ', pt.last_name, pt.first_name)), '') as patient_name
    from done d
      join shares sh on sh.plan_id = d.plan_id
      left join public.services sv on sv.organization_id = org_id and sv.id = d.service_id
      left join public.service_categories c on c.organization_id = org_id and c.id = sv.category_id
      left join public.service_categories sec on sec.organization_id = org_id and sec.id = c.parent_id
      left join public.service_costs sc on sc.organization_id = org_id and sc.service_id = d.service_id
      left join public.patients pt on pt.organization_id = org_id and pt.id = d.patient_id
    where d.done_at >= from_at and d.done_at < to_at and d.doctor_id is not null
    order by d.done_at, d.id
  loop
    scheme := private.payroll_scheme_at(org_id, rec.doctor_id, null, rec.day);
    pct := case when scheme.id is null then 0 else private.payroll_percent(scheme, rec.category_id, rec.section_id) end;
    net := greatest(0, rec.amount - case when scheme.deduct_materials then rec.cost else 0 end);
    line_base := case when scheme.percent_base = 'paid' and rec.paid < rec.done_amount
      then private.payroll_mul_div(net, greatest(rec.paid, 0), rec.done_amount) else net end;
    doctor_id := rec.doctor_id;
    sales_id := null;
    scheme_id := scheme.id;
    source := 'plan_item';
    source_id := rec.id;
    work_day := rec.day;
    patient_id := rec.patient_id;
    patient_name := rec.patient_name;
    service_name := rec.name;
    category_name := rec.category_name;
    amount := rec.amount;
    materials := case when scheme.deduct_materials then rec.cost else 0 end;
    base := line_base;
    percent := pct;
    accrued := private.payroll_mul_div(line_base, pct, 100);
    person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
    totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
    return next;
  end loop;

  -- Completed visits of the CRM with a priced service, deal without a plan
  for rec in
    select v.id, v.doctor_id, v.patient_id, v.service_id, sv.name as service_name, round(sv.price)::bigint as price,
      sv.category_id, c.parent_id as section_id, coalesce(sec.name, c.name) as category_name,
      coalesce(round(sc.cost_price)::bigint, 0) as cost,
      coalesce((select sum(o.paid_delta) from public.account_operations o
        where o.organization_id = org_id and o.visit_id = v.id), 0)::bigint as paid,
      private.clinic_date(org_id, v.starts_at) as day,
      nullif(btrim(concat_ws(' ', pt.last_name, pt.first_name)), '') as patient_name
    from public.visits v
      join public.services sv on sv.organization_id = v.organization_id and sv.id = v.service_id
      left join public.service_categories c on c.organization_id = org_id and c.id = sv.category_id
      left join public.service_categories sec on sec.organization_id = org_id and sec.id = c.parent_id
      left join public.service_costs sc on sc.organization_id = org_id and sc.service_id = sv.id
      left join public.patients pt on pt.organization_id = org_id and pt.id = v.patient_id
    where v.organization_id = org_id and v.status = 'completed' and v.source = 'crm' and v.doctor_id is not null
      and sv.price > 0 and v.starts_at >= from_at and v.starts_at < to_at
      and not exists (
        select 1 from public.treatment_plans tp
        where tp.organization_id = v.organization_id and tp.deal_id = v.deal_id and tp.status <> 'declined')
    order by v.starts_at, v.id
  loop
    scheme := private.payroll_scheme_at(org_id, rec.doctor_id, null, rec.day);
    pct := case when scheme.id is null then 0 else private.payroll_percent(scheme, rec.category_id, rec.section_id) end;
    net := greatest(0, rec.price - case when scheme.deduct_materials then rec.cost else 0 end);
    line_base := case when scheme.percent_base = 'paid' and rec.paid < rec.price
      then private.payroll_mul_div(net, greatest(rec.paid, 0), rec.price) else net end;
    doctor_id := rec.doctor_id;
    sales_id := null;
    scheme_id := scheme.id;
    source := 'visit';
    source_id := rec.id;
    work_day := rec.day;
    patient_id := rec.patient_id;
    patient_name := rec.patient_name;
    service_name := rec.service_name;
    category_name := rec.category_name;
    amount := rec.price;
    materials := case when scheme.deduct_materials then rec.cost else 0 end;
    base := line_base;
    percent := pct;
    accrued := private.payroll_mul_div(line_base, pct, 100);
    person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
    totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
    return next;
  end loop;

  -- Payments of the deals of an employee of the CRM (percent of sales)
  for rec in
    select o.id, d.sales_id, o.patient_id, o.paid_delta, private.clinic_date(org_id, o.occurred_at) as day,
      d.name as deal_name,
      nullif(btrim(concat_ws(' ', pt.last_name, pt.first_name)), '') as patient_name
    from public.account_operations o
      join public.deals d on d.organization_id = o.organization_id and d.id = o.deal_id
      left join public.patients pt on pt.organization_id = org_id and pt.id = o.patient_id
    where o.organization_id = org_id and o.paid_delta <> 0 and d.sales_id is not null
      and o.occurred_at >= from_at and o.occurred_at < to_at
      and exists (select 1 from public.payroll_schemes s where s.organization_id = org_id and s.sales_id = d.sales_id)
    order by o.occurred_at, o.id
  loop
    scheme := private.payroll_scheme_at(org_id, null, rec.sales_id, rec.day);
    if scheme.id is null or scheme.percent = 0 then
      continue;
    end if;
    doctor_id := null;
    sales_id := rec.sales_id;
    scheme_id := scheme.id;
    source := 'payment';
    source_id := rec.id;
    work_day := rec.day;
    patient_id := rec.patient_id;
    patient_name := rec.patient_name;
    service_name := rec.deal_name;
    category_name := null;
    amount := rec.paid_delta;
    materials := 0;
    base := rec.paid_delta;
    percent := scheme.percent;
    accrued := private.payroll_mul_div(rec.paid_delta, scheme.percent, 100);
    person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
    totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
    return next;
  end loop;

  -- A fixed rate per completed visit: the doctor's, or the employee's who
  -- booked it
  for rec in
    select v.id, x.doctor_id, x.sales_id, v.patient_id, private.clinic_date(org_id, v.starts_at) as day,
      sv.name as service_name,
      nullif(btrim(concat_ws(' ', pt.last_name, pt.first_name)), '') as patient_name
    from public.visits v
      cross join lateral (
        select v.doctor_id, null::bigint as sales_id where v.doctor_id is not null
        union all
        select null::bigint, v.created_by where v.created_by is not null
      ) x
      left join public.services sv on sv.organization_id = v.organization_id and sv.id = v.service_id
      left join public.patients pt on pt.organization_id = org_id and pt.id = v.patient_id
    where v.organization_id = org_id and v.status = 'completed' and v.starts_at >= from_at and v.starts_at < to_at
      and exists (select 1 from public.payroll_schemes s where s.organization_id = org_id and s.visit_rate > 0
        and s.doctor_id is not distinct from x.doctor_id and s.sales_id is not distinct from x.sales_id)
    order by v.starts_at, v.id
  loop
    scheme := private.payroll_scheme_at(org_id, rec.doctor_id, rec.sales_id, rec.day);
    if scheme.id is null or scheme.visit_rate = 0 then
      continue;
    end if;
    doctor_id := rec.doctor_id;
    sales_id := rec.sales_id;
    scheme_id := scheme.id;
    source := 'visit_rate';
    source_id := rec.id;
    work_day := rec.day;
    patient_id := rec.patient_id;
    patient_name := rec.patient_name;
    service_name := rec.service_name;
    category_name := null;
    amount := scheme.visit_rate;
    materials := 0;
    base := scheme.visit_rate;
    percent := null;
    accrued := scheme.visit_rate;
    person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
    totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
    return next;
  end loop;

  -- The salary and the minimum: the scheme of the last day of the month
  for person in
    select distinct s.doctor_id, s.sales_id
    from public.payroll_schemes s
    where s.organization_id = org_id and s.effective_from < month_end
  loop
    scheme := private.payroll_scheme_at(org_id, person.doctor_id, person.sales_id, month_end - 1);
    if scheme.fixed_salary > 0 then
      doctor_id := person.doctor_id;
      sales_id := person.sales_id;
      scheme_id := scheme.id;
      source := 'fixed';
      source_id := null;
      work_day := null;
      patient_id := null;
      patient_name := null;
      service_name := null;
      category_name := null;
      amount := scheme.fixed_salary;
      materials := 0;
      base := scheme.fixed_salary;
      percent := null;
      accrued := scheme.fixed_salary;
      person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
      totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
      return next;
    end if;
    if scheme.min_guaranteed > 0 then
      total := coalesce((totals ->> case when person.doctor_id is not null then 'd' || person.doctor_id else 's' || person.sales_id end)::bigint, 0);
      if total < scheme.min_guaranteed then
        doctor_id := person.doctor_id;
        sales_id := person.sales_id;
        scheme_id := scheme.id;
        source := 'minimum';
        source_id := null;
        work_day := null;
        patient_id := null;
        patient_name := null;
        service_name := null;
        category_name := null;
        amount := scheme.min_guaranteed - total;
        materials := 0;
        base := scheme.min_guaranteed - total;
        percent := null;
        accrued := scheme.min_guaranteed - total;
        person_key := case when doctor_id is not null then 'd' || doctor_id else 's' || sales_id end;
        totals := totals || jsonb_build_object(person_key, coalesce((totals ->> person_key)::bigint, 0) + accrued);
        return next;
      end if;
    end if;
  end loop;
end;
$$;

-- The owner and the head only (money, stage 30)
CREATE OR REPLACE FUNCTION "private"."payroll_check_access"() RETURNS "void"
    LANGUAGE "plpgsql" STABLE
    SET "search_path" TO ''
    AS $$
begin
  if coalesce(private.current_user_role() in ('owner', 'head'), false) is false then
    raise exception 'Зарплаты видят только владелец и руководитель'
      using errcode = 'insufficient_privilege', hint = 'payroll_forbidden';
  end if;
