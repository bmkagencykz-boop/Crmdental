--
-- Stage 39: payroll of the doctors and the staff (see supabase/schemas/39_payroll.sql).
--

--
-- Payroll of the doctors and the staff (stage 39): «Зарплаты», like a dental
-- MIS — a doctor earns a percentage of the work they did.
--
--   payroll_schemes        the pay scheme of a doctor (or of an employee of
--                          the CRM: an assistant, an administrator), with
--                          its effective date (the history of schemes: the
--                          scheme of a day is the last one effective on that
--                          day):
--                            fixed_salary      «оклад» per month
--                            percent           of the work done
--                            percent_base      'price': of the price of the
--                                              work (with the discounts of
--                                              the plan); 'paid': of the part
--                                              the patient paid
--                            deduct_materials  the cost price of the service
--                                              (stage 35) is deducted first
--                            category_rates    [{category_id, percent}]: the
--                                              percentage of a section (or
--                                              subsection) of the price list
--                                              instead of the default one
--                                              («Ортопедия» 25 %, «Терапия»
--                                              30 %); a subsection's own rate
--                                              wins over its section's
--                            visit_rate        a fixed amount per completed
--                                              visit
--                            min_guaranteed    «минимум»: the month's accrual
--                                              (work, visits, salary) is
--                                              topped up to it
--   payroll_adjustments    manual lines of a month: bonus («премия»), penalty
--                          («штраф»), payout («выплата»)
--   payroll_months         a closed month: its lines are frozen in
--                          payroll_closed_lines; bonuses and penalties of a
--                          closed month cannot change (payouts can)
--
-- The work of a doctor in a month (private.payroll_compute):
--   plan_item  a done item of a treatment plan (not declined, stage not
--              cancelled), done that month in the clinic's time zone; its
--              doctor: the item's doctor, else the stage's, else the plan's.
--              Amount = line total × stage discount × plan discount, pro rata
--              (Σ amounts of a whole plan = its total).
--   visit      a completed visit of the CRM with a priced service whose deal
--              has no treatment plan (as the patient account of stage 36
--              charges it); amount = the service price.
--   visit_rate every completed visit of the doctor (CRM or MIS) × visit_rate.
-- For an employee of the CRM: payment (the services paid on the deals they
-- are responsible for: account_operations.paid_delta, a refund negative) and
-- visit_rate (completed visits they booked).
-- Then fixed (the salary of the scheme effective on the last day) and
-- minimum (the top-up to min_guaranteed).
--
-- A line: materials = cost price × quantity (when deducted); base = (amount −
-- materials, never below 0) × paid share in the 'paid' mode (paid share of a
-- plan = its payments / the amount of its done work, at most 1; of a visit =
-- its payments / its price); accrued = base × percent. Whole tenge, half
-- away from zero. Twin: src/components/atomic-crm/payroll/payrollMath.ts.
--
-- public.payroll_month(month) returns the month for the page: per doctor and
-- employee the scheme, the lines, the totals, bonuses, penalties, payouts,
-- the balance («остаток к выплате»), the count of overdue plan stages (a
-- stage of theirs with a past deadline in the month, not done), the days off
-- (weekly hours and exceptions of the schedule, stage 28) and a calendar of
-- the month (works and accrual per day).
--
-- Rights: the owner and the head only (money, stage 30): the tables, the
-- functions. A doctor is no user of the CRM: no self-view. Schemes,
-- adjustments and closings go to the audit log.
--

