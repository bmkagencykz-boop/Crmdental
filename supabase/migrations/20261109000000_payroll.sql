$$;

-- The lines of a month: frozen when it is closed, else computed
CREATE OR REPLACE FUNCTION "private"."payroll_month_lines"("org_id" bigint, "month_start" "date") RETURNS TABLE("doctor_id" bigint, "sales_id" bigint, "scheme_id" bigint, "source" "text", "source_id" bigint, "work_day" "date", "patient_id" bigint, "patient_name" "text", "service_name" "text", "category_name" "text", "amount" bigint, "materials" bigint, "base" bigint, "percent" numeric, "accrued" bigint)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
#variable_conflict use_column
begin
  if exists (select 1 from public.payroll_months m where m.organization_id = org_id and m.month = month_start) then
    return query
    select l.doctor_id, l.sales_id, l.scheme_id, l.source, l.source_id, l.work_day, l.patient_id, l.patient_name,
      l.service_name, l.category_name, l.amount, l.materials, l.base, l.percent, l.accrued
    from public.payroll_closed_lines l
    where l.organization_id = org_id and l.month = month_start
    order by l.id;
  else
    return query select * from private.payroll_compute(org_id, month_start);
  end if;
end;
$$;

-- A day off of a doctor: an exception without hours, else a weekday
-- missing from the weekly hours (no weekly hours: the clinic's, every day).
-- Twin: isDayOff()
CREATE OR REPLACE FUNCTION "private"."payroll_day_off"("org_id" bigint, "target_doctor_id" bigint, "day" "date") RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  exception_row public.doctor_exceptions;
  hours jsonb;
begin
  select * into exception_row from public.doctor_exceptions e
  where e.organization_id = org_id and e.doctor_id = target_doctor_id and e.day = payroll_day_off.day;
  if found then
    return exception_row.start_time is null;
  end if;
  select d.working_hours into hours from public.doctors d where d.organization_id = org_id and d.id = target_doctor_id;
  if hours is null or hours = '{}'::jsonb then
    return false;
  end if;
  return not (hours ? extract(isodow from day)::integer::text);
end;
$$;

-- «Зарплаты» of a month: see the header. The owner and the head.
CREATE OR REPLACE FUNCTION "public"."payroll_month"("target_month" "date") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  month_start date := date_trunc('month', target_month)::date;
  month_end date := (date_trunc('month', target_month) + interval '1 month')::date;
  today date := private.clinic_date(private.current_organization_id(), now());
  closing public.payroll_months;
  grouped jsonb;
  employees jsonb := '[]'::jsonb;
  person record;
  person_key text;
  person_lines jsonb;
  scheme public.payroll_schemes;
  adjustments jsonb;
  bonuses bigint;
  penalties bigint;
  payouts bigint;
  lines_accrued bigint;
  days jsonb;
begin
  perform private.payroll_check_access();
  if target_month is null then
    raise exception 'Укажите месяц' using errcode = '22023';
  end if;
  select * into closing from public.payroll_months m where m.organization_id = org_id and m.month = month_start;

  select coalesce(jsonb_object_agg(g.key, g.lines), '{}'::jsonb) into grouped
  from (
    select case when l.doctor_id is not null then 'd' || l.doctor_id else 's' || l.sales_id end as key,
      jsonb_agg(to_jsonb(l) order by l.work_day nulls last, l.source, l.source_id) as lines
    from private.payroll_month_lines(org_id, month_start) l
    group by 1
  ) g;

  for person in
    select 'doctor' as kind, d.id as doctor_id, null::bigint as sales_id, d.name, d.specialty, d.color,
      d.position, d.is_active
    from public.doctors d
    where d.organization_id = org_id
      and (d.is_active or grouped ? ('d' || d.id)
        or exists (select 1 from public.payroll_adjustments a where a.organization_id = org_id and a.doctor_id = d.id and a.month = month_start))
    union all
    select 'sales', null, s.id, btrim(concat_ws(' ', s.first_name, s.last_name)), s.role, null, 0, not s.disabled
    from public.sales s
    where s.organization_id = org_id
      and (grouped ? ('s' || s.id)
        or exists (select 1 from public.payroll_schemes p where p.organization_id = org_id and p.sales_id = s.id and p.effective_from < month_end)
        or exists (select 1 from public.payroll_adjustments a where a.organization_id = org_id and a.sales_id = s.id and a.month = month_start))
    order by 1, 7, 4
  loop
    person_key := case when person.doctor_id is not null then 'd' || person.doctor_id else 's' || person.sales_id end;
    person_lines := coalesce(grouped -> person_key, '[]'::jsonb);
    scheme := private.payroll_scheme_at(org_id, person.doctor_id, person.sales_id, month_end - 1);

    select coalesce(jsonb_agg(to_jsonb(a) order by a.occurred_on, a.id), '[]'::jsonb),
      coalesce(sum(a.amount) filter (where a.kind = 'bonus'), 0)::bigint,
      coalesce(sum(a.amount) filter (where a.kind = 'penalty'), 0)::bigint,
      coalesce(sum(a.amount) filter (where a.kind = 'payout'), 0)::bigint
    into adjustments, bonuses, penalties, payouts
    from public.payroll_adjustments a
    where a.organization_id = org_id and a.month = month_start
      and a.doctor_id is not distinct from person.doctor_id and a.sales_id is not distinct from person.sales_id;

    select coalesce(sum((l ->> 'accrued')::bigint), 0)::bigint into lines_accrued
    from jsonb_array_elements(person_lines) l;

    select jsonb_agg(jsonb_build_object(
        'day', g.day::date,
        'works', coalesce(w.works, 0),
        'amount', coalesce(w.amount, 0),
        'overdue', coalesce(o.overdue, 0),
        'off', person.doctor_id is not null and private.payroll_day_off(org_id, person.doctor_id, g.day::date))
      order by g.day)
    into days
    from generate_series(month_start, month_end - 1, interval '1 day') g(day)
      left join (
        select (l ->> 'work_day')::date as day,
          count(*) filter (where l ->> 'source' in ('plan_item', 'visit')) as works,
          sum((l ->> 'accrued')::bigint) as amount
        from jsonb_array_elements(person_lines) l
        where l ->> 'work_day' is not null
        group by 1
      ) w on w.day = g.day::date
      left join (
        select st.deadline as day, count(*) as overdue
        from public.treatment_stages st
          join public.treatment_plans p on p.organization_id = st.organization_id and p.id = st.plan_id
        where st.organization_id = org_id and person.doctor_id is not null
          and coalesce(st.doctor_id, p.doctor_id) = person.doctor_id
          and st.deadline >= month_start and st.deadline < month_end and st.deadline < today
          and st.status not in ('done', 'cancelled') and p.status <> 'declined'
        group by st.deadline
      ) o on o.day = g.day::date;

    employees := employees || jsonb_build_array(jsonb_build_object(
      'kind', person.kind,
      'doctor_id', person.doctor_id,
      'sales_id', person.sales_id,
      'name', person.name,
      'specialty', person.specialty,
      'color', person.color,
      'is_active', person.is_active,
      'scheme', case when scheme.id is not null then to_jsonb(scheme) end,
      'works_count', (select count(*) from jsonb_array_elements(person_lines) l where l ->> 'source' in ('plan_item', 'visit')),
      'work_amount', (select coalesce(sum((l ->> 'amount')::bigint), 0) from jsonb_array_elements(person_lines) l where l ->> 'source' in ('plan_item', 'visit', 'payment')),
      'materials', (select coalesce(sum((l ->> 'materials')::bigint), 0) from jsonb_array_elements(person_lines) l),
      'work_accrued', (select coalesce(sum((l ->> 'accrued')::bigint), 0) from jsonb_array_elements(person_lines) l where l ->> 'source' in ('plan_item', 'visit', 'payment')),
      'visits_count', (select count(*) from jsonb_array_elements(person_lines) l where l ->> 'source' = 'visit_rate'),
      'visits_accrued', (select coalesce(sum((l ->> 'accrued')::bigint), 0) from jsonb_array_elements(person_lines) l where l ->> 'source' = 'visit_rate'),
      'fixed', (select coalesce(sum((l ->> 'accrued')::bigint), 0) from jsonb_array_elements(person_lines) l where l ->> 'source' = 'fixed'),
      'minimum', (select coalesce(sum((l ->> 'accrued')::bigint), 0) from jsonb_array_elements(person_lines) l where l ->> 'source' = 'minimum'),
      'bonuses', bonuses,
      'penalties', penalties,
      'accrued', lines_accrued + bonuses - penalties,
      'paid_out', payouts,
      'balance', lines_accrued + bonuses - penalties - payouts,
      'overdue_count', (select coalesce(sum((d ->> 'overdue')::integer), 0) from jsonb_array_elements(days) d),
      'days_off', (select count(*) from jsonb_array_elements(days) d where (d ->> 'off')::boolean),
      'days', days,
      'lines', person_lines,
      'adjustments', adjustments));
  end loop;

  return jsonb_build_object(
    'month', month_start,
    'closed', closing.id is not null,
    'closed_at', closing.closed_at,
    'closed_by', closing.closed_by,
    'employees', employees);
end;
$$;

-- «Закрыть месяц»: its lines are frozen (the owner and the head)
CREATE OR REPLACE FUNCTION "public"."close_payroll_month"("target_month" "date") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  month_start date := date_trunc('month', target_month)::date;
  lines_count integer;
  total bigint;
begin
  perform private.payroll_check_access();
  if target_month is null or month_start > date_trunc('month', private.clinic_date(org_id, now()))::date then
    raise exception 'Нельзя закрыть месяц, который ещё не начался' using errcode = '22023';
  end if;
  if exists (select 1 from public.payroll_months m where m.organization_id = org_id and m.month = month_start) then
    raise exception 'Месяц уже закрыт' using errcode = '23505', hint = 'payroll_month_closed';
  end if;
  insert into public.payroll_months (organization_id, month) values (org_id, month_start);
  insert into public.payroll_closed_lines (organization_id, month, doctor_id, sales_id, scheme_id, source, source_id,
    work_day, patient_id, patient_name, service_name, category_name, amount, materials, base, percent, accrued)
  select org_id, month_start, l.doctor_id, l.sales_id, l.scheme_id, l.source, l.source_id, l.work_day, l.patient_id,
    l.patient_name, l.service_name, l.category_name, l.amount, l.materials, l.base, l.percent, l.accrued
  from private.payroll_compute(org_id, month_start) l;
  get diagnostics lines_count = row_count;
  select coalesce(sum(l.accrued), 0)::bigint into total
  from public.payroll_closed_lines l where l.organization_id = org_id and l.month = month_start;
  return jsonb_build_object('month', month_start, 'lines', lines_count, 'accrued', total);
end;
$$;

-- «Открыть месяц»: the owner only; the lines are computed again
CREATE OR REPLACE FUNCTION "public"."reopen_payroll_month"("target_month" "date") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
begin
  if private.current_user_role() is distinct from 'owner' then
    raise exception 'Открыть закрытый месяц может только владелец' using errcode = 'insufficient_privilege', hint = 'payroll_forbidden';
  end if;
  delete from public.payroll_months m
  where m.organization_id = org_id and m.month = date_trunc('month', target_month)::date;
  if not found then
    raise exception 'Месяц не закрыт' using errcode = 'P0002';
  end if;
end;
$$;

-- A scheme: the category rates checked and normalized
CREATE OR REPLACE FUNCTION "private"."handle_payroll_scheme_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  rate jsonb;
  rates jsonb := '[]'::jsonb;
  category bigint;
  rate_percent numeric;
begin
  for rate in select * from jsonb_array_elements(new.category_rates) loop
    if jsonb_typeof(rate) <> 'object' or jsonb_typeof(rate -> 'category_id') is distinct from 'number'
      or jsonb_typeof(rate -> 'percent') is distinct from 'number' then
      raise exception 'Процент направления: укажите раздел прайса и процент' using errcode = '22023';
    end if;
    category := (rate ->> 'category_id')::bigint;
    rate_percent := (rate ->> 'percent')::numeric;
    if rate_percent < 0 or rate_percent > 100 then
      raise exception 'Процент должен быть от 0 до 100' using errcode = '22023';
    end if;
    if not exists (select 1 from public.service_categories c where c.organization_id = new.organization_id and c.id = category) then
      raise exception 'Раздел прайса не найден' using errcode = '22023';
    end if;
    if rates @> jsonb_build_array(jsonb_build_object('category_id', category)) then
      raise exception 'Процент для раздела указан дважды' using errcode = '22023';
    end if;
    rates := rates || jsonb_build_array(jsonb_build_object('category_id', category, 'percent', round(rate_percent, 2)));
  end loop;
  new.category_rates := rates;
  new.updated_at := now();
  return new;
end;
$$;

-- Bonuses and penalties of a closed month are frozen (payouts are not);
-- the month is its first day
CREATE OR REPLACE FUNCTION "private"."handle_payroll_adjustment_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  -- Deleting the clinic, the doctor or the employee takes everything
  if tg_op = 'DELETE' and pg_trigger_depth() > 1 then
    return old;
  end if;
  if tg_op <> 'INSERT' and old.kind <> 'payout' and exists (
    select 1 from public.payroll_months m where m.organization_id = old.organization_id and m.month = old.month) then
    raise exception 'Месяц закрыт: премии и штрафы не меняются' using errcode = '22023', hint = 'payroll_month_closed';
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  new.month := date_trunc('month', new.month)::date;
  if new.kind <> 'payout' and exists (
    select 1 from public.payroll_months m where m.organization_id = new.organization_id and m.month = new.month) then
    raise exception 'Месяц закрыт: премии и штрафы не меняются' using errcode = '22023', hint = 'payroll_month_closed';
  end if;
  return new;
end;
$$;

