alter table public.payroll_adjustments
    add constraint payroll_adjustments_account_operation_id_fkey foreign key (organization_id, account_operation_id) references public.account_operations(organization_id, id) on delete cascade;

create table public.lab_payments (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    lab_id bigint not null,
    -- The month of the settlement it pays (its first day)
    month date not null,
    amount bigint not null,
    method text not null default 'bank_transfer',
    paid_at timestamp with time zone not null default now(),
    comment text,
    -- The expense of the cash desk («из кассы»)
