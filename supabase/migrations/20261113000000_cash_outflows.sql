--
-- Stage 42: money going out of the cash desk (see
-- supabase/schemas/42_cash_outflows.sql): expenses («Расход») with the
-- categories of a clinic, the payouts of the payroll and the new lab
-- payments linked to their expense, the lab settlement with paid and
-- balance, the plan item doctor copied with a plan, the data of the
-- existing clinics.
--

--
-- The clinic setting
--

-- «Администраторы проводят расходы из кассы»
alter table public.organization_settings add column manager_cash_expenses boolean not null default false;

--
-- Categories
--

create table public.cash_expense_categories (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    -- System categories: salary, lab, materials, rent, other
    code text,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint cash_expense_categories_name_not_blank check (btrim(name) <> ''),
    constraint cash_expense_categories_name_length check (char_length(name) <= 100),
    constraint cash_expense_categories_code_check check (code is null or code in ('salary', 'lab', 'materials', 'rent', 'other'))
);

alter table public.cash_expense_categories add constraint cash_expense_categories_organization_id_id_key unique (organization_id, id);
alter table public.cash_expense_categories
    add constraint cash_expense_categories_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade;
create unique index cash_expense_categories_code_idx on public.cash_expense_categories using btree (organization_id, code) where code is not null;
create unique index cash_expense_categories_name_idx on public.cash_expense_categories using btree (organization_id, lower(name));

--
-- Expenses in the ledger (account_operations of stage 36)
--

drop view public.account_operations_summary;
alter table public.account_operations drop column till_delta;
alter table public.account_operations add column till_delta bigint generated always as (
        case
            when method = 'deposit' or kind = 'correction' then 0
            when kind in ('payment', 'deposit') then amount
            when kind in ('refund', 'expense') then - amount
            else 0
        end) stored;
alter table public.account_operations add column category_id bigint;
alter table public.account_operations alter column patient_id drop not null;
alter table public.account_operations drop constraint account_operations_kind_check;
alter table public.account_operations add constraint account_operations_kind_check
    check (kind in ('payment', 'deposit', 'deposit_payment', 'refund', 'correction', 'expense'));
alter table public.account_operations drop constraint account_operations_kind_rules;
alter table public.account_operations add constraint account_operations_kind_rules check (
        case kind
            when 'payment' then account = 'services' and method <> 'deposit'
            when 'deposit' then account = 'deposit' and method not in ('deposit', 'other')
            when 'deposit_payment' then account = 'services' and method = 'deposit'
            when 'refund' then not (account = 'deposit' and method = 'deposit')
            when 'expense' then account = 'services' and method in ('cash', 'card', 'kaspi_qr', 'kaspi_transfer', 'bank_transfer')
            else method = 'other'
        end);
-- A patient's operation, or an expense: no patient, a category
alter table public.account_operations add constraint account_operations_expense_check
    check ((kind = 'expense') = (patient_id is null) and (kind = 'expense') = (category_id is not null));
alter table public.account_operations
    add constraint account_operations_category_id_fkey foreign key (organization_id, category_id) references public.cash_expense_categories(organization_id, id);
create index account_operations_category_id_idx on public.account_operations using btree (organization_id, category_id) where category_id is not null;

--
-- Links: payouts and lab payments
--

alter table public.payroll_adjustments add column account_operation_id bigint;
