-- The categories of a new clinic
CREATE OR REPLACE FUNCTION "private"."seed_cash_expense_categories"("org_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.cash_expense_categories (organization_id, name, code, position)
  select org_id, c.name, c.code, c.position
  from (values
    ('Зарплата', 'salary', 0),
    ('Лаборатория', 'lab', 1),
    ('Материалы', 'materials', 2),
    ('Аренда', 'rent', 3),
    ('Прочее', 'other', 4)
  ) as c(name, code, position)
  where not exists (
    select 1 from public.cash_expense_categories e
    where e.organization_id = org_id and (e.code = c.code or lower(e.name) = lower(c.name)));
end;
$$;

CREATE OR REPLACE FUNCTION "private"."handle_organization_cash_expense_categories"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  perform private.seed_cash_expense_categories(new.id);
  return new;
end;
$$;

-- The category of a system code in a clinic
CREATE OR REPLACE FUNCTION "private"."cash_expense_category_id"("org_id" bigint, "category_code" "text") RETURNS bigint
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return (select c.id from public.cash_expense_categories c where c.organization_id = org_id and c.code = category_code);
end;
$$;

-- Who records expenses: the owner and the head; an administrator when the
-- clinic allows it
CREATE OR REPLACE FUNCTION "private"."can_record_expense"() RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  role text := private.current_user_role();
begin
  if role in ('owner', 'head') then
    return true;
  end if;
  if role = 'manager' then
    return coalesce((
      select s.manager_cash_expenses from public.organization_settings s
      where s.organization_id = private.current_organization_id()), false);
  end if;
  return false;
end;
$$;

-- A system category keeps its code and is not deleted
CREATE OR REPLACE FUNCTION "private"."handle_cash_expense_category_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'DELETE' then
    if old.code is not null and pg_trigger_depth() = 1
      and exists (select 1 from public.organizations o where o.id = old.organization_id) then
      raise exception 'Системную статью расхода нельзя удалить — только переименовать или убрать в архив'
        using errcode = '22023', hint = 'expense_category_system';
    end if;
    return old;
  end if;
  if tg_op = 'INSERT' then
    if pg_trigger_depth() = 1 and private.current_user_role() is not null then
      new.code := null;
    end if;
  elsif new.code is distinct from old.code then
    raise exception 'Код системной статьи не меняется' using errcode = '22023', hint = 'expense_category_system';
  end if;
  new.name := btrim(new.name);
  return new;
end;
$$;

-- Before an operation is written (after the checks of stage 36): an
-- expense has no patient, deal, plan or visit, a category of the clinic, a
-- real method and a writer allowed to spend
CREATE OR REPLACE FUNCTION "private"."handle_account_operation_expense"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  sync text := coalesce(current_setting('crm.ledger_sync', true), '');
  category public.cash_expense_categories;
begin
  if new.kind <> 'expense' then
    if new.category_id is not null then
      raise exception 'Статья расхода указывается только у расхода' using errcode = '22023', hint = 'expense_category';
    end if;
    return new;
  end if;
  if tg_op = 'INSERT' then
    if new.patient_id is not null or new.deal_id is not null or new.plan_id is not null or new.visit_id is not null
      or cardinality(new.plan_item_ids) > 0 then
      raise exception 'Расход не связан с пациентом, сделкой или визитом' using errcode = '22023', hint = 'expense_patient';
    end if;
    if sync = '' and private.current_user_role() is not null and not private.can_record_expense() then
      raise exception 'Расходы из кассы проводят владелец и руководитель' using errcode = '42501', hint = 'expense_forbidden';
    end if;
    new.account := 'services';
    new.prepayment := false;
    new.cash_received := null;
  end if;
  if new.method not in ('cash', 'card', 'kaspi_qr', 'kaspi_transfer', 'bank_transfer') then
    raise exception 'Расход проводится наличными, картой, Kaspi или переводом' using errcode = '22023', hint = 'expense_method';
  end if;
  select * into category from public.cash_expense_categories c
  where c.organization_id = new.organization_id and c.id = new.category_id;
  if not found then
    raise exception 'Укажите статью расхода' using errcode = '22023', hint = 'expense_category';
  end if;
  if tg_op = 'UPDATE' and new.category_id is distinct from old.category_id then
    if exists (select 1 from public.payroll_adjustments a where a.account_operation_id = new.id)
      or exists (select 1 from public.lab_payments l where l.account_operation_id = new.id) then
      raise exception 'Это выплата зарплаты или оплата лаборатории: статья не меняется' using errcode = '22023', hint = 'expense_linked';
    end if;
  end if;
  if (tg_op = 'INSERT' or new.category_id is distinct from old.category_id) and not category.is_active then
    raise exception 'Статья расхода в архиве' using errcode = '22023', hint = 'expense_category_archived';
  end if;
  return new;
end;
$$;

-- The method and the time of an expense changed in the cash desk: its
-- payout or lab payment follows
CREATE OR REPLACE FUNCTION "private"."handle_expense_link_sync"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  perform set_config('crm.cash_link', 'on', true);
  update public.payroll_adjustments a
  set occurred_on = private.clinic_date(new.organization_id, new.occurred_at)
  where a.organization_id = new.organization_id and a.account_operation_id = new.id
    and a.occurred_on is distinct from private.clinic_date(new.organization_id, new.occurred_at);
  update public.lab_payments l
  set method = new.method, paid_at = new.occurred_at
  where l.organization_id = new.organization_id and l.account_operation_id = new.id
    and (l.method <> new.method or l.paid_at <> new.occurred_at);
  perform set_config('crm.cash_link', '', true);
  return null;
end;
$$;

-- A payout given from the cash desk: its operation is an expense of the
-- category Зарплата with the same amount; the link, the amount and the day
-- are the operation's
CREATE OR REPLACE FUNCTION "private"."handle_payroll_adjustment_cash_link"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  op public.account_operations;
begin
  if tg_op = 'UPDATE' then
    if new.account_operation_id is distinct from old.account_operation_id then
      raise exception 'Связь выплаты с кассой не меняется' using errcode = '22023', hint = 'cash_linked';
    end if;
    if old.account_operation_id is not null and coalesce(current_setting('crm.cash_link', true), '') <> 'on'
      and (new.amount <> old.amount or new.occurred_on <> old.occurred_on or new.kind <> old.kind) then
      raise exception 'Выплата проведена через кассу: сумму и дату меняют в кассе или отменяют выплату'
        using errcode = '22023', hint = 'cash_linked';
    end if;
    return new;
  end if;
  if new.account_operation_id is null then
    return new;
  end if;
  select * into op from public.account_operations o
  where o.organization_id = new.organization_id and o.id = new.account_operation_id;
  if not found or op.kind <> 'expense' or op.amount <> new.amount
    or op.category_id is distinct from private.cash_expense_category_id(new.organization_id, 'salary')
    or exists (select 1 from public.lab_payments l where l.account_operation_id = op.id) then
    raise exception 'Выплату связывают с расходом «Зарплата» той же суммы' using errcode = '22023', hint = 'cash_link_invalid';
  end if;
  new.occurred_on := private.clinic_date(new.organization_id, op.occurred_at);
  return new;
end;
$$;

-- A lab payment: the month is its first day; from the cash desk — the
-- expense of the category Лаборатория with the same amount gives the method
-- and the moment
CREATE OR REPLACE FUNCTION "private"."handle_lab_payment_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  op public.account_operations;
begin
  new.month := date_trunc('month', new.month)::date;
  new.comment := nullif(btrim(new.comment), '');
  if tg_op = 'UPDATE' then
    if new.account_operation_id is distinct from old.account_operation_id then
      raise exception 'Связь оплаты с кассой не меняется' using errcode = '22023', hint = 'cash_linked';
    end if;
    if new.lab_id <> old.lab_id and exists (select 1 from public.labs l where l.organization_id = new.organization_id and l.id = old.lab_id) then
      raise exception 'Оплату нельзя перенести в другую лабораторию' using errcode = '22023', hint = 'lab_payment_lab';
    end if;
    if old.account_operation_id is not null and coalesce(current_setting('crm.cash_link', true), '') <> 'on'
      and (new.amount <> old.amount or new.method <> old.method or new.paid_at <> old.paid_at) then
      raise exception 'Оплата проведена через кассу: сумму, способ и время меняют в кассе или отменяют оплату'
        using errcode = '22023', hint = 'cash_linked';
    end if;
    return new;
  end if;
  if pg_trigger_depth() = 1 and private.current_user_role() is not null then
    new.created_by := private.current_sales_id();
    new.created_at := now();
  end if;
  if new.account_operation_id is not null then
    select * into op from public.account_operations o
    where o.organization_id = new.organization_id and o.id = new.account_operation_id;
    if not found or op.kind <> 'expense' or op.amount <> new.amount
      or op.category_id is distinct from private.cash_expense_category_id(new.organization_id, 'lab')
      or exists (select 1 from public.payroll_adjustments a where a.account_operation_id = op.id) then
      raise exception 'Оплату лаборатории связывают с расходом «Лаборатория» той же суммы' using errcode = '22023', hint = 'cash_link_invalid';
    end if;
    new.method := op.method;
    new.paid_at := op.occurred_at;
  end if;
  return new;
end;
$$;

-- A payout or a lab payment deleted by an employee cancels its operation
-- (a cascade — the clinic, the doctor, the operation itself — does not)
CREATE OR REPLACE FUNCTION "private"."handle_cash_link_deleted"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if old.account_operation_id is not null and pg_trigger_depth() = 1 then
    delete from public.account_operations o
    where o.organization_id = old.organization_id and o.id = old.account_operation_id;
  end if;
  return null;
end;
$$;

-- The moment of a day-only date: now when it is today in the clinic, else
-- noon of that day
CREATE OR REPLACE FUNCTION "private"."cash_moment"("org_id" bigint, "day" "date") RETURNS timestamp with time zone
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if day is null then
    return now();
  end if;
  return private.payment_moment(org_id, day, now());
end;
$$;

-- «Выплата» of the payroll; «Выдать из кассы» (from_cash) writes the
-- expense Зарплата first (a cash payout needs the open shift of the
-- cashier). The owner and the head; a closed month still takes payouts.
CREATE OR REPLACE FUNCTION "public"."record_payroll_payout"("target_doctor_id" bigint, "target_sales_id" bigint, "target_month" "date", "payout_amount" bigint, "payout_day" "date" DEFAULT NULL::"date", "payout_note" "text" DEFAULT NULL::"text", "from_cash" boolean DEFAULT false, "payout_method" "text" DEFAULT 'cash'::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  person text;
  op_id bigint;
  adjustment_id bigint;
  moment timestamp with time zone;
begin
  perform private.payroll_check_access();
  if target_month is null or payout_amount is null or payout_amount <= 0 then
    raise exception 'Укажите месяц и сумму выплаты' using errcode = '22023';
  end if;
  if num_nonnulls(target_doctor_id, target_sales_id) <> 1 then
    raise exception 'Укажите врача или сотрудника' using errcode = '22023';
  end if;
  if target_doctor_id is not null then
    select d.name into person from public.doctors d where d.organization_id = org_id and d.id = target_doctor_id;
  else
    select btrim(concat_ws(' ', s.first_name, s.last_name)) into person
    from public.sales s where s.organization_id = org_id and s.id = target_sales_id;
  end if;
  if person is null then
    raise exception 'Сотрудник не найден' using errcode = 'P0002';
  end if;
  moment := private.cash_moment(org_id, payout_day);
  if from_cash then
    if coalesce(payout_method, 'cash') = 'cash' and not exists (
      select 1 from public.cash_shifts s
      where s.organization_id = org_id and s.sales_id = private.current_sales_id() and s.closed_at is null) then
      raise exception 'Откройте смену кассы, чтобы выдать наличные' using errcode = '22023', hint = 'shift_required';
    end if;
    insert into public.account_operations (organization_id, kind, amount, method, occurred_at, category_id, comment)
    values (org_id, 'expense', payout_amount, coalesce(payout_method, 'cash'), moment,
      private.cash_expense_category_id(org_id, 'salary'),
      left(concat_ws(' — ', 'Зарплата: ' || person || ', ' || to_char(date_trunc('month', target_month), 'MM.YYYY'),
        nullif(btrim(payout_note), '')), 1000))
    returning id into op_id;
  end if;
  insert into public.payroll_adjustments (organization_id, doctor_id, sales_id, month, kind, amount, note, occurred_on,
    account_operation_id)
  values (org_id, target_doctor_id, target_sales_id, date_trunc('month', target_month)::date, 'payout', payout_amount,
    nullif(btrim(payout_note), ''), coalesce(payout_day, private.clinic_date(org_id, now())), op_id)
  returning id into adjustment_id;
  return jsonb_build_object('adjustment_id', adjustment_id, 'operation_id', op_id);
end;
$$;

-- «Оплатить» a lab for a month; from_cash writes the expense Лаборатория
-- first (cash needs the open shift of the cashier). The owner and the head.
CREATE OR REPLACE FUNCTION "public"."record_lab_payment"("target_lab_id" bigint, "target_month" "date", "payment_amount" bigint, "payment_method" "text" DEFAULT 'bank_transfer'::"text", "payment_day" "date" DEFAULT NULL::"date", "payment_comment" "text" DEFAULT NULL::"text", "from_cash" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  lab_name text;
  op_id bigint;
  payment_id bigint;
  moment timestamp with time zone;
begin
  if org_id is null or coalesce(private.current_user_role() in ('owner', 'head'), false) is false then
    raise exception 'Оплату лаборатории проводят владелец и руководитель' using errcode = '42501', hint = 'lab_payment_forbidden';
  end if;
  if target_month is null or payment_amount is null or payment_amount <= 0 then
    raise exception 'Укажите месяц и сумму оплаты' using errcode = '22023';
  end if;
  select l.name into lab_name from public.labs l where l.organization_id = org_id and l.id = target_lab_id;
  if lab_name is null then
    raise exception 'Лаборатория не найдена' using errcode = 'P0002';
  end if;
  moment := private.cash_moment(org_id, payment_day);
  if from_cash then
    if coalesce(payment_method, 'cash') = 'cash' and not exists (
      select 1 from public.cash_shifts s
      where s.organization_id = org_id and s.sales_id = private.current_sales_id() and s.closed_at is null) then
      raise exception 'Откройте смену кассы, чтобы выдать наличные' using errcode = '22023', hint = 'shift_required';
    end if;
    insert into public.account_operations (organization_id, kind, amount, method, occurred_at, category_id, comment)
    values (org_id, 'expense', payment_amount, coalesce(payment_method, 'cash'), moment,
      private.cash_expense_category_id(org_id, 'lab'),
      left(concat_ws(' — ', 'Лаборатория: ' || lab_name || ', ' || to_char(date_trunc('month', target_month), 'MM.YYYY'),
        nullif(btrim(payment_comment), '')), 1000))
    returning id into op_id;
  end if;
  insert into public.lab_payments (organization_id, lab_id, month, amount, method, paid_at, comment, account_operation_id)
  values (org_id, target_lab_id, target_month, payment_amount, coalesce(payment_method, 'bank_transfer'), moment,
    payment_comment, op_id)
  returning id into payment_id;
  return jsonb_build_object('payment_id', payment_id, 'operation_id', op_id);
end;
$$;

-- Reports «Деньги» → «Расходы по статьям»: the expenses of the period by
-- category (the ledger), with the branch filter
CREATE OR REPLACE FUNCTION "public"."report_cash_expenses"("period_from" timestamp with time zone DEFAULT NULL::timestamp with time zone, "period_to" timestamp with time zone DEFAULT NULL::timestamp with time zone, "filter_branch_id" bigint DEFAULT NULL::bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE
    SET "search_path" TO ''
