    created_by bigint default private.current_sales_id(),
    created_at timestamp with time zone not null default now(),
    constraint lab_payments_month_check check (extract(day from month) = 1),
    constraint lab_payments_amount_check check (amount > 0 and amount <= 1000000000),
    constraint lab_payments_method_check check (method in ('cash', 'card', 'kaspi_qr', 'kaspi_transfer', 'bank_transfer', 'other')),
    constraint lab_payments_comment_length check (comment is null or char_length(comment) <= 1000)
