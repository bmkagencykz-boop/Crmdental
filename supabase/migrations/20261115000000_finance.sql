-- Stage 44: finance (see supabase/schemas/44_finance.sql) — money accounts,
-- the articles of the ДДС and the P&L, the method map, manual money
-- movements and accruals, the transactions linked to the payouts and the
-- lab payments paid without the cash desk, the reports report_cash_flow,
-- report_cash_flow_movements, report_pnl and the financial model
-- (report_finance_model); the data of the existing clinics.
