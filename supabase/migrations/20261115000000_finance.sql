-- The accounts, the method map and the articles of a new clinic; the
-- expense categories get their articles
CREATE OR REPLACE FUNCTION "private"."seed_finance"("org_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.finance_accounts (organization_id, name, kind, code, position)
  select org_id, a.name, a.kind, a.code, a.position
  from (values
    ('Касса', 'cash', 'till', 0),
    ('Kaspi', 'kaspi', 'kaspi', 1),
    ('Банк', 'bank', 'bank', 2)
  ) as a(name, kind, code, position)
  where not exists (
    select 1 from public.finance_accounts f
    where f.organization_id = org_id and (f.code = a.code or lower(f.name) = lower(a.name)));

  insert into public.finance_method_accounts (organization_id, method, account_id)
  select org_id, m.method, f.id
  from (values
    ('cash', 'till'),
    ('card', 'kaspi'),
    ('kaspi_qr', 'kaspi'),
    ('kaspi_transfer', 'kaspi'),
    ('bank_transfer', 'bank'),
    ('insurance', 'bank'),
    ('other', 'bank')
  ) as m(method, code)
    join public.finance_accounts f on f.organization_id = org_id and f.code = m.code
  on conflict (organization_id, method) do nothing;

  insert into public.finance_articles (organization_id, name, code, section, activity, pnl_line, position)
  select org_id, a.name, a.code, a.section, a.activity, a.pnl_line, a.position
  from (values
    ('Оплата услуг', 'services', 'in', 'operating', 'revenue', 0),
    ('Предоплаты и депозиты', 'prepayments', 'in', 'operating', null, 1),
    ('Возвраты пациентам', 'refunds', 'in', 'operating', null, 2),
    ('Прочие поступления', 'other_in', 'in', 'operating', 'other_income', 3),
    ('Кредиты и займы полученные', 'loans_in', 'in', 'financing', null, 4),
    ('Вклад собственника', 'owner_in', 'in', 'financing', null, 5),
    ('Зарплата врачей', 'salary_doctors', 'out', 'operating', 'doctors', 10),
    ('Зарплата персонала', 'salary_staff', 'out', 'operating', 'staff', 11),
    ('Лаборатория', 'lab', 'out', 'operating', 'lab', 12),
    ('Материалы', 'materials', 'out', 'operating', 'materials', 13),
    ('Аренда', 'rent', 'out', 'operating', 'opex', 14),
    ('Коммунальные услуги', 'utilities', 'out', 'operating', 'opex', 15),
    ('Маркетинг', 'marketing', 'out', 'operating', 'marketing', 16),
    ('Налоги', 'taxes', 'out', 'operating', 'tax', 17),
    ('Кредиты и лизинг', 'loans', 'out', 'financing', null, 18),
    ('Проценты по кредитам', 'interest', 'out', 'financing', 'interest', 19),
    ('Оборудование и ремонт', 'equipment', 'out', 'investing', null, 20),
    ('Дивиденды и вывод собственника', 'dividends', 'out', 'financing', null, 21),
    ('Амортизация', 'depreciation', 'out', 'operating', 'depreciation', 22),
    ('Прочие выплаты', 'other_out', 'out', 'operating', 'opex', 23)
  ) as a(name, code, section, activity, pnl_line, position)
  where not exists (
    select 1 from public.finance_articles f
    where f.organization_id = org_id and (f.code = a.code or lower(f.name) = lower(a.name)));

  update public.cash_expense_categories c
  set article_id = f.id
  from public.finance_articles f
  where c.organization_id = org_id and c.article_id is null and c.code is not null
    and f.organization_id = org_id
    and f.code = case c.code when 'salary' then 'salary_staff' when 'other' then 'other_out' else c.code end;
end;
$$;

