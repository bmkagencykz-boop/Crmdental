create table public.finance_accounts (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    kind text not null default 'bank',
    -- System accounts: till, kaspi, bank
    code text,
    opening_balance bigint not null default 0,
    opening_date date,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint finance_accounts_name_not_blank check (btrim(name) <> ''),
    constraint finance_accounts_name_length check (char_length(name) <= 100),
    constraint finance_accounts_kind_check check (kind in ('cash', 'bank', 'kaspi', 'other')),
    constraint finance_accounts_code_check check (code is null or code in ('till', 'kaspi', 'bank')),
    constraint finance_accounts_opening_check check (opening_balance between -100000000000 and 100000000000)
);

create table public.finance_articles (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    code text,
    section text not null,
    activity text not null default 'operating',
    pnl_line text,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint finance_articles_name_not_blank check (btrim(name) <> ''),
    constraint finance_articles_name_length check (char_length(name) <= 100),
    constraint finance_articles_section_check check (section in ('in', 'out')),
    constraint finance_articles_activity_check check (activity in ('operating', 'investing', 'financing')),
    constraint finance_articles_pnl_line_check check (pnl_line is null or pnl_line in (
        'revenue', 'other_income', 'materials', 'lab', 'doctors', 'staff', 'marketing', 'opex',
        'interest', 'depreciation', 'tax')),
    constraint finance_articles_code_check check (code is null or code in (
        'services', 'prepayments', 'refunds', 'other_in', 'loans_in', 'owner_in',
        'salary_doctors', 'salary_staff', 'lab', 'materials', 'rent', 'utilities', 'marketing', 'taxes',
        'loans', 'interest', 'equipment', 'dividends', 'depreciation', 'other_out'))
);

create table public.finance_method_accounts (
    organization_id bigint not null default private.current_organization_id(),
    method text not null,
    account_id bigint not null,
    constraint finance_method_accounts_pkey primary key (organization_id, method),
    constraint finance_method_accounts_method_check check (method in (
        'cash', 'card', 'kaspi_qr', 'kaspi_transfer', 'bank_transfer', 'insurance', 'other'))
);

create table public.finance_transactions (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    -- in, out, transfer (account → to_account), accrual (no money, P&L only)
    kind text not null,
    occurred_on date not null default CURRENT_DATE,
    account_id bigint,
    to_account_id bigint,
    article_id bigint,
    amount bigint not null,
    counterparty text,
    comment text,
    branch_id bigint,
    -- The payroll payout / lab payment paid without the cash desk
    payroll_adjustment_id bigint,
    lab_payment_id bigint,
    created_by bigint default private.current_sales_id(),
    created_at timestamp with time zone not null default now(),
    constraint finance_transactions_kind_check check (kind in ('in', 'out', 'transfer', 'accrual')),
    constraint finance_transactions_amount_check check (amount > 0 and amount <= 100000000000),
    constraint finance_transactions_kind_rules check (
        case kind
            when 'transfer' then account_id is not null and to_account_id is not null and account_id <> to_account_id
                and article_id is null
            when 'accrual' then account_id is null and to_account_id is null and article_id is not null
            else account_id is not null and to_account_id is null and article_id is not null
        end),
    constraint finance_transactions_link_check check (num_nonnulls(payroll_adjustment_id, lab_payment_id) <= 1
        and (num_nonnulls(payroll_adjustment_id, lab_payment_id) = 0 or kind = 'out')),
    constraint finance_transactions_counterparty_length check (counterparty is null or char_length(counterparty) <= 200),
    constraint finance_transactions_comment_length check (comment is null or char_length(comment) <= 1000)
);

