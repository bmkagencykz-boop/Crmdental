-- Every money movement of the clinic between two days (half-open, either
-- may be null) — see the header. amount: + into the account, − out of it.
CREATE OR REPLACE FUNCTION "private"."finance_movements"("org_id" bigint, "from_day" "date", "to_day" "date") RETURNS TABLE("source" "text", "source_id" bigint, "day" "date", "account_id" bigint, "article_id" bigint, "amount" bigint, "branch_id" bigint, "transfer" boolean, "counterparty" "text", "comment" "text")
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
#variable_conflict use_column
declare
  tz text := coalesce((select nullif(o.timezone, '') from public.organizations o where o.id = org_id), 'Asia/Almaty');
  from_at timestamp with time zone := case when from_day is null then null else from_day::timestamp at time zone tz end;
  to_at timestamp with time zone := case when to_day is null then null else to_day::timestamp at time zone tz end;
  a_services bigint := private.finance_article_id(org_id, 'services');
  a_prepayments bigint := private.finance_article_id(org_id, 'prepayments');
  a_refunds bigint := private.finance_article_id(org_id, 'refunds');
  a_doctors bigint := private.finance_article_id(org_id, 'salary_doctors');
  a_staff bigint := private.finance_article_id(org_id, 'salary_staff');
  a_other bigint := private.finance_article_id(org_id, 'other_out');
begin
  return query
  select 'operation'::text, o.id, (o.occurred_at at time zone tz)::date, m.account_id,
    case o.kind
      when 'payment' then case when o.prepayment then a_prepayments else a_services end
      when 'deposit' then a_prepayments
      when 'refund' then a_refunds
      else coalesce(case when pa.id is null then null when pa.doctor_id is not null then a_doctors else a_staff end,
        c.article_id, a_other)
    end,
    (sign(o.till_delta) * part.amount)::bigint,
    o.branch_id, false,
    coalesce(nullif(btrim(concat_ws(' ', pt.last_name, pt.first_name)), ''), c.name),
    o.comment
  from public.account_operations o
    cross join lateral (
      select p ->> 'method' as method, (p ->> 'amount')::bigint as amount
      from jsonb_array_elements(o.parts) p
      where o.method = 'mixed'
      union all
      select o.method, o.amount where o.method <> 'mixed'
    ) part
    left join public.finance_method_accounts m on m.organization_id = o.organization_id and m.method = part.method
    left join public.cash_expense_categories c on c.organization_id = o.organization_id and c.id = o.category_id
    left join public.payroll_adjustments pa on pa.organization_id = o.organization_id and pa.account_operation_id = o.id
    left join public.patients pt on pt.organization_id = o.organization_id and pt.id = o.patient_id
  where o.organization_id = org_id and o.till_delta <> 0 and part.amount <> 0
    and (from_at is null or o.occurred_at >= from_at)
    and (to_at is null or o.occurred_at < to_at)
  union all
  select 'transaction'::text, t.id, t.occurred_on, x.account_id, t.article_id, x.amount, t.branch_id, t.kind = 'transfer',
    t.counterparty, t.comment
  from public.finance_transactions t
    cross join lateral (
      select t.account_id, case when t.kind = 'in' then t.amount else - t.amount end as amount
      union all
      select t.to_account_id, t.amount where t.kind = 'transfer'
    ) x
  where t.organization_id = org_id and t.kind <> 'accrual'
    and (from_day is null or t.occurred_on >= from_day)
    and (to_day is null or t.occurred_on < to_day);
end;
$$;

-- The bucket of a day: its day, the Monday of its week, the first of its month
CREATE OR REPLACE FUNCTION "private"."finance_bucket"("day" "date", "granularity" "text") RETURNS "date"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select date_trunc(granularity, day::timestamp)::date;
$$;

-- «ДДС»: the cash flow statement between two days (half-open) by day, week
-- or month, with the balances of the accounts (see the header)
CREATE OR REPLACE FUNCTION "public"."report_cash_flow"("period_from" "date", "period_to" "date", "filter_branch_id" bigint DEFAULT NULL::bigint, "granularity" "text" DEFAULT 'month'::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  step interval;
  periods date[];
  result jsonb;
begin
  if not private.finance_can_view() then
    raise exception 'Нет доступа к финансам' using errcode = 'insufficient_privilege', hint = 'finance_forbidden';
  end if;
  if period_from is null or period_to is null or period_to <= period_from then
    raise exception 'Укажите период' using errcode = '22023', hint = 'finance_period';
  end if;
  if granularity not in ('day', 'week', 'month') then
    raise exception 'Разбивка — по дням, неделям или месяцам' using errcode = '22023', hint = 'finance_granularity';
  end if;
  step := ('1 ' || granularity)::interval;
  select array_agg(g::date order by g) into periods
  from generate_series(private.finance_bucket(period_from, granularity)::timestamp,
    private.finance_bucket(period_to - 1, granularity)::timestamp, step) g;
  if cardinality(periods) > 400 then
    raise exception 'Слишком длинный период для такой разбивки' using errcode = '22023', hint = 'finance_period';
  end if;

  with mv as (
    select m.*, private.finance_bucket(m.day, granularity) as period
    from private.finance_movements(org_id, null, period_to) m
    where filter_branch_id is null or m.branch_id = filter_branch_id
  ),
  inside as (
    select * from mv where mv.day >= period_from
  ),
  article_rows as (
    select i.article_id, i.period, sum(i.amount)::bigint as amount
    from inside i where not i.transfer
    group by i.article_id, i.period
  ),
  accounts as (
    select a.id as account_id, a.opening_balance, a.opening_date, a.position
    from public.finance_accounts a where a.organization_id = org_id
    union all
    select null::bigint, 0::bigint, null::date, 1000000
    where exists (select 1 from mv where mv.account_id is null)
  ),
  balances as (
    select a.account_id, a.position,
      case when filter_branch_id is null then
        a.opening_balance
        + coalesce((select sum(m.amount) from mv m where m.account_id is not distinct from a.account_id and m.day < period_from), 0)
        - coalesce((select sum(m.amount) from mv m where m.account_id is not distinct from a.account_id and m.day < a.opening_date), 0)
      end::bigint as opening,
      coalesce((select sum(i.amount) from inside i where i.account_id is not distinct from a.account_id), 0)::bigint as flow,
      coalesce((
        select jsonb_agg(jsonb_build_object('period', f.period, 'amount', f.amount) order by f.period)
        from (select i.period, sum(i.amount)::bigint as amount from inside i
          where i.account_id is not distinct from a.account_id group by i.period) f
      ), '[]'::jsonb) as flows
    from accounts a
  ),
  per as (
    select p.period,
      coalesce(sum(i.amount) filter (where not i.transfer and ar.section = 'in'), 0)::bigint as inflow,
      coalesce(- sum(i.amount) filter (where not i.transfer and ar.section = 'out'), 0)::bigint as outflow,
      coalesce(sum(i.amount) filter (where not i.transfer), 0)::bigint as net
    from unnest(periods) as p(period)
      left join inside i on i.period = p.period
      left join public.finance_articles ar on ar.organization_id = org_id and ar.id = i.article_id
    group by p.period
  ),
  opening as (
    select case when filter_branch_id is null then sum(b.opening)::bigint end as total from balances b
  ),
  totals as (
    select per.*,
      (o.total + coalesce(sum(per.net) over (order by per.period rows between unbounded preceding and 1 preceding), 0))::bigint as opening,
      (o.total + sum(per.net) over (order by per.period rows between unbounded preceding and current row))::bigint as closing
    from per cross join opening o
  )
  select jsonb_build_object(
    'granularity', granularity,
    'from', period_from,
    'to', period_to,
    'periods', to_jsonb(periods),
    'balances', filter_branch_id is null,
    'rows', coalesce((select jsonb_agg(jsonb_build_object('article_id', r.article_id, 'period', r.period, 'amount', r.amount)
      order by r.article_id, r.period) from article_rows r), '[]'::jsonb),
    'accounts', coalesce((select jsonb_agg(jsonb_build_object('account_id', b.account_id, 'opening', b.opening,
      'closing', b.opening + b.flow, 'flow', b.flow, 'flows', b.flows) order by b.position, b.account_id) from balances b), '[]'::jsonb),
    'totals', coalesce((select jsonb_agg(jsonb_build_object('period', t.period, 'inflow', t.inflow, 'outflow', t.outflow,
      'net', t.net, 'opening', t.opening, 'closing', t.closing) order by t.period) from totals t), '[]'::jsonb),
    'total', (select jsonb_build_object('inflow', coalesce(sum(t.inflow), 0), 'outflow', coalesce(sum(t.outflow), 0),
      'net', coalesce(sum(t.net), 0), 'opening', (select o.total from opening o),
      'closing', (select o.total from opening o) + coalesce(sum(t.net), 0)) from per t)
  ) into result;
  return result;
end;
$$;

-- The drill-down of a cell of the ДДС: the movements of the period with the
-- article (or the transfers: filter_transfers) and / or the account
CREATE OR REPLACE FUNCTION "public"."report_cash_flow_movements"("period_from" "date", "period_to" "date", "filter_branch_id" bigint DEFAULT NULL::bigint, "filter_article_id" bigint DEFAULT NULL::bigint, "filter_account_id" bigint DEFAULT NULL::bigint, "filter_transfers" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not private.finance_can_view() then
    raise exception 'Нет доступа к финансам' using errcode = 'insufficient_privilege', hint = 'finance_forbidden';
  end if;
  return coalesce((
    select jsonb_agg(to_jsonb(m) order by m.day desc, m.source, m.source_id desc)
    from (
      select * from private.finance_movements(private.current_organization_id(), period_from, period_to) x
      where (filter_branch_id is null or x.branch_id = filter_branch_id)
        and (filter_article_id is null or x.article_id = filter_article_id)
        and (filter_account_id is null or x.account_id = filter_account_id)
        and (not filter_transfers or x.transfer)
      order by x.day desc, x.source, x.source_id desc
      limit 1000
    ) m
  ), '[]'::jsonb);
end;
$$;

-- Services rendered between two moments (see the header: the recognition of
-- private.payroll_compute for the plan items, of the patient account for
-- the visits), with the cost price of their materials
CREATE OR REPLACE FUNCTION "private"."finance_revenue_items"("org_id" bigint, "from_at" timestamp with time zone, "to_at" timestamp with time zone) RETURNS TABLE("source" "text", "source_id" bigint, "done_at" timestamp with time zone, "amount" bigint, "cost" bigint, "branch_id" bigint, "doctor_id" bigint)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
#variable_conflict use_column
begin
  return query
  with plans as (
    select distinct i.plan_id
    from public.treatment_plan_items i
    where i.organization_id = org_id and i.done and i.done_at >= from_at and i.done_at < to_at
  ),
  stage_sums as (
    select s.id, s.discount_percent, coalesce(sum(i.line_total), 0)::bigint as lines
    from public.treatment_stages s
      left join public.treatment_plan_items i on i.organization_id = s.organization_id and i.stage_id = s.id
    where s.organization_id = org_id and s.plan_id in (select plan_id from plans)
    group by s.id, s.discount_percent
  ),
  plan_sums as (
    select p.id, private.treatment_plan_subtotal(org_id, p.id) as subtotal, p.discount_percent, p.discount_amount,
      p.deal_id, p.doctor_id
    from public.treatment_plans p
    where p.organization_id = org_id and p.id in (select plan_id from plans) and p.status <> 'declined'
  )
  select 'plan_item'::text, i.id, i.done_at,
    private.payroll_mul_div(
      i.line_total::numeric * private.treatment_stage_total(ss.lines, ss.discount_percent),
      private.treatment_plan_total(ps.subtotal, ps.discount_percent, ps.discount_amount),
      ss.lines::numeric * ps.subtotal),
    coalesce(round(sc.cost_price * i.quantity)::bigint, 0),
    d.branch_id,
    coalesce(i.doctor_id, s.doctor_id, ps.doctor_id)
  from public.treatment_plan_items i
    join public.treatment_stages s on s.organization_id = i.organization_id and s.id = i.stage_id
    join stage_sums ss on ss.id = s.id
    join plan_sums ps on ps.id = i.plan_id
    left join public.deals d on d.organization_id = org_id and d.id = ps.deal_id
    left join public.service_costs sc on sc.organization_id = org_id and sc.service_id = i.service_id
  where i.organization_id = org_id and i.done and i.done_at >= from_at and i.done_at < to_at and s.status <> 'cancelled'
  union all
  select 'visit'::text, v.id, v.starts_at, round(sv.price)::bigint, coalesce(round(sc.cost_price)::bigint, 0),
    v.branch_id, v.doctor_id
  from public.visits v
    join public.services sv on sv.organization_id = v.organization_id and sv.id = v.service_id
    left join public.service_costs sc on sc.organization_id = org_id and sc.service_id = sv.id
  where v.organization_id = org_id and v.status = 'completed' and v.source = 'crm'
    and sv.price > 0 and v.starts_at >= from_at and v.starts_at < to_at
    and not exists (
      select 1 from public.treatment_plans tp
      where tp.organization_id = v.organization_id and tp.deal_id = v.deal_id and tp.status <> 'declined');
end;
$$;

-- Every amount of the P&L between two months (from_month included,
-- to_month excluded): (month, line, source, article, branch, amount).
-- Income lines (revenue, other_income) and cost lines are positive;
-- refunds are a line of their own, subtracted from the revenue.
CREATE OR REPLACE FUNCTION "private"."finance_pnl_facts"("org_id" bigint, "from_month" "date", "to_month" "date") RETURNS TABLE("month" "date", "line" "text", "source" "text", "article_id" bigint, "branch_id" bigint, "amount" bigint)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
#variable_conflict use_column
declare
  tz text := coalesce((select nullif(o.timezone, '') from public.organizations o where o.id = org_id), 'Asia/Almaty');
  from_at timestamp with time zone := from_month::timestamp at time zone tz;
  to_at timestamp with time zone := to_month::timestamp at time zone tz;
begin
  -- Services rendered and their materials
  return query
  select date_trunc('month', r.done_at at time zone tz)::date, x.line, 'services'::text, null::bigint, r.branch_id, x.amount
  from private.finance_revenue_items(org_id, from_at, to_at) r
    cross join lateral (values ('revenue', r.amount), ('materials', r.cost)) as x(line, amount)
  where x.amount <> 0;

  -- Refunds of services
  return query
  select date_trunc('month', o.occurred_at at time zone tz)::date, 'refunds'::text, 'refunds'::text, null::bigint,
    o.branch_id, o.amount
  from public.account_operations o
  where o.organization_id = org_id and o.kind = 'refund' and o.account = 'services'
    and o.occurred_at >= from_at and o.occurred_at < to_at;

  -- The lab (stage 40; the costs stage 43 marks free are 0 there)
  return query
  select c.month, 'lab'::text, 'lab'::text, null::bigint, c.branch_id, c.amount
  from public.lab_order_costs c
  where c.organization_id = org_id and c.month >= from_month and c.month < to_month and c.amount <> 0;

  -- Payroll: doctors' variable pay (cost of sales), the staff and the
  -- doctors' fixed salaries (operating)
  return query
  select m.month::date,
    case when l.doctor_id is not null and l.source <> 'fixed' then 'doctors' else 'staff' end,
    'payroll'::text, null::bigint, d.branch_id, l.accrued
  from generate_series(from_month::timestamp, (to_month - 1)::timestamp, interval '1 month') m(month)
    cross join lateral private.payroll_month_lines(org_id, m.month::date) l
    left join public.doctors d on d.organization_id = org_id and d.id = l.doctor_id
  where l.accrued <> 0;
  return query
  select a.month, case when a.doctor_id is not null then 'doctors' else 'staff' end, 'payroll'::text, null::bigint,
    d.branch_id, case when a.kind = 'bonus' then a.amount else - a.amount end
  from public.payroll_adjustments a
    left join public.doctors d on d.organization_id = org_id and d.id = a.doctor_id
  where a.organization_id = org_id and a.kind in ('bonus', 'penalty') and a.month >= from_month and a.month < to_month;

  -- Advertising (stage 32), spread over its days
  return query
  select m.month::date, 'marketing'::text, 'ad_spend'::text, null::bigint, null::bigint,
    round(s.amount * (least(s.spent_to + 1, (m.month + interval '1 month')::date) - greatest(s.spent_from, m.month::date))::numeric
      / (s.spent_to + 1 - s.spent_from))::bigint
  from public.ad_spend s
    cross join lateral generate_series(date_trunc('month', greatest(s.spent_from, from_month)::timestamp),
      date_trunc('month', least(s.spent_to, to_month - 1)::timestamp), interval '1 month') m(month)
  where s.organization_id = org_id and s.spent_to >= from_month and s.spent_from < to_month and s.amount > 0;

  -- Payments on articles of cash-basis lines (by the day they were paid)
  return query
  select date_trunc('month', mv.day)::date, ar.pnl_line, 'cash'::text, ar.id, mv.branch_id,
    case when ar.pnl_line = 'other_income' then mv.amount else - mv.amount end
  from private.finance_movements(org_id, from_month, to_month) mv
    join public.finance_articles ar on ar.organization_id = org_id and ar.id = mv.article_id
  where not mv.transfer and ar.pnl_line in ('other_income', 'marketing', 'opex', 'interest', 'depreciation', 'tax');

  -- Accruals («начисление»)
  return query
  select date_trunc('month', t.occurred_on)::date, ar.pnl_line, 'manual'::text, ar.id, t.branch_id, t.amount
  from public.finance_transactions t
    join public.finance_articles ar on ar.organization_id = org_id and ar.id = t.article_id
  where t.organization_id = org_id and t.kind = 'accrual' and ar.pnl_line is not null
    and t.occurred_on >= from_month and t.occurred_on < to_month;
end;
$$;

-- A rounded share in percent (one decimal), null without a base
CREATE OR REPLACE FUNCTION "private"."finance_share"("part" numeric, "whole" numeric) RETURNS numeric
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case when whole is null or whole = 0 then null else round(part * 100 / whole, 1) end;
$$;

-- a / b rounded, null when b is 0
CREATE OR REPLACE FUNCTION "private"."finance_ratio"("a" numeric, "b" numeric) RETURNS bigint
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case when b is null or b = 0 then null else round(a / b)::bigint end;
$$;

-- The P&L of a clinic (no rights check: public.report_pnl and the model)
CREATE OR REPLACE FUNCTION "private"."finance_pnl"("org_id" bigint, "from_month" "date", "to_month" "date", "filter_branch_id" bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  tz text := coalesce((select nullif(o.timezone, '') from public.organizations o where o.id = org_id), 'Asia/Almaty');
  chair_count bigint;
  result jsonb;
begin
  select count(*) into chair_count from public.chairs c
  where c.organization_id = org_id and c.is_active and (filter_branch_id is null or c.branch_id = filter_branch_id);

  with facts as (
    select * from private.finance_pnl_facts(org_id, from_month, to_month) f
    where filter_branch_id is null or f.branch_id = filter_branch_id
  ),
  months as (
    select g::date as month from generate_series(from_month::timestamp, (to_month - 1)::timestamp, interval '1 month') g
  ),
  fact_rows as (
    select f.month, f.line, f.source, f.article_id, sum(f.amount)::bigint as amount
    from facts f group by f.month, f.line, f.source, f.article_id
  ),
  visits as (
    select date_trunc('month', v.starts_at at time zone tz)::date as month, count(*)::bigint as visits
    from public.visits v
    where v.organization_id = org_id and v.status = 'completed'
      and v.starts_at >= from_month::timestamp at time zone tz and v.starts_at < to_month::timestamp at time zone tz
      and (filter_branch_id is null or v.branch_id = filter_branch_id)
    group by 1
  ),
  lines as (
    select m.month,
      coalesce(sum(f.amount) filter (where f.line = 'revenue'), 0) - coalesce(sum(f.amount) filter (where f.line = 'refunds'), 0) as revenue,
      coalesce(sum(f.amount) filter (where f.line = 'refunds'), 0) as refunds,
      coalesce(sum(f.amount) filter (where f.line = 'revenue' and f.source = 'services'), 0)
        - coalesce(sum(f.amount) filter (where f.line = 'refunds'), 0) as services,
      coalesce(sum(f.amount) filter (where f.line = 'materials'), 0) as materials,
      coalesce(sum(f.amount) filter (where f.line = 'lab'), 0) as lab,
      coalesce(sum(f.amount) filter (where f.line = 'doctors'), 0) as doctors,
      coalesce(sum(f.amount) filter (where f.line = 'staff'), 0) as staff,
      coalesce(sum(f.amount) filter (where f.line = 'marketing'), 0) as marketing,
      coalesce(sum(f.amount) filter (where f.line = 'opex'), 0) as opex_other,
      coalesce(sum(f.amount) filter (where f.line = 'other_income'), 0) as other_income,
      coalesce(sum(f.amount) filter (where f.line = 'interest'), 0) as interest,
      coalesce(sum(f.amount) filter (where f.line = 'depreciation'), 0) as depreciation,
      coalesce(sum(f.amount) filter (where f.line = 'tax'), 0) as tax,
      coalesce(max(v.visits), 0) as visits
    from months m
      left join facts f on f.month = m.month
      left join visits v on v.month = m.month
    group by m.month
  ),
  summary as (
    select l.*,
      l.materials + l.lab + l.doctors as cogs,
      l.revenue - (l.materials + l.lab + l.doctors) as gross,
      l.staff + l.marketing + l.opex_other as opex,
      l.revenue - (l.materials + l.lab + l.doctors) - (l.staff + l.marketing + l.opex_other) + l.other_income as ebitda
    from lines l
  ),
  total as (
    select sum(s.revenue) as revenue, sum(s.refunds) as refunds, sum(s.services) as services, sum(s.materials) as materials, sum(s.lab) as lab,
      sum(s.doctors) as doctors, sum(s.staff) as staff, sum(s.marketing) as marketing, sum(s.opex_other) as opex_other,
      sum(s.other_income) as other_income, sum(s.interest) as interest, sum(s.depreciation) as depreciation,
      sum(s.tax) as tax, sum(s.visits) as visits, sum(s.cogs) as cogs, sum(s.gross) as gross, sum(s.opex) as opex,
      sum(s.ebitda) as ebitda, count(*) as months
    from summary s
  )
  select jsonb_build_object(
    'from', from_month,
    'to', to_month,
    'chairs', chair_count,
    'months', (select jsonb_agg(m.month order by m.month) from months m),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('month', r.month, 'line', r.line, 'source', r.source,
      'article_id', r.article_id, 'amount', r.amount) order by r.month, r.line, r.source, r.article_id) from fact_rows r), '[]'::jsonb),
    'summary', (select jsonb_agg(jsonb_build_object(
        'month', s.month, 'revenue', s.revenue, 'refunds', s.refunds, 'materials', s.materials, 'lab', s.lab,
        'doctors', s.doctors, 'staff', s.staff, 'marketing', s.marketing, 'opex_other', s.opex_other,
        'other_income', s.other_income, 'interest', s.interest, 'depreciation', s.depreciation, 'tax', s.tax,
        'cogs', s.cogs, 'gross', s.gross, 'opex', s.opex, 'ebitda', s.ebitda,
        'net', s.ebitda - s.interest - s.depreciation - s.tax,
        'gross_margin', private.finance_share(s.gross, s.revenue),
        'net_margin', private.finance_share(s.ebitda - s.interest - s.depreciation - s.tax, s.revenue),
        'visits', s.visits,
        'avg_check', private.finance_ratio(s.services, s.visits),
        'revenue_per_chair', private.finance_ratio(s.revenue, chair_count),
        'lab_share', private.finance_share(s.lab, s.revenue),
        'payroll_share', private.finance_share(s.doctors + s.staff, s.revenue)
      ) order by s.month) from summary s),
    'total', (select jsonb_build_object(
        'revenue', t.revenue, 'refunds', t.refunds, 'materials', t.materials, 'lab', t.lab, 'doctors', t.doctors,
        'staff', t.staff, 'marketing', t.marketing, 'opex_other', t.opex_other, 'other_income', t.other_income,
        'interest', t.interest, 'depreciation', t.depreciation, 'tax', t.tax, 'cogs', t.cogs, 'gross', t.gross,
        'opex', t.opex, 'ebitda', t.ebitda, 'net', t.ebitda - t.interest - t.depreciation - t.tax,
        'gross_margin', private.finance_share(t.gross, t.revenue),
        'net_margin', private.finance_share(t.ebitda - t.interest - t.depreciation - t.tax, t.revenue),
        'visits', t.visits,
        'avg_check', private.finance_ratio(t.services, t.visits),
        'revenue_per_chair', private.finance_ratio(t.revenue, chair_count * t.months),
        'lab_share', private.finance_share(t.lab, t.revenue),
        'payroll_share', private.finance_share(t.doctors + t.staff, t.revenue)
      ) from total t)
  ) into result;
  return result;
end;
$$;

-- «ПиУ»: the P&L by month between two months (from included, to excluded;
-- any day of a month means that month). The owner and the head.
CREATE OR REPLACE FUNCTION "public"."report_pnl"("period_from" "date", "period_to" "date", "filter_branch_id" bigint DEFAULT NULL::bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  from_month date := date_trunc('month', period_from)::date;
  to_month date := date_trunc('month', period_to)::date;
begin
  if not private.finance_can_edit() then
    raise exception 'ПиУ видят только владелец и руководитель' using errcode = 'insufficient_privilege', hint = 'finance_forbidden';
  end if;
  if period_from is null or period_to is null or to_month <= from_month then
    raise exception 'Укажите период' using errcode = '22023', hint = 'finance_period';
  end if;
  if to_month > (from_month + interval '36 months')::date then
    raise exception 'Не больше 36 месяцев' using errcode = '22023', hint = 'finance_period';
  end if;
  return private.finance_pnl(private.current_organization_id(), from_month, to_month, filter_branch_id);
end;
$$;

-- The plan of a model for a scenario (base, optimistic, pessimistic):
-- visits = round(chairs × days × hours × visits per chair-hour ×
-- utilization % × factor), revenue = visits × average check; the lines
-- (fixed, % of revenue) by their P&L line; break-even; the cash plan and
-- the payback of the investment. Twin: computeModel() in financeMath.ts
CREATE OR REPLACE FUNCTION "private"."finance_model_plan"("target_model_id" bigint, "scenario" "text") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  model public.finance_models;
  mm public.finance_model_months;
  factor numeric;
  i integer;
  chairs numeric; days numeric; hours numeric; util numeric; vpch numeric; check_amount bigint;
  capacity numeric;
  visits bigint;
  revenue bigint;
  rec record;
  line_amount bigint;
  sums jsonb;
  fixed_total bigint;
  percent_total numeric;
  be_revenue bigint;
  cogs bigint; gross bigint; opex bigint; ebitda bigint; net bigint; cash_flow bigint;
  cash bigint;
  payback_cum bigint := 0;
  payback integer;
  after_count integer := 0;
  after_sum bigint := 0;
  months jsonb := '[]'::jsonb;
  line_values jsonb;
  totals jsonb := '{}'::jsonb;
  key text;
begin
  select * into model from public.finance_models m where m.id = target_model_id;
  if not found then
    return null;
  end if;
  factor := case scenario when 'optimistic' then model.optimistic_factor when 'pessimistic' then model.pessimistic_factor else 1 end;
  cash := model.opening_cash;
  for i in 0..11 loop
    select * into mm from public.finance_model_months x where x.model_id = model.id and x.month_index = i;
    chairs := coalesce(mm.chairs, model.chairs);
    days := coalesce(mm.working_days, model.working_days);
    hours := coalesce(mm.hours_per_day, model.hours_per_day);
    util := coalesce(mm.utilization, model.utilization);
    vpch := coalesce(mm.visits_per_chair_hour, model.visits_per_chair_hour);
    check_amount := coalesce(mm.avg_check, model.avg_check);
    capacity := chairs * days * hours * vpch;
    visits := round(capacity * util * factor / 100)::bigint;
    revenue := visits * check_amount;
    sums := jsonb_build_object('materials', 0, 'lab', 0, 'doctors', 0, 'staff', 0, 'marketing', 0, 'opex', 0,
      'interest', 0, 'depreciation', 0, 'tax', 0);
    line_values := '[]'::jsonb;
    fixed_total := 0;
    percent_total := 0;
    for rec in
      select l.* from public.finance_model_lines l
      where l.model_id = model.id and i between l.from_index and l.to_index
      order by l.position, l.id
    loop
      if rec.kind = 'percent' then
        line_amount := private.payroll_mul_div(revenue, rec.percent, 100);
        percent_total := percent_total + rec.percent;
      else
        line_amount := rec.amount;
        fixed_total := fixed_total + rec.amount;
      end if;
      sums := sums || jsonb_build_object(rec.pnl_line, (sums ->> rec.pnl_line)::bigint + line_amount);
      line_values := line_values || jsonb_build_array(jsonb_build_object('line_id', rec.id, 'amount', line_amount));
    end loop;
    cogs := (sums ->> 'materials')::bigint + (sums ->> 'lab')::bigint + (sums ->> 'doctors')::bigint;
    gross := revenue - cogs;
    opex := (sums ->> 'staff')::bigint + (sums ->> 'marketing')::bigint + (sums ->> 'opex')::bigint;
    ebitda := gross - opex;
    net := ebitda - (sums ->> 'interest')::bigint - (sums ->> 'depreciation')::bigint - (sums ->> 'tax')::bigint;
    cash_flow := net + (sums ->> 'depreciation')::bigint - case when i = model.investment_month then model.investment_amount else 0 end;
    cash := cash + cash_flow;
    be_revenue := case when percent_total < 100 then ceil(fixed_total * 100 / (100 - percent_total))::bigint end;
    if model.investment_amount > 0 and i >= model.investment_month then
      payback_cum := payback_cum + net + (sums ->> 'depreciation')::bigint;
      after_count := after_count + 1;
      after_sum := after_sum + net + (sums ->> 'depreciation')::bigint;
      if payback is null and payback_cum >= model.investment_amount then
        payback := i - model.investment_month + 1;
      end if;
    end if;
    months := months || jsonb_build_array(jsonb_build_object(
      'index', i,
      'month', (model.start_month + make_interval(months => i))::date,
      'chairs', chairs, 'working_days', days, 'hours_per_day', hours, 'utilization', util,
      'visits_per_chair_hour', vpch, 'avg_check', check_amount,
      'visits', visits, 'revenue', revenue,
      'materials', (sums ->> 'materials')::bigint, 'lab', (sums ->> 'lab')::bigint, 'doctors', (sums ->> 'doctors')::bigint,
      'staff', (sums ->> 'staff')::bigint, 'marketing', (sums ->> 'marketing')::bigint, 'opex_other', (sums ->> 'opex')::bigint,
      'interest', (sums ->> 'interest')::bigint, 'depreciation', (sums ->> 'depreciation')::bigint, 'tax', (sums ->> 'tax')::bigint,
      'cogs', cogs, 'gross', gross, 'opex', opex, 'ebitda', ebitda, 'net', net,
      'cash_flow', cash_flow, 'cash', cash,
      'fixed_costs', fixed_total, 'variable_percent', percent_total,
      'break_even_revenue', be_revenue,
      'break_even_utilization', case when be_revenue is not null and capacity * check_amount > 0
        then round(be_revenue * 100 / (capacity * check_amount), 1) end,
      'lines', line_values));
    foreach key in array array['visits', 'revenue', 'materials', 'lab', 'doctors', 'staff', 'marketing', 'opex_other',
      'interest', 'depreciation', 'tax', 'cogs', 'gross', 'opex', 'ebitda', 'net', 'cash_flow'] loop
      totals := totals || jsonb_build_object(key, coalesce((totals ->> key)::bigint, 0) + (months -> i ->> key)::bigint);
    end loop;
  end loop;
  return jsonb_build_object(
    'model_id', model.id,
    'scenario', coalesce(scenario, 'base'),
    'factor', factor,
    'start_month', model.start_month,
    'months', months,
    'total', totals || jsonb_build_object('closing_cash', cash,
      'gross_margin', private.finance_share((totals ->> 'gross')::numeric, (totals ->> 'revenue')::numeric),
      'net_margin', private.finance_share((totals ->> 'net')::numeric, (totals ->> 'revenue')::numeric)),
    'investment', model.investment_amount,
    'payback_months', case
      when model.investment_amount = 0 then null
      when payback is not null then payback
      when after_count > 0 and after_sum > 0 then
        after_count + ceil((model.investment_amount - payback_cum)::numeric * after_count / after_sum)::integer
    end,
    'payback_in_horizon', payback is not null);
end;
$$;

-- «Финмодель»: the plan of a model for a scenario, and plan vs fact (the
-- P&L of the whole clinic) for its months up to the current one. The owner
-- and the head.
CREATE OR REPLACE FUNCTION "public"."report_finance_model"("target_model_id" bigint, "scenario" "text" DEFAULT 'base'::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  model public.finance_models;
  plan jsonb;
  current_month date;
  fact_to date;
  fact jsonb;
begin
  if not private.finance_can_edit() then
    raise exception 'Финмодель видят только владелец и руководитель' using errcode = 'insufficient_privilege', hint = 'finance_forbidden';
  end if;
  if coalesce(scenario, 'base') not in ('base', 'optimistic', 'pessimistic') then
    raise exception 'Сценарий: базовый, оптимистичный или пессимистичный' using errcode = '22023', hint = 'finance_scenario';
  end if;
  select * into model from public.finance_models m where m.organization_id = org_id and m.id = target_model_id;
  if not found then
    raise exception 'Модель не найдена' using errcode = 'P0002';
  end if;
  plan := private.finance_model_plan(model.id, coalesce(scenario, 'base'));
  current_month := date_trunc('month', private.clinic_date(org_id, now()))::date;
  fact_to := least((current_month + interval '1 month')::date, (model.start_month + interval '12 months')::date);
  if fact_to > model.start_month then
    fact := private.finance_pnl(org_id, model.start_month, fact_to, null);
  end if;
  return plan || jsonb_build_object(
    'current_month', current_month,
    'fact', coalesce((
      select jsonb_agg(jsonb_build_object(
        'month', s ->> 'month',
        'revenue', (s ->> 'revenue')::bigint,
        'gross', (s ->> 'gross')::bigint,
        'ebitda', (s ->> 'ebitda')::bigint,
        'net', (s ->> 'net')::bigint,
        'visits', (s ->> 'visits')::bigint,
        'revenue_delta', (s ->> 'revenue')::bigint - (p ->> 'revenue')::bigint,
        'net_delta', (s ->> 'net')::bigint - (p ->> 'net')::bigint,
        'revenue_percent', private.finance_share((s ->> 'revenue')::numeric, (p ->> 'revenue')::numeric),
        'partial', (s ->> 'month')::date = current_month
      ) order by s ->> 'month')
      from jsonb_array_elements(fact -> 'summary') s
        join jsonb_array_elements(plan -> 'months') p on p ->> 'month' = s ->> 'month'
    ), '[]'::jsonb));
end;
$$;

-- An account: a system one keeps its code and is not deleted
CREATE OR REPLACE FUNCTION "private"."handle_finance_account_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'DELETE' then
    if old.code is not null and pg_trigger_depth() = 1
      and exists (select 1 from public.organizations o where o.id = old.organization_id) then
      raise exception 'Системный счёт нельзя удалить — только переименовать или убрать в архив'
        using errcode = '22023', hint = 'finance_system';
    end if;
    return old;
  end if;
  if tg_op = 'INSERT' then
    if pg_trigger_depth() = 1 and private.current_user_role() is not null then
      new.code := null;
    end if;
  elsif new.code is distinct from old.code then
    raise exception 'Код системного счёта не меняется' using errcode = '22023', hint = 'finance_system';
  end if;
  new.name := btrim(new.name);
  return new;
end;
$$;

-- An article: a system one keeps its code, section, activity and line and
-- is not deleted
CREATE OR REPLACE FUNCTION "private"."handle_finance_article_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'DELETE' then
    if old.code is not null and pg_trigger_depth() = 1
      and exists (select 1 from public.organizations o where o.id = old.organization_id) then
      raise exception 'Системную статью нельзя удалить — только переименовать или убрать в архив'
        using errcode = '22023', hint = 'finance_system';
    end if;
