select set_config('crm.finance_sync', 'on', true);
insert into public.finance_transactions (organization_id, kind, occurred_on, account_id, article_id, amount,
  counterparty, comment, payroll_adjustment_id, created_by)
select a.organization_id, 'out', a.occurred_on, private.finance_method_account(a.organization_id, 'bank_transfer'),
  private.finance_article_id(a.organization_id, case when a.doctor_id is not null then 'salary_doctors' else 'salary_staff' end),
  a.amount,
  left(coalesce(d.name, nullif(btrim(concat_ws(' ', s.first_name, s.last_name)), '')), 200),
  left(concat_ws(' — ', 'Зарплата за ' || to_char(a.month, 'MM.YYYY'), a.note), 1000), a.id, a.created_by
from public.payroll_adjustments a
  left join public.doctors d on d.organization_id = a.organization_id and d.id = a.doctor_id
  left join public.sales s on s.organization_id = a.organization_id and s.id = a.sales_id
where a.kind = 'payout' and a.account_operation_id is null
  and private.finance_method_account(a.organization_id, 'bank_transfer') is not null;
insert into public.finance_transactions (organization_id, kind, occurred_on, account_id, article_id, amount,
  counterparty, comment, lab_payment_id, created_by)
select p.organization_id, 'out', private.clinic_date(p.organization_id, p.paid_at),
  coalesce(private.finance_method_account(p.organization_id, p.method), private.finance_method_account(p.organization_id, 'bank_transfer')),
  private.finance_article_id(p.organization_id, 'lab'), p.amount, left(l.name, 200),
  left(concat_ws(' — ', 'Лаборатория за ' || to_char(p.month, 'MM.YYYY'), p.comment), 1000), p.id, p.created_by
from public.lab_payments p
  join public.labs l on l.organization_id = p.organization_id and l.id = p.lab_id
where p.account_operation_id is null
  and private.finance_method_account(p.organization_id, 'bank_transfer') is not null;
select set_config('crm.finance_sync', '', true);
alter table public.finance_transactions enable trigger audit_finance_transaction;
