$$;

-- A transaction: the article fits its kind (in / out by section, accrual:
-- an article of the P&L); a linked one (payout, lab payment) keeps its
-- amount, day and kind — they change on the payroll or lab side
CREATE OR REPLACE FUNCTION "private"."handle_finance_transaction_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  article public.finance_articles;
  syncing boolean := coalesce(current_setting('crm.finance_sync', true), '') = 'on';
begin
  if tg_op = 'DELETE' then
    if not syncing and pg_trigger_depth() = 1 and (old.payroll_adjustment_id is not null or old.lab_payment_id is not null)
      and exists (select 1 from public.organizations o where o.id = old.organization_id) then
      raise exception 'Это выплата зарплаты или оплата лаборатории: удалите её в разделе «Зарплаты» или «Лаборатория»'
        using errcode = '22023', hint = 'finance_linked';
    end if;
    return old;
  end if;
  if tg_op = 'INSERT' then
    if not syncing and (new.payroll_adjustment_id is not null or new.lab_payment_id is not null) then
      raise exception 'Связь с выплатой задаёт только система' using errcode = '22023', hint = 'finance_linked';
    end if;
    if pg_trigger_depth() = 1 and private.current_user_role() is not null then
      new.created_by := private.current_sales_id();
      new.created_at := now();
    end if;
  elsif not syncing then
    if new.payroll_adjustment_id is distinct from old.payroll_adjustment_id or new.lab_payment_id is distinct from old.lab_payment_id then
      raise exception 'Связь с выплатой не меняется' using errcode = '22023', hint = 'finance_linked';
    end if;
    if (old.payroll_adjustment_id is not null or old.lab_payment_id is not null)
      and (new.amount <> old.amount or new.occurred_on <> old.occurred_on or new.kind <> old.kind) then
      raise exception 'Сумму и дату выплаты меняют в разделе «Зарплаты» или «Лаборатория»'
        using errcode = '22023', hint = 'finance_linked';
    end if;
  end if;
  new.counterparty := nullif(btrim(new.counterparty), '');
  new.comment := nullif(btrim(new.comment), '');
  if new.article_id is not null then
    select * into article from public.finance_articles a
    where a.organization_id = new.organization_id and a.id = new.article_id;
    if not found then
      raise exception 'Статья не найдена' using errcode = '22023', hint = 'finance_article';
    end if;
    if new.kind = 'in' and article.section <> 'in' then
      raise exception 'Поступление — по статье поступлений' using errcode = '22023', hint = 'finance_article';
    end if;
    if new.kind = 'out' and article.section <> 'out' then
      raise exception 'Выплата — по статье выплат' using errcode = '22023', hint = 'finance_article';
    end if;
    if new.kind = 'accrual' and article.pnl_line is null then
      raise exception 'Начисление — по статье, которая входит в ПиУ' using errcode = '22023', hint = 'finance_article';
    end if;
    if not article.is_active and not syncing and (tg_op = 'INSERT' or new.article_id is distinct from old.article_id) then
      raise exception 'Статья в архиве' using errcode = '22023', hint = 'finance_article';
    end if;
  end if;
  return new;
end;
$$;

-- A payroll payout paid without the cash desk: its linked transaction
-- («Зарплата врачей» / «Зарплата персонала», the bank account of the
-- method bank_transfer) follows its amount and day
CREATE OR REPLACE FUNCTION "private"."handle_finance_payout_sync"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  person text;
begin
  if tg_op = 'DELETE' then
    return null;
  end if;
  perform set_config('crm.finance_sync', 'on', true);
  if new.kind <> 'payout' or new.account_operation_id is not null then
    delete from public.finance_transactions t
    where t.organization_id = new.organization_id and t.payroll_adjustment_id = new.id;
  elsif exists (select 1 from public.finance_transactions t
      where t.organization_id = new.organization_id and t.payroll_adjustment_id = new.id) then
    update public.finance_transactions t
    set amount = new.amount, occurred_on = new.occurred_on
    where t.organization_id = new.organization_id and t.payroll_adjustment_id = new.id
      and (t.amount <> new.amount or t.occurred_on <> new.occurred_on);
  else
    if new.doctor_id is not null then
      select d.name into person from public.doctors d where d.organization_id = new.organization_id and d.id = new.doctor_id;
    else
      select nullif(btrim(concat_ws(' ', s.first_name, s.last_name)), '') into person
      from public.sales s where s.organization_id = new.organization_id and s.id = new.sales_id;
    end if;
    insert into public.finance_transactions (organization_id, kind, occurred_on, account_id, article_id, amount,
      counterparty, comment, payroll_adjustment_id, created_by)
    select new.organization_id, 'out', new.occurred_on, a.account_id,
      private.finance_article_id(new.organization_id, case when new.doctor_id is not null then 'salary_doctors' else 'salary_staff' end),
      new.amount, left(person, 200),
      left(concat_ws(' — ', 'Зарплата за ' || to_char(new.month, 'MM.YYYY'), new.note), 1000), new.id, new.created_by
    from (select private.finance_method_account(new.organization_id, 'bank_transfer') as account_id) a
    where a.account_id is not null
      and private.finance_article_id(new.organization_id, 'salary_staff') is not null;
  end if;
  perform set_config('crm.finance_sync', '', true);
  return null;
end;
$$;

-- A lab payment paid without the cash desk: its linked transaction
-- («Лаборатория», the account of its method) follows its amount, day and
-- method
CREATE OR REPLACE FUNCTION "private"."handle_finance_lab_payment_sync"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  lab_name text;
  day date;
begin
  if tg_op = 'DELETE' then
    return null;
  end if;
  perform set_config('crm.finance_sync', 'on', true);
  day := private.clinic_date(new.organization_id, new.paid_at);
  if new.account_operation_id is not null then
    delete from public.finance_transactions t
    where t.organization_id = new.organization_id and t.lab_payment_id = new.id;
  elsif exists (select 1 from public.finance_transactions t
      where t.organization_id = new.organization_id and t.lab_payment_id = new.id) then
    update public.finance_transactions t
    set amount = new.amount, occurred_on = day,
      account_id = case when tg_op = 'UPDATE' and new.method <> old.method
        then coalesce(private.finance_method_account(new.organization_id, new.method), t.account_id) else t.account_id end
    where t.organization_id = new.organization_id and t.lab_payment_id = new.id;
  else
    select l.name into lab_name from public.labs l where l.organization_id = new.organization_id and l.id = new.lab_id;
    insert into public.finance_transactions (organization_id, kind, occurred_on, account_id, article_id, amount,
      counterparty, comment, lab_payment_id, created_by)
    select new.organization_id, 'out', day, a.account_id, private.finance_article_id(new.organization_id, 'lab'),
      new.amount, left(lab_name, 200),
      left(concat_ws(' — ', 'Лаборатория за ' || to_char(new.month, 'MM.YYYY'), new.comment), 1000), new.id, new.created_by
    from (select coalesce(private.finance_method_account(new.organization_id, new.method),
      private.finance_method_account(new.organization_id, 'bank_transfer')) as account_id) a
    where a.account_id is not null and private.finance_article_id(new.organization_id, 'lab') is not null;
  end if;
  perform set_config('crm.finance_sync', '', true);
  return null;
end;
$$;

