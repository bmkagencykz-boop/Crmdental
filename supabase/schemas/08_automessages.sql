-- Templates and rules are settings (owner and head); the queue follows the deal
create policy "Organization members can read" on public.message_templates for select to authenticated
    using (organization_id = (select private.current_organization_id()));
create policy "Owner and head can insert" on public.message_templates for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));
