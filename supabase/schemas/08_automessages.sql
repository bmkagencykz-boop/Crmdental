--
-- Automatic messages by templates, stage scripts (stage 6)
--
-- A rule "stage X -> template Y" puts a message in the queue (automessages)
-- when a deal enters the stage: N minutes after, or N minutes before the
-- visit (deals.appointment_at). The deal triggers schedule and cancel the
-- queue, so all the timing logic lives here. The edge function
-- automessages_dispatch, started every minute by pg_cron, takes the due rows
-- (public.claim_automessages) and sends them through Wazzup24; "show to the
-- employee first" rules become a task with the text instead.
--

-- pg_cron starts the dispatcher (the job itself is created by the migration
-- 20261002000000_stage6_automessages.sql: it is data, not schema)
create extension if not exists "pg_cron" with schema "pg_catalog";

-- What the employee says to the patient at a stage (shown on the deal page)
alter table public.stages add column script text;

-- Texts of the clinic, with the variables {имя}, {услуга}, {дата_визита}, {клиника}, {врач}
create table public.message_templates (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    body text not null,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint message_templates_name_not_blank check (btrim(name) <> ''),
    constraint message_templates_body_not_blank check (btrim(body) <> '')
);

-- Stage X -> template Y.
--   timing after_stage: offset_minutes after the deal enters the stage;
--   timing before_visit: offset_minutes before deals.appointment_at.
--   mode auto: sent by the dispatcher; confirm: a task shows the text to the
--   responsible, who sends it (or not).
create table public.automessage_rules (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    stage_id bigint not null,
    template_id bigint not null,
    timing text not null default 'after_stage',
    offset_minutes integer not null default 0,
    mode text not null default 'auto',
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint automessage_rules_timing_check check (timing in ('after_stage', 'before_visit')),
    constraint automessage_rules_mode_check check (mode in ('auto', 'confirm')),
    constraint automessage_rules_offset_positive check (offset_minutes >= 0)
);

-- The queue. pending -> sending -> sent | failed (auto rules),
-- pending -> awaiting (task created) -> sent (confirm rules),
-- pending | awaiting -> cancelled (the deal left the stage, the visit moved,
-- the rule was switched off, an employee cancelled it).
create table public.automessages (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    deal_id bigint not null,
    rule_id bigint,
    -- Stage and timing of the rule when scheduled: leaving the stage or
    -- moving the visit cancels the row
    stage_id bigint not null,
    timing text not null,
    send_at timestamp with time zone not null,
    status text not null default 'pending',
    -- Rendered when the row is due
    text text,
    error text,
    claimed_at timestamp with time zone,
    processed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    constraint automessages_status_check check (status in ('pending', 'sending', 'awaiting', 'sent', 'cancelled', 'failed')),
    constraint automessages_timing_check check (timing in ('after_stage', 'before_visit'))
);

