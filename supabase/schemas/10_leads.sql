--
-- Stage 8: requests from the website, Tilda and 2GIS (lead webhook), and the
-- clinic's own Telegram bot (Bot API) next to the Wazzup24 channels.
--

--
-- Tables
--

-- Token of the clinic's lead webhook (edge function leads_webhook?token=).
-- Readable by the service role only; owners and heads get it through
-- public.lead_webhook_token() and change it with
-- public.regenerate_lead_webhook_token().
create table public.lead_integrations (
    organization_id bigint primary key,
    token text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
    created_at timestamp with time zone not null default now(),
    token_changed_at timestamp with time zone
);

-- Every request received through the webhook: what the form sent, where it
-- went, and the payload hash that makes a repeated submission a no-op
create table public.lead_submissions (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    phone text not null,
    payload_hash text not null,
    payload jsonb not null default '{}'::jsonb,
    patient_id bigint not null,
    deal_id bigint not null,
    created_at timestamp with time zone not null default now()
);

-- The clinic's own Telegram bot (token from @BotFather). Secret: service role
-- only, like messenger_integrations. webhook_token is part of the webhook
-- URL (identifies the clinic), secret_token is checked in the
-- X-Telegram-Bot-Api-Secret-Token header of every update.
create table public.telegram_bots (
    organization_id bigint primary key,
    bot_token text,
    bot_id bigint,
    username text,
    name text,
    webhook_token text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
    secret_token text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
    connected_at timestamp with time zone,
    last_error text
);

alter table public.lead_submissions add constraint lead_submissions_organization_id_id_key unique (organization_id, id);

