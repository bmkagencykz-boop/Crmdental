--
-- Data import (Excel / CSV, amoCRM export) and groundwork for MIS integrations
--
-- external_refs: which row of the CRM a record of another system is (an amoCRM
-- deal, a row of a clinic's Excel file, later a patient of a MIS). Imports use
-- it to find what they already brought in, so running a file twice changes
-- nothing. entity_id is not a foreign key (it points at one of several tables);
-- triggers remove the references of deleted patients and deals.
--
-- integrations: connections to other systems (MIS). Their settings hold API
-- keys, so only the service role reads the table, like messenger_integrations;
-- employees see the status through integration_status().
--

create table public.external_refs (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    entity text not null,
    entity_id bigint not null,
    system text not null,
    external_id text not null,
    created_at timestamp with time zone not null default now(),
    -- appointment: a MIS appointment on its deal; payment, doctor: stage 27
    constraint external_refs_entity_check check (entity in ('patient', 'deal', 'sales', 'service', 'appointment', 'payment', 'doctor')),
    constraint external_refs_system_not_blank check (btrim(system) <> ''),
    constraint external_refs_external_id_not_blank check (btrim(external_id) <> ''),
    constraint external_refs_external_id_key unique (organization_id, system, entity, external_id)
);

create table public.integrations (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    kind text not null,
    -- requested: the clinic asked for the connector; connected / error: a
    -- running connector; disabled: turned off by the clinic
    status text not null default 'requested',
    settings jsonb not null default '{}'::jsonb,
    last_sync_at timestamp with time zone,
    last_error text,
    created_at timestamp with time zone not null default now(),
    -- dentist_plus, macdent: the connectors of stage 27 (27_mis_connectors.sql)
    constraint integrations_kind_check check (kind in ('ident', 'dentalpro', 'medelement', '1c_medicine', 'other', 'dentist_plus', 'macdent')),
    constraint integrations_status_check check (status in ('requested', 'connected', 'error', 'disabled')),
    constraint integrations_settings_is_object check (jsonb_typeof(settings) = 'object'),
    constraint integrations_organization_id_kind_key unique (organization_id, kind)
);

alter table public.external_refs add constraint external_refs_organization_id_id_key unique (organization_id, id);
alter table public.integrations add constraint integrations_organization_id_id_key unique (organization_id, id);

alter table public.external_refs
    add constraint external_refs_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade;
alter table public.integrations
    add constraint integrations_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade;

create index external_refs_entity_idx on public.external_refs using btree (organization_id, entity, entity_id);

