-- Row Level Security
--

alter table public.external_refs enable row level security;
alter table public.integrations enable row level security;

-- External references: members read (a patient card may show its MIS id),
-- the owner and the head write them (imports). integrations has no policy:
-- its settings are secrets, only the service role (connectors) reads them.
create policy "Organization members can read" on public.external_refs for select to authenticated
    using (organization_id = (select private.current_organization_id()));
create policy "Owner and head can insert" on public.external_refs for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));
create policy "Owner and head can update" on public.external_refs for update to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'))
    with check (organization_id = (select private.current_organization_id()));
create policy "Owner and head can delete" on public.external_refs for delete to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));

