create or replace view public.audit_log_summary with (security_invoker = on) as
select
    a.id,
    a.organization_id,
    a.at,
    a.sales_id,
    a.source,
    a.entity,
    a.entity_id,
    a.action,
    a.changes,
    a.deal_id,
    a.patient_id,
    d.name as deal_name,
    nullif(btrim(concat_ws(' ', p.last_name, p.first_name)), '') as patient_name,
    lower(concat_ws(' ',
        d.name, p.last_name, p.first_name, p.middle_name, array_to_string(p.phones, ' '),
        a.changes -> 'name' ->> 0, a.changes -> 'name' ->> 1,
        a.changes -> 'last_name' ->> 0, a.changes -> 'first_name' ->> 0
    )) as search_text
from public.audit_log a
    left join public.deals d on d.organization_id = a.organization_id and d.id = a.deal_id
    left join public.patients p on p.organization_id = a.organization_id and p.id = a.patient_id;

alter table public.audit_log enable row level security;

create policy "Owner and head can read" on public.audit_log for select to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));

