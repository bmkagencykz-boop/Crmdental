create or replace trigger patient_custom_values
    before insert or update on public.patients
    for each row execute function private.handle_custom_values('patient');

create or replace trigger audit_custom_field
    after insert or update or delete on public.custom_fields
    for each row execute function private.audit_row('custom_field', 'entity,name,type,options,required,is_active,show_on_card');

--
-- Row Level Security
--

alter table public.custom_fields enable row level security;

-- Every employee reads the definitions (forms, cards, filters); the owner and
-- the head edit them
create policy "Organization members can read" on public.custom_fields for select to authenticated
    using (organization_id = (select private.current_organization_id()));
create policy "Owner and head can insert" on public.custom_fields for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));
create policy "Owner and head can update" on public.custom_fields for update to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'))
    with check (organization_id = (select private.current_organization_id()));
create policy "Owner and head can delete" on public.custom_fields for delete to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head'));

