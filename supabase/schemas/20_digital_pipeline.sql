-- Does an active webhook of the clinic want this event (cheap check before
-- building a payload)
CREATE OR REPLACE FUNCTION "private"."has_webhook"("org_id" bigint, "webhook_event" "text") RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select current_setting('crm.importing', true) is distinct from 'on'
    and exists (
      select 1 from public.webhooks w
      where w.organization_id = org_id and w.is_active and webhook_event = any(w.events)
    )
$$;

-- Queues the event for the active webhooks that want it (only_webhook_id: for
-- that webhook only, whatever its events: the action of a stage trigger, the
-- test). Payload: { event, occurred_at, organization_id, data }.
CREATE OR REPLACE FUNCTION "private"."enqueue_webhook"("org_id" bigint, "webhook_event" "text", "data" "jsonb", "only_webhook_id" bigint DEFAULT NULL::bigint) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  queued integer;
begin
  -- Imports (public.import_batch) are bulk writes: nothing is sent
  if current_setting('crm.importing', true) = 'on' then
    return 0;
  end if;
  insert into public.webhook_deliveries (organization_id, webhook_id, event, payload)
  select org_id, w.id, webhook_event,
    jsonb_build_object('event', webhook_event, 'occurred_at', now(), 'organization_id', org_id, 'data', data)
  from public.webhooks w
  where w.organization_id = org_id
    and w.is_active
    and case when only_webhook_id is null then webhook_event = any(w.events) else w.id = only_webhook_id end;
  get diagnostics queued = row_count;
  return queued;
end;
$$;

-- Wait before the next attempt: 1 min, 5 min, 30 min, 2 h, then 6 h
CREATE OR REPLACE FUNCTION "private"."webhook_retry_delay"("attempt" integer) RETURNS interval
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case
    when attempt <= 1 then interval '1 minute'
    when attempt = 2 then interval '5 minutes'
    when attempt = 3 then interval '30 minutes'
    when attempt = 4 then interval '2 hours'
    else interval '6 hours'
  end
$$;

-- Switching a webhook on starts afresh; switching it off cancels its queue
CREATE OR REPLACE FUNCTION "private"."handle_webhook_update"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if new.is_active and not old.is_active then
    new.failure_count := 0;
    new.disabled_at := null;
    new.last_error := null;
  elsif old.is_active and not new.is_active then
    update public.webhook_deliveries d
    set status = 'cancelled', error = coalesce(d.error, 'Вебхук выключен')
    where d.organization_id = new.organization_id and d.webhook_id = new.id and d.status = 'pending';
  end if;
  return new;
end;
$$;

-- Dispatcher (edge function webhooks_dispatch, service role only): takes the
-- due deliveries of the active webhooks with FOR UPDATE SKIP LOCKED (two runs
-- never take the same row) and returns them with the URL and the secret. A
-- run that died while sending gives its rows back after 10 minutes (the
-- receiver deduplicates by delivery id).
CREATE OR REPLACE FUNCTION "public"."claim_webhook_deliveries"("max_rows" integer DEFAULT 50) RETURNS TABLE("id" bigint, "organization_id" bigint, "webhook_id" bigint, "url" "text", "secret" "text", "event" "text", "payload" "jsonb", "attempts" integer)
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  update public.webhook_deliveries d
  set status = 'pending', next_attempt_at = now()
  where d.status = 'sending' and d.claimed_at < now() - interval '10 minutes';

  return query
  with due as (
    select d.id
    from public.webhook_deliveries d
      join public.webhooks w on w.organization_id = d.organization_id and w.id = d.webhook_id
    where d.status = 'pending' and d.next_attempt_at <= now() and w.is_active
    order by d.next_attempt_at, d.id
    limit greatest(max_rows, 0)
    for update of d skip locked
  ), taken as (
    update public.webhook_deliveries d
    set status = 'sending', claimed_at = now()
    from due
    where d.id = due.id
    returning d.id, d.organization_id, d.webhook_id, d.event, d.payload, d.attempts
  )
  select t.id, t.organization_id, t.webhook_id, w.url, w.secret, t.event, t.payload, t.attempts
  from taken t
    join public.webhooks w on w.organization_id = t.organization_id and w.id = t.webhook_id
  order by t.id;
end;
$$;

-- Result of a delivery (edge function webhooks_dispatch, service role only).
-- A failure is retried later (private.webhook_retry_delay), 5 attempts at
-- most; 10 failed attempts in a row switch the webhook off. Returns the new
-- status of the delivery (null: not being sent).
CREATE OR REPLACE FUNCTION "public"."complete_webhook_delivery"("delivery_id" bigint, "delivered" boolean, "response_status" integer DEFAULT NULL::integer, "error_text" "text" DEFAULT NULL::"text") RETURNS "text"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  delivery public.webhook_deliveries;
  new_status text;
  failures integer;
  message text := left(coalesce(nullif(btrim(error_text), ''),
    case when response_status is not null then 'HTTP ' || response_status else 'Ошибка отправки' end), 500);
begin
  select * into delivery from public.webhook_deliveries d
  where d.id = delivery_id
  for update;
  if not found or delivery.status <> 'sending' then
    return null;
  end if;

  if delivered then
    update public.webhook_deliveries d
    set status = 'delivered', attempts = d.attempts + 1, response_status = complete_webhook_delivery.response_status,
        error = null, delivered_at = now()
    where d.id = delivery.id;
    update public.webhooks w
    set failure_count = 0, last_success_at = now()
    where w.organization_id = delivery.organization_id and w.id = delivery.webhook_id;
    return 'delivered';
  end if;

  new_status := case when delivery.attempts + 1 >= 5 then 'failed' else 'pending' end;
  update public.webhook_deliveries d
  set status = new_status, attempts = d.attempts + 1, response_status = complete_webhook_delivery.response_status,
      error = message,
      next_attempt_at = now() + private.webhook_retry_delay(d.attempts + 1)
  where d.id = delivery.id;

  update public.webhooks w
  set failure_count = w.failure_count + 1, last_error = message, last_failure_at = now()
  where w.organization_id = delivery.organization_id and w.id = delivery.webhook_id
  returning w.failure_count into failures;
  if failures >= 10 then
    update public.webhooks w
    set is_active = false, disabled_at = now(),
        last_error = 'Отключён после ' || failures || ' ошибок подряд: ' || message
    where w.organization_id = delivery.organization_id and w.id = delivery.webhook_id and w.is_active;
  end if;
  return new_status;
end;
$$;

-- Called every minute by pg_cron: starts the edge function when a delivery
-- is due. Needs the Vault secrets project_url and automessages_dispatch_key
-- (the key of all the dispatchers, function secret AUTOMESSAGES_DISPATCH_KEY).
CREATE OR REPLACE FUNCTION "private"."request_webhooks_dispatch"() RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  project_url text;
  dispatch_key text;
begin
  if not exists (
    select 1 from public.webhook_deliveries d
    where (d.status = 'pending' and d.next_attempt_at <= now())
      or (d.status = 'sending' and d.claimed_at < now() - interval '10 minutes')
  ) then
    return null;
  end if;
  if to_regclass('vault.decrypted_secrets') is null then
    return null;
  end if;
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into project_url using 'project_url';
  execute 'select decrypted_secret from vault.decrypted_secrets where name = $1'
    into dispatch_key using 'automessages_dispatch_key';
  if project_url is null or dispatch_key is null then
    raise warning 'webhooks: Vault secrets project_url and automessages_dispatch_key are not set';
    return null;
  end if;
  return net.http_post(
    url := rtrim(project_url, '/') || '/functions/v1/webhooks_dispatch',
    body := '{}'::jsonb,
    params := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || dispatch_key
    ),
    timeout_milliseconds := 5000
  );
end;
$$;

-- «Отправить тест» in the settings (owner and head): a ping to one webhook
CREATE OR REPLACE FUNCTION "public"."send_test_webhook"("target_webhook_id" bigint) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
