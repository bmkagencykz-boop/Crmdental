-- Last activity of a deal: entering its stage, a message, a note, a call, a
-- completed task (edits of the fields do not count: automatic ones either)
CREATE OR REPLACE FUNCTION "private"."deal_last_activity_at"("deal" "public"."deals") RETURNS timestamp with time zone
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select greatest(
    deal.stage_changed_at,
    (select max(m.sent_at) from public.messages m where m.organization_id = deal.organization_id and m.deal_id = deal.id),
    (select max(n.date) from public.deal_notes n where n.organization_id = deal.organization_id and n.deal_id = deal.id),
    (select max(c.called_at) from public.calls c where c.organization_id = deal.organization_id and c.deal_id = deal.id),
    (select max(t.done_date) from public.tasks t where t.organization_id = deal.organization_id and t.deal_id = deal.id)
  )
$$;

-- Delayed triggers, run by pg_cron every 5 minutes (and by the tests with a
-- moment): «N minutes without activity» (once per quiet period) and «N
-- minutes after the visit» (once per visit date). At most 200 deals per
-- trigger and run; the next run takes the rest. Also purges the old API rate
-- limit windows.
CREATE OR REPLACE FUNCTION "private"."stage_triggers_tick"("moment" timestamp with time zone DEFAULT "now"()) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  trigger_row public.stage_triggers;
  target record;
  fired integer := 0;
begin
  for trigger_row in
    select t.* from public.stage_triggers t
    where t.is_active and t.event in ('idle', 'visit_passed')
    order by t.organization_id, t.position, t.id
  loop
    for target in
      select c.id, c.event_key
      from (
        select d.id,
          case when trigger_row.event = 'idle'
            then 'idle:' || extract(epoch from private.deal_last_activity_at(d))
            else 'visit:' || extract(epoch from d.appointment_at)
          end as event_key,
          case when trigger_row.event = 'idle'
            then private.deal_last_activity_at(d)
            else d.appointment_at
          end as since
        from public.deals d
        where d.organization_id = trigger_row.organization_id
          and d.stage_id = trigger_row.stage_id
          and d.archived_at is null
          and (trigger_row.event = 'idle' or d.appointment_at is not null)
          and private.stage_trigger_matches(trigger_row, d)
      ) c
      where c.since <= moment - make_interval(mins => trigger_row.delay_minutes)
        and not exists (
          select 1 from public.stage_trigger_runs r
          where r.trigger_id = trigger_row.id and r.deal_id = c.id and r.event_key = c.event_key
        )
      order by c.since, c.id
      limit 200
    loop
      if private.fire_stage_trigger(trigger_row, target.id, target.event_key) is not null then
        fired := fired + 1;
      end if;
    end loop;
  end loop;

  delete from public.api_request_counts c where c.window_start < moment - interval '1 hour';
  return fired;
end;
$$;

