-- POST /api/deals: patient_id, or patient { first_name, last_name, phone }
-- (found by phone or created), and the deal fields. Without sales_id the
-- deal is distributed by the clinic rules, like a website lead.
CREATE OR REPLACE FUNCTION "public"."api_create_deal"("api_key" "text", "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authenticate(api_key, true)).organization_id;
  new_patient_id bigint;
  new_pipeline_id bigint;
  new_stage_id bigint;
  new_deal public.deals;
  created_patient boolean := false;
  found_patient jsonb;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  new_patient_id := (body ->> 'patient_id')::bigint;
  if new_patient_id is null and body ? 'patient' then
    found_patient := private.api_find_or_create_patient(org_id, body -> 'patient');
    new_patient_id := (found_patient ->> 'patient_id')::bigint;
    created_patient := (found_patient ->> 'created')::boolean;
  end if;
  if new_patient_id is null then
    raise exception 'Укажите patient_id или patient' using errcode = '22023';
  end if;
  if not exists (select 1 from public.patients p where p.organization_id = org_id and p.id = new_patient_id) then
    raise exception 'Пациент не найден' using errcode = 'PT404', hint = 'not_found';
  end if;

  new_pipeline_id := (body ->> 'pipeline_id')::bigint;
  new_stage_id := (body ->> 'stage_id')::bigint;
  if new_stage_id is not null and new_pipeline_id is null then
    select s.pipeline_id into new_pipeline_id from public.stages s
    where s.organization_id = org_id and s.id = new_stage_id;
    if new_pipeline_id is null then
      raise exception 'Этап не найден' using errcode = '23503';
    end if;
  end if;

  insert into public.deals (organization_id, patient_id, pipeline_id, stage_id, name, source_id, service_id,
    doctor_id, sales_id, plan_amount, consultation_amount, appointment_at, visit_at, description, tags)
  values (org_id, new_patient_id, new_pipeline_id, new_stage_id,
    nullif(btrim(body ->> 'name'), ''),
    (body ->> 'source_id')::bigint,
    (body ->> 'service_id')::bigint,
    (body ->> 'doctor_id')::bigint,
    (body ->> 'sales_id')::bigint,
    coalesce((body ->> 'plan_amount')::bigint, 0),
    (body ->> 'consultation_amount')::bigint,
    (body ->> 'appointment_at')::timestamp with time zone,
    (body ->> 'visit_at')::timestamp with time zone,
    body ->> 'description',
    private.api_tag_ids(org_id, body -> 'tags'))
  returning * into new_deal;

  -- The row after the triggers (distribution, automations)
  select * into new_deal from public.deals d where d.organization_id = org_id and d.id = new_deal.id;
  return jsonb_build_object('data', private.deal_json(new_deal), 'created_patient', created_patient);
end;
$$;

-- PATCH /api/deals/:id: only the fields present in the body change. The
-- rules of the deals apply (stage checklist, refusal reason, refusal locked).
CREATE OR REPLACE FUNCTION "public"."api_update_deal"("api_key" "text", "deal_id" bigint, "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authenticate(api_key, true)).organization_id;
  deal public.deals;
  new_stage_id bigint;
  new_pipeline_id bigint;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  select * into deal from public.deals d
  where d.organization_id = org_id and d.id = api_update_deal.deal_id
  for update;
  if not found then
    raise exception 'Сделка не найдена' using errcode = 'PT404', hint = 'not_found';
  end if;

  new_stage_id := case when body ? 'stage_id' then (body ->> 'stage_id')::bigint else deal.stage_id end;
  new_pipeline_id := case
    when body ? 'pipeline_id' then (body ->> 'pipeline_id')::bigint
    when body ? 'stage_id' then (select s.pipeline_id from public.stages s where s.organization_id = org_id and s.id = new_stage_id)
    else deal.pipeline_id
  end;
  if new_stage_id is null or new_pipeline_id is null then
    raise exception 'Этап не найден' using errcode = '23503';
  end if;

  update public.deals d
  set pipeline_id = new_pipeline_id,
      stage_id = new_stage_id,
      name = case when body ? 'name' then nullif(btrim(body ->> 'name'), '') else d.name end,
      sales_id = case when body ? 'sales_id' then (body ->> 'sales_id')::bigint else d.sales_id end,
      source_id = case when body ? 'source_id' then (body ->> 'source_id')::bigint else d.source_id end,
      service_id = case when body ? 'service_id' then (body ->> 'service_id')::bigint else d.service_id end,
      doctor_id = case when body ? 'doctor_id' then (body ->> 'doctor_id')::bigint else d.doctor_id end,
      plan_amount = case when body ? 'plan_amount' then coalesce((body ->> 'plan_amount')::bigint, 0) else d.plan_amount end,
      consultation_amount = case when body ? 'consultation_amount' then (body ->> 'consultation_amount')::bigint else d.consultation_amount end,
      appointment_at = case when body ? 'appointment_at' then (body ->> 'appointment_at')::timestamp with time zone else d.appointment_at end,
      visit_at = case when body ? 'visit_at' then (body ->> 'visit_at')::timestamp with time zone else d.visit_at end,
      description = case when body ? 'description' then body ->> 'description' else d.description end,
      tags = case when body ? 'tags' then private.api_tag_ids(org_id, body -> 'tags') else d.tags end,
      lost_reason_id = case when body ? 'lost_reason_id' then (body ->> 'lost_reason_id')::bigint else d.lost_reason_id end,
      lost_comment = case when body ? 'lost_comment' then body ->> 'lost_comment' else d.lost_comment end
  where d.organization_id = org_id and d.id = deal.id;

  select * into deal from public.deals d where d.organization_id = org_id and d.id = api_update_deal.deal_id;
  return jsonb_build_object('data', private.deal_json(deal));
end;
$$;

