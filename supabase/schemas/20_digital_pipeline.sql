-- A new key (owner and head): returned once, only its hash is stored
CREATE OR REPLACE FUNCTION "public"."create_api_key"("key_name" "text", "key_scope" "text" DEFAULT 'read'::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  new_key text := 'dcrm_' || replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  new_row public.api_keys;
begin
  if org_id is null or private.current_user_role() not in ('owner', 'head') then
    raise exception 'Only the owner and the head manage API keys' using errcode = '42501';
  end if;
  if key_scope is null or key_scope not in ('read', 'write') then
    raise exception 'Доступ ключа: read или write' using errcode = '22023';
  end if;
  insert into public.api_keys (organization_id, name, prefix, key_hash, scope, created_by)
  values (org_id, btrim(coalesce(key_name, '')), left(new_key, 12), private.api_key_hash(new_key), key_scope,
    private.current_sales_id())
  returning * into new_row;
  return jsonb_build_object('id', new_row.id, 'name', new_row.name, 'prefix', new_row.prefix,
    'scope', new_row.scope, 'created_at', new_row.created_at, 'key', new_key);
end;
$$;

CREATE OR REPLACE FUNCTION "public"."revoke_api_key"("key_id" bigint) RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if private.current_organization_id() is null or private.current_user_role() not in ('owner', 'head') then
    raise exception 'Only the owner and the head manage API keys' using errcode = '42501';
  end if;
  update public.api_keys k
  set revoked_at = now()
  where k.organization_id = private.current_organization_id() and k.id = key_id and k.revoked_at is null;
  return found;
end;
$$;

-- The clinic of an API key. Errors carry PostgREST HTTP statuses (PTnnn):
-- 401 unknown or revoked key, 403 read-only key for a write, 429 more than
-- 60 requests in the current minute. Changes made through the API are
-- audited with the source 'api'.
CREATE OR REPLACE FUNCTION "private"."api_authenticate"("api_key" "text", "need_write" boolean) RETURNS "public"."api_keys"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  key_row public.api_keys;
  used integer;
begin
  select * into key_row from public.api_keys k
  where k.key_hash = private.api_key_hash(api_key) and k.revoked_at is null;
  if not found then
    raise exception 'Неверный или отозванный API-ключ' using errcode = 'PT401', hint = 'invalid_key';
  end if;
  if need_write and key_row.scope <> 'write' then
    raise exception 'Ключ только для чтения' using errcode = 'PT403', hint = 'read_only_key';
  end if;
  insert into public.api_request_counts as c (api_key_id, window_start, requests)
  values (key_row.id, date_trunc('minute', now()), 1)
  on conflict (api_key_id, window_start) do update set requests = c.requests + 1
  returning c.requests into used;
  if used > 60 then
    raise exception 'Слишком много запросов: не больше 60 в минуту на ключ' using errcode = 'PT429', hint = 'rate_limited';
  end if;
  update public.api_keys k set last_used_at = now() where k.id = key_row.id;
  perform set_config('crm.audit_source', 'api', true);
  return key_row;
end;
$$;

-- Page and page size of a list: page from 1, per_page 1..100 (50)
CREATE OR REPLACE FUNCTION "private"."api_page"("params" "jsonb", OUT "page" integer, OUT "per_page" integer) RETURNS "record"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select greatest(coalesce((params ->> 'page')::integer, 1), 1),
    least(greatest(coalesce((params ->> 'per_page')::integer, 50), 1), 100)
$$;

-- Tag ids of a request, all of the clinic
CREATE OR REPLACE FUNCTION "private"."api_tag_ids"("org_id" bigint, "value" "jsonb") RETURNS bigint[]
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  ids bigint[];
begin
  if value is null or value = 'null'::jsonb then
    return '{}'::bigint[];
  end if;
  if jsonb_typeof(value) <> 'array' then
    raise exception 'tags: ожидается массив id тегов' using errcode = '22023';
  end if;
  select coalesce(array_agg(distinct x::bigint), '{}'::bigint[]) into ids
  from jsonb_array_elements_text(value) as x;
  if exists (
    select 1 from unnest(ids) as i
    where not exists (select 1 from public.tags t where t.organization_id = org_id and t.id = i)
  ) then
    raise exception 'tags: неизвестный тег' using errcode = '23503';
  end if;
  return ids;
end;
$$;

-- A patient of the request: found by phone, else created. Returns
-- { patient_id, created }.
CREATE OR REPLACE FUNCTION "private"."api_find_or_create_patient"("org_id" bigint, "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  numbers text[];
  found_id bigint;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'patient: ожидается объект' using errcode = '22023';
  end if;
  select coalesce(array_agg(distinct private.normalize_phone(x)) filter (where private.normalize_phone(x) is not null), '{}'::text[])
  into numbers
  from (
    select body ->> 'phone' as x
    union all
    select jsonb_array_elements_text(case when jsonb_typeof(body -> 'phones') = 'array' then body -> 'phones' else '[]'::jsonb end)
  ) p;
  if cardinality(numbers) > 0 then
    select p.id into found_id from public.patients p
    where p.organization_id = org_id and p.phones && numbers
    order by p.last_seen desc, p.id desc
    limit 1;
    if found_id is not null then
      return jsonb_build_object('patient_id', found_id, 'created', false);
    end if;
  end if;
  if nullif(btrim(coalesce(body ->> 'first_name', '')), '') is null
    and nullif(btrim(coalesce(body ->> 'last_name', '')), '') is null
    and cardinality(numbers) = 0 then
    raise exception 'Укажите имя или телефон пациента' using errcode = '22023';
  end if;
  insert into public.patients (organization_id, first_name, last_name, middle_name, phone_jsonb, birth_date, city, source_id, sales_id, tags)
  values (
    org_id,
    nullif(btrim(body ->> 'first_name'), ''),
    nullif(btrim(body ->> 'last_name'), ''),
    nullif(btrim(body ->> 'middle_name'), ''),
    coalesce((select jsonb_agg(jsonb_build_object('number', n, 'type', 'mobile')) from unnest(numbers) as n), '[]'::jsonb),
    (body ->> 'birth_date')::date,
    nullif(btrim(body ->> 'city'), ''),
    (body ->> 'source_id')::bigint,
    (body ->> 'sales_id')::bigint,
    private.api_tag_ids(org_id, body -> 'tags')
  )
  returning id into found_id;
  return jsonb_build_object('patient_id', found_id, 'created', true);
end;
$$;

