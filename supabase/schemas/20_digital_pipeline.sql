--
-- Digital pipeline, outgoing webhooks and the public REST API (stage 20)
--
-- Digital pipeline («Цифровая воронка», as in amoCRM): per stage, triggers
-- «when X happens to a deal of this stage (and it matches the conditions),
-- do Y». They sit next to the task rules (stage 5) and the auto-message
-- rules (stage 6), which keep their own tables; the settings screen shows
-- the three of them in one grid, stages as columns.
--   events     stage_entered, message_in, message_out, call_missed,
--              payment_added, appointment_set (immediate, run by the
--              triggers of this file) and idle, visit_passed (delayed, run by
--              pg_cron through private.stage_triggers_tick every 5 minutes)
--   conditions source, service, doctor, responsible (any of the chosen ids),
--              tags present / absent
--   actions    move_stage, set_responsible, add_tag, remove_tag, create_task,
--              send_template (stage 6 queue), send_webhook, set_field
-- Every run is written to public.stage_trigger_runs (the deal feed shows it)
-- and happens at most once per (trigger, deal, event instance): the unique
-- event_key. A chain of automatic actions is limited by the session variable
-- crm.automation_depth (at most 3 nested actions). Automatic changes are
-- audited with the source 'automation'. An action that fails (a move blocked
-- by the stage checklist, a refusal without reason...) is logged as skipped
-- or failed and never raised to the sender of the event (an inbound message
-- must be stored whatever happens). Imports (crm.importing) run nothing.
--
-- Outgoing webhooks: the owner and the head register URLs with the events
-- they want. The triggers of this file queue one delivery per webhook
-- (public.webhook_deliveries); the edge function webhooks_dispatch, started
-- every minute by pg_cron through pg_net (Vault secrets project_url and
-- automessages_dispatch_key, as for the auto-messages), takes them
-- (public.claim_webhook_deliveries), posts the JSON signed with HMAC-SHA256
-- (per-webhook secret) and reports back (public.complete_webhook_delivery):
-- retries with backoff, and after 10 failures in a row the webhook is
-- switched off with the error shown in the settings.
--
-- Public REST API: API keys (read, or read + write) created by the owner and
-- the head; only the SHA-256 of a key is stored, the key is shown once. The
-- edge function api (Authorization: Bearer <key>) calls the public.api_*
-- functions below (service role only): they resolve the clinic from the key
-- hash, check the scope and a per-key limit of requests per minute, and work
-- inside that clinic only.
--

--
-- Tables
--

-- Outgoing webhooks of the clinic. The secret signs the deliveries; only the
-- owner and the head read it.
create table public.webhooks (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text,
    url text not null,
    events text[] not null default '{}'::text[],
    secret text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
    is_active boolean not null default true,
    -- Failed attempts in a row; reaching 10 switches the webhook off
    failure_count integer not null default 0,
    last_error text,
    last_success_at timestamp with time zone,
    last_failure_at timestamp with time zone,
    -- Switched off by the dispatcher after too many failures
    disabled_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    constraint webhooks_url_check check (url ~ '^https?://[^/\s]+'),
    constraint webhooks_events_check check (events <@ array['deal.created', 'deal.stage_changed', 'deal.won', 'deal.lost',
        'patient.created', 'message.received', 'payment.added', 'task.completed']::text[])
);

-- The delivery queue. pending -> sending -> delivered | pending (retry, later)
-- | failed (too many attempts); pending -> cancelled (webhook switched off).
-- Events: those of webhooks.events, 'automation' (action of a stage trigger)
-- and 'ping' (test from the settings).
create table public.webhook_deliveries (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    webhook_id bigint not null,
    event text not null,
    payload jsonb not null,
    status text not null default 'pending',
    attempts integer not null default 0,
    next_attempt_at timestamp with time zone not null default now(),
    response_status integer,
    error text,
    claimed_at timestamp with time zone,
    delivered_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    constraint webhook_deliveries_status_check check (status in ('pending', 'sending', 'delivered', 'failed', 'cancelled'))
);

-- A trigger of the digital pipeline: stage + event (+ conditions) -> action.
-- pipeline_id is filled from the stage (private.handle_stage_trigger_saved);
-- a move goes to a stage of the same pipeline.
create table public.stage_triggers (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    pipeline_id bigint not null,
    stage_id bigint not null,
    name text,
    event text not null,
    -- idle: minutes without activity; visit_passed: minutes after the visit
    delay_minutes integer not null default 0,
    -- Conditions: empty = any
    source_ids bigint[] not null default '{}'::bigint[],
    service_ids bigint[] not null default '{}'::bigint[],
    doctor_ids bigint[] not null default '{}'::bigint[],
    sales_ids bigint[] not null default '{}'::bigint[],
    tags_present bigint[] not null default '{}'::bigint[],
    tags_absent bigint[] not null default '{}'::bigint[],
    action text not null,
    target_stage_id bigint,
    -- set_responsible: null = the next one of the round robin
    target_sales_id bigint,
    tag_id bigint,
    task_type text,
    task_text text,
    task_due_minutes integer,
    template_id bigint,
    message_mode text,
    webhook_id bigint,
    field_name text,
    plan_amount bigint,
    doctor_id bigint,
    service_id bigint,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint stage_triggers_event_check check (event in ('stage_entered', 'message_in', 'message_out', 'call_missed',
        'idle', 'payment_added', 'appointment_set', 'visit_passed')),
    constraint stage_triggers_delay_check check (delay_minutes >= 0 and (event <> 'idle' or delay_minutes > 0)),
    constraint stage_triggers_action_check check (action in ('move_stage', 'set_responsible', 'add_tag', 'remove_tag',
        'create_task', 'send_template', 'send_webhook', 'set_field', 'start_salesbot')),
    constraint stage_triggers_move_check check (action <> 'move_stage' or (target_stage_id is not null and target_stage_id <> stage_id)),
    constraint stage_triggers_tag_check check (action not in ('add_tag', 'remove_tag') or tag_id is not null),
    constraint stage_triggers_task_check check (action <> 'create_task' or (
        task_type in ('call', 'message', 'reminder', 'other') and btrim(coalesce(task_text, '')) <> '' and task_due_minutes >= 0)),
    constraint stage_triggers_template_check check (action <> 'send_template' or (
        template_id is not null and coalesce(message_mode, 'auto') in ('auto', 'confirm'))),
    constraint stage_triggers_webhook_check check (action <> 'send_webhook' or webhook_id is not null),
    constraint stage_triggers_field_check check (action <> 'set_field' or (
        (field_name = 'plan_amount' and plan_amount >= 0)
        or (field_name = 'doctor_id' and doctor_id is not null)
        or (field_name = 'service_id' and service_id is not null)))
);

-- What the triggers did, per deal (deal feed, loop protection). status: done,
