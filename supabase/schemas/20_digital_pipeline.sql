-- Conditions of a trigger: every non-empty list must match the deal
CREATE OR REPLACE FUNCTION "private"."stage_trigger_matches"("trigger_row" "public"."stage_triggers", "deal" "public"."deals") RETURNS boolean
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select coalesce(
    (cardinality(trigger_row.source_ids) = 0 or deal.source_id = any(trigger_row.source_ids))
    and (cardinality(trigger_row.service_ids) = 0 or deal.service_id = any(trigger_row.service_ids))
    and (cardinality(trigger_row.doctor_ids) = 0 or deal.doctor_id = any(trigger_row.doctor_ids))
    and (cardinality(trigger_row.sales_ids) = 0 or deal.sales_id = any(trigger_row.sales_ids))
    and trigger_row.tags_present <@ deal.tags
    and not (trigger_row.tags_absent && deal.tags),
    false)
$$;

-- The action of a trigger on a deal; returns what changed (shown in the deal
-- feed). Raises when the action cannot be done (the caller logs it).
CREATE OR REPLACE FUNCTION "private"."apply_stage_trigger_action"("trigger_row" "public"."stage_triggers", "deal" "public"."deals") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := deal.organization_id;
  new_sales_id bigint;
  new_id bigint;
  zone text;
  template_body text;
  rendered text;
  old_value jsonb;
  queued integer;
begin
  case trigger_row.action
  when 'move_stage' then
    if deal.stage_id = trigger_row.target_stage_id then
      return jsonb_build_object('unchanged', true);
    end if;
    update public.deals d
    set stage_id = trigger_row.target_stage_id
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_stage_id', deal.stage_id, 'to_stage_id', trigger_row.target_stage_id);

  when 'set_responsible' then
    new_sales_id := coalesce(trigger_row.target_sales_id, private.next_responsible(org_id));
    if new_sales_id is null then
      raise exception 'Некому назначить: распределение по очереди не настроено' using errcode = '22023';
    end if;
    if exists (select 1 from public.sales s where s.id = new_sales_id and s.disabled) then
      raise exception 'Сотрудник отключён' using errcode = '22023';
    end if;
    if deal.sales_id is not distinct from new_sales_id then
      return jsonb_build_object('unchanged', true);
    end if;
    update public.deals d
    set sales_id = new_sales_id
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('from_sales_id', deal.sales_id, 'to_sales_id', new_sales_id);

  when 'add_tag' then
    if trigger_row.tag_id = any(deal.tags) then
      return jsonb_build_object('unchanged', true, 'tag_id', trigger_row.tag_id);
    end if;
    update public.deals d
    set tags = array_append(d.tags, trigger_row.tag_id)
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('tag_id', trigger_row.tag_id);

  when 'remove_tag' then
    if not trigger_row.tag_id = any(deal.tags) then
      return jsonb_build_object('unchanged', true, 'tag_id', trigger_row.tag_id);
    end if;
    update public.deals d
    set tags = array_remove(d.tags, trigger_row.tag_id)
    where d.organization_id = org_id and d.id = deal.id;
    return jsonb_build_object('tag_id', trigger_row.tag_id);

  when 'create_task' then
    -- Same as the task rules (private.create_rule_tasks)
    insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id)
    values (org_id, deal.id, trigger_row.task_type, btrim(trigger_row.task_text),
      now() + make_interval(mins => trigger_row.task_due_minutes), deal.sales_id)
    returning id into new_id;
    return jsonb_build_object('task_id', new_id);

  when 'send_template' then
    -- The stage 6 queue: "show first" becomes the task with the text and the
    -- «Отправить» button right away; "auto" is sent by the dispatcher
    -- (quiet hours apply, leaving the stage cancels it)
    if coalesce(trigger_row.message_mode, 'auto') = 'confirm' then
      select t.body into template_body from public.message_templates t
      where t.organization_id = org_id and t.id = trigger_row.template_id;
      rendered := private.render_template(template_body, private.automessage_vars(deal));
      insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at, status, text, processed_at)
      values (org_id, deal.id, null, trigger_row.template_id, deal.stage_id, 'after_stage', now(), 'awaiting', rendered, now())
      returning id into new_id;
      insert into public.tasks (organization_id, deal_id, type, text, due_date, sales_id, automessage_id)
      values (org_id, deal.id, 'message', rendered, now(), deal.sales_id, new_id);
    else
      select o.timezone into zone from public.organizations o where o.id = org_id;
      insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at)
      values (org_id, deal.id, null, trigger_row.template_id, deal.stage_id, 'after_stage',
        private.automessage_send_time(now(), zone))
      returning id into new_id;
    end if;
    return jsonb_build_object('automessage_id', new_id, 'template_id', trigger_row.template_id,
      'mode', coalesce(trigger_row.message_mode, 'auto'));

  when 'send_webhook' then
    queued := private.enqueue_webhook(org_id, 'automation',
      jsonb_build_object('deal_id', deal.id, 'patient_id', deal.patient_id,
        'trigger', jsonb_build_object('id', trigger_row.id, 'name', trigger_row.name, 'event', trigger_row.event),
        'deal', private.deal_json(deal)),
      trigger_row.webhook_id);
    if queued = 0 then
      raise exception 'Вебхук выключен' using errcode = '22023';
    end if;
    return jsonb_build_object('webhook_id', trigger_row.webhook_id);

  when 'start_salesbot' then
    -- «Запустить салесбот» (26_salesbot.sql): replaces the bot of the deal
    new_id := private.salesbot_start(trigger_row.salesbot_id, deal.id, 'pipeline');
    if new_id is null then
      raise exception 'Бот не запущен' using errcode = '22023';
    end if;
    return jsonb_build_object('salesbot_id', trigger_row.salesbot_id, 'session_id', new_id);

  when 'set_field' then
    old_value := to_jsonb(deal) -> trigger_row.field_name;
    if trigger_row.field_name = 'plan_amount' then
      update public.deals d set plan_amount = trigger_row.plan_amount
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'plan_amount', 'from', old_value, 'to', trigger_row.plan_amount);
    elsif trigger_row.field_name = 'doctor_id' then
      update public.deals d set doctor_id = trigger_row.doctor_id
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'doctor_id', 'from', old_value, 'to', trigger_row.doctor_id);
    else
      update public.deals d set service_id = trigger_row.service_id
      where d.organization_id = org_id and d.id = deal.id;
      return jsonb_build_object('field', 'service_id', 'from', old_value, 'to', trigger_row.service_id);
    end if;
  end case;
  return '{}'::jsonb;
end;
$$;

-- Runs one trigger on one deal for one event instance (event_key), once:
-- checks that the deal is still at the stage and matches the conditions,
-- records the run, applies the action one level deeper (crm.automation_depth,
-- at most 3 levels) with the audit source 'automation'. An error of the
-- action is caught and recorded: skipped for the stage checklist, failed
-- otherwise. Returns the status, or null when nothing ran.
CREATE OR REPLACE FUNCTION "private"."fire_stage_trigger"("trigger_row" "public"."stage_triggers", "target_deal_id" bigint, "instance_key" "text") RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  depth integer := coalesce(nullif(current_setting('crm.automation_depth', true), '')::integer, 0);
  previous_source text := coalesce(current_setting('crm.audit_source', true), '');
  run_id bigint;
  run_status text := 'done';
  result jsonb;
  error_hint text;
  error_message text;
begin
  if current_setting('crm.importing', true) = 'on' then
    return null;
  end if;
  select * into deal from public.deals d
  where d.organization_id = trigger_row.organization_id and d.id = target_deal_id;
  -- Unsorted leads (stage 18) wait for a person to accept them
  if not found or deal.archived_at is not null or deal.unsorted_at is not null
    or deal.stage_id <> trigger_row.stage_id
    or not private.stage_trigger_matches(trigger_row, deal) then
    return null;
  end if;

  insert into public.stage_trigger_runs (organization_id, deal_id, trigger_id, trigger_name, event, event_key, action)
  values (deal.organization_id, deal.id, trigger_row.id, trigger_row.name, trigger_row.event, instance_key,
    trigger_row.action)
  on conflict (trigger_id, deal_id, event_key) do nothing
  returning id into run_id;
  if run_id is null then
    return null;
  end if;

  if depth >= 3 then
    update public.stage_trigger_runs r
    set status = 'skipped', error = 'Слишком длинная цепочка автоматических действий'
    where r.id = run_id;
    return 'skipped';
  end if;

  perform set_config('crm.automation_depth', (depth + 1)::text, true);
  perform set_config('crm.audit_source', 'automation', true);
  begin
    result := private.apply_stage_trigger_action(trigger_row, deal);
  exception when others then
    get stacked diagnostics error_hint = pg_exception_hint, error_message = message_text;
    run_status := case when error_hint = 'stage_checklist_incomplete' then 'skipped' else 'failed' end;
  end;
  perform set_config('crm.automation_depth', depth::text, true);
  perform set_config('crm.audit_source', previous_source, true);

  update public.stage_trigger_runs r
  set status = run_status, details = coalesce(result, '{}'::jsonb), error = left(error_message, 500)
  where r.id = run_id;
  return run_status;
end;
$$;

-- The active triggers of the deal's stage for an immediate event
CREATE OR REPLACE FUNCTION "private"."run_stage_triggers"("deal" "public"."deals", "trigger_event" "text", "instance_key" "text") RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  trigger_row public.stage_triggers;
  fired integer := 0;
begin
  if current_setting('crm.importing', true) = 'on' or deal.archived_at is not null then
    return 0;
  end if;
  for trigger_row in
    select t.* from public.stage_triggers t
    where t.organization_id = deal.organization_id
      and t.stage_id = deal.stage_id
      and t.event = trigger_event
      and t.is_active
    order by t.position, t.id
  loop
    -- An earlier trigger may have moved the deal: fire_stage_trigger checks it
    if private.fire_stage_trigger(trigger_row, deal.id, instance_key) is not null then
      fired := fired + 1;
    end if;
  end loop;
  return fired;
end;
$$;

