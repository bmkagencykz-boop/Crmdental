-- GET /api/tasks?deal_id=&done=true|false&page=&per_page=
CREATE OR REPLACE FUNCTION "public"."api_list_tasks"("api_key" "text", "params" "jsonb" DEFAULT '{}'::"jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'tasks')).organization_id;
  page_number integer := (private.api_page(params)).page;
  page_size integer := (private.api_page(params)).per_page;
  f_deal bigint := (params ->> 'deal_id')::bigint;
  f_done boolean := (params ->> 'done')::boolean;
  total bigint;
  items jsonb;
begin
  select count(*) into total from public.tasks t
  where t.organization_id = org_id and (f_deal is null or t.deal_id = f_deal)
    and (f_done is null or (t.done_date is not null) = f_done);
  select coalesce(jsonb_agg(x.j order by x.due_date, x.id), '[]'::jsonb) into items
  from (
    select t.id, t.due_date, jsonb_build_object('id', t.id, 'deal_id', t.deal_id, 'type', t.type, 'text', t.text,
      'due_date', t.due_date, 'done_date', t.done_date, 'sales_id', t.sales_id, 'duration_minutes', t.duration_minutes,
      'result', t.result, 'created_at', t.created_at) as j
    from public.tasks t
    where t.organization_id = org_id and (f_deal is null or t.deal_id = f_deal)
      and (f_done is null or (t.done_date is not null) = f_done)
    order by t.due_date, t.id
    limit page_size offset (page_number - 1) * page_size
  ) x;
  return jsonb_build_object('data', items,
    'meta', jsonb_build_object('page', page_number, 'per_page', page_size, 'total', total));
end;
$$;

-- POST /api/tasks { deal_id, type, text, due_date, sales_id, duration_minutes }:
-- without sales_id the task goes to the responsible of the deal
