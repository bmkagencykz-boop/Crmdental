    task_type, task_text, task_due_minutes, template_id, message_mode, webhook_id, field_name, plan_amount, doctor_id,
    service_id, is_active, position)
  values (org_id, (select s.pipeline_id from public.stages s where s.organization_id = org_id and s.id = r.stage_id),
    r.stage_id, r.name, r.event, coalesce(r.delay_minutes, 0), coalesce(r.source_ids, '{}'), coalesce(r.service_ids, '{}'),
    coalesce(r.doctor_ids, '{}'), coalesce(r.sales_ids, '{}'), coalesce(r.tags_present, '{}'), coalesce(r.tags_absent, '{}'),
    r.action, r.target_stage_id, r.target_sales_id, r.tag_id, r.task_type, r.task_text, r.task_due_minutes, r.template_id,
    r.message_mode, r.webhook_id, r.field_name, r.plan_amount, r.doctor_id, r.service_id, coalesce(r.is_active, true),
    coalesce(r.position, 0))
  returning * into saved;
  return jsonb_build_object('data', private.api_stage_trigger_json(saved));
end;
$$;

-- PATCH /api/stage_triggers/:id: only the fields present in the body change
CREATE OR REPLACE FUNCTION "public"."api_update_stage_trigger"("api_key" "text", "trigger_id" bigint, "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'pipelines:write')).organization_id;
  current_row public.stage_triggers;
  r public.stage_triggers;
  saved public.stage_triggers;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  select * into current_row from public.stage_triggers t
  where t.organization_id = org_id and t.id = api_update_stage_trigger.trigger_id
  for update;
  if not found then
    raise exception 'Триггер не найден' using errcode = 'PT404', hint = 'not_found';
  end if;
  -- The current row, overwritten by the fields of the body
  r := jsonb_populate_record(current_row, body - 'id' - 'organization_id' - 'pipeline_id' - 'created_at');
  update public.stage_triggers t
  set stage_id = r.stage_id, name = r.name, event = r.event, delay_minutes = coalesce(r.delay_minutes, 0),
      source_ids = coalesce(r.source_ids, '{}'), service_ids = coalesce(r.service_ids, '{}'),
      doctor_ids = coalesce(r.doctor_ids, '{}'), sales_ids = coalesce(r.sales_ids, '{}'),
      tags_present = coalesce(r.tags_present, '{}'), tags_absent = coalesce(r.tags_absent, '{}'),
      action = r.action, target_stage_id = r.target_stage_id, target_sales_id = r.target_sales_id, tag_id = r.tag_id,
      task_type = r.task_type, task_text = r.task_text, task_due_minutes = r.task_due_minutes,
      template_id = r.template_id, message_mode = r.message_mode, webhook_id = r.webhook_id,
      field_name = r.field_name, plan_amount = r.plan_amount, doctor_id = r.doctor_id, service_id = r.service_id,
      is_active = coalesce(r.is_active, true), position = coalesce(r.position, 0)
  where t.organization_id = org_id and t.id = current_row.id
  returning * into saved;
  return jsonb_build_object('data', private.api_stage_trigger_json(saved));
end;
$$;

