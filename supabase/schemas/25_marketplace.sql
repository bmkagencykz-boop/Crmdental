--
-- Integrations marketplace, developer apps, fine API scopes and integrator
-- access (stage 25)
--
-- Developer apps («Приложения разработчиков»): an integrator (agency) or the
-- owner / head registers an app in the clinic — name, developer, links,
-- the scopes it needs and the webhook events it wants. Installing it
-- (public.install_developer_app) creates an API key bound to the app with
-- exactly these scopes (public.api_keys.app_id) and, with the scope
-- 'webhooks', a webhook subscription (public.webhooks.app_id). Uninstalling
-- revokes the key and deletes the webhooks. A manifest (JSON) carries the
-- same definition to other clinics (public.import_app_manifest).
--
-- Fine API scopes: api_keys.scopes lists them; a key without scopes is a key
-- of stage 20 and keeps its rights (read: deals:read, patients:read,
-- settings:read; write: plus deals:write and patients:write). Every public
-- api_* function asks private.api_authorize for the scope it needs.
--
-- Integrator (sales.role = 'integrator'): a technical account of an agency.
-- It configures the clinic (pipelines, stages, digital pipeline, automations,
-- auto-messages, quick replies, custom fields, integrations, API) and only
-- reads deals and patients; no money (payments, reports, plans), no staff,
-- no deleting. Message texts are hidden unless the owner turns on
-- sales.can_read_messages. After sales.access_expires_at the account
-- behaves as disabled (private.current_organization_id() and the other
-- helpers of 01_tables.sql return null). Rights are granted here, in one
-- place: permissive policies "Integrator can ..." next to the owner and head
-- ones for the configuration tables, restrictive policies "Integrators
-- cannot ..." / "Integrators do not see ..." on the operational tables.
--

--
-- Tables
--

-- Integrator access: until when, and whether the conversations are visible
alter table public.sales add column access_expires_at timestamp with time zone;
alter table public.sales add column can_read_messages boolean not null default false;

-- Fine scopes of a key (empty: the read / write key of stage 20) and the app
-- that owns it
alter table public.api_keys add column scopes text[] not null default '{}'::text[];
alter table public.api_keys add column app_id bigint;
alter table public.api_keys add constraint api_keys_scopes_check check (scopes <@ array['deals:read', 'deals:write',
    'patients:read', 'patients:write', 'messages:read', 'messages:write', 'tasks', 'settings:read', 'settings:write',
    'pipelines:write', 'salesbot:write', 'webhooks']::text[]);

-- Webhook subscription of an app (deleted with it)
alter table public.webhooks add column app_id bigint;

-- An app of a developer, registered in the clinic. slug: the id of its
-- manifest, the same in every clinic.
create table public.developer_apps (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    slug text not null,
    name text not null,
    description text,
    developer_name text not null,
    developer_contact text,
    website_url text,
    -- Page of the app where the clinic sets it up (opened from the catalog)
    settings_url text,
    scopes text[] not null default '{}'::text[],
    webhook_url text,
    webhook_events text[] not null default '{}'::text[],
    installed_at timestamp with time zone,
    installed_by bigint,
    api_key_id bigint,
    uninstalled_at timestamp with time zone,
    created_by bigint,
    created_at timestamp with time zone not null default now(),
    constraint developer_apps_slug_check check (slug ~ '^[a-z0-9][a-z0-9_-]{1,62}$'),
    constraint developer_apps_name_not_blank check (btrim(name) <> ''),
    constraint developer_apps_developer_not_blank check (btrim(developer_name) <> ''),
    constraint developer_apps_website_url_check check (website_url is null or website_url ~ '^https?://[^/\s]+'),
    constraint developer_apps_settings_url_check check (settings_url is null or settings_url ~ '^https?://[^/\s]+'),
    constraint developer_apps_webhook_url_check check (webhook_url is null or webhook_url ~ '^https?://[^/\s]+'),
    constraint developer_apps_scopes_check check (cardinality(scopes) > 0 and scopes <@ array['deals:read', 'deals:write',
        'patients:read', 'patients:write', 'messages:read', 'messages:write', 'tasks', 'settings:read', 'settings:write',
        'pipelines:write', 'salesbot:write', 'webhooks']::text[]),
    constraint developer_apps_webhook_events_check check (webhook_events <@ array['deal.created', 'deal.stage_changed',
        'deal.won', 'deal.lost', 'patient.created', 'message.received', 'payment.added', 'task.completed']::text[]),
    constraint developer_apps_webhook_check check (cardinality(webhook_events) = 0 or (webhook_url is not null and 'webhooks' = any(scopes))),
    constraint developer_apps_slug_key unique (organization_id, slug)
);

alter table public.developer_apps add constraint developer_apps_organization_id_id_key unique (organization_id, id);

alter table public.developer_apps
