alter table public.developer_apps
    add constraint developer_apps_installed_by_fkey foreign key (organization_id, installed_by) references public.sales(organization_id, id) on delete set null (installed_by);
alter table public.developer_apps
    add constraint developer_apps_created_by_fkey foreign key (organization_id, created_by) references public.sales(organization_id, id) on delete set null (created_by);
alter table public.developer_apps
    add constraint developer_apps_api_key_id_fkey foreign key (organization_id, api_key_id) references public.api_keys(organization_id, id) on delete set null (api_key_id);
alter table public.api_keys
    add constraint api_keys_app_id_fkey foreign key (organization_id, app_id) references public.developer_apps(organization_id, id) on delete set null (app_id);
alter table public.webhooks
    add constraint webhooks_app_id_fkey foreign key (organization_id, app_id) references public.developer_apps(organization_id, id) on delete cascade;

create index api_keys_app_id_idx on public.api_keys using btree (organization_id, app_id) where app_id is not null;
create index webhooks_app_id_idx on public.webhooks using btree (organization_id, app_id) where app_id is not null;

