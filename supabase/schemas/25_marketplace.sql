-- POST /api/messages { deal_id, text }: queued like an automatic message
-- (public.automessages without rule nor template, the text as given) and
-- sent within a minute by automessages_dispatch through the channel of the
-- conversation (Wazzup24 or the Telegram bot)
CREATE OR REPLACE FUNCTION "public"."api_send_message"("api_key" "text", "body" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := (private.api_authorize(api_key, 'messages:write')).organization_id;
  deal public.deals;
  message_text text := nullif(btrim(coalesce(body ->> 'text', '')), '');
  saved public.automessages;
begin
  if body is null or jsonb_typeof(body) <> 'object' then
    raise exception 'Ожидается JSON-объект' using errcode = '22023';
  end if;
  if message_text is null then
    raise exception 'Укажите text' using errcode = '22023';
  end if;
  if length(message_text) > 4000 then
    raise exception 'text: не длиннее 4000 символов' using errcode = '22023';
  end if;
  select * into deal from public.deals d where d.organization_id = org_id and d.id = (body ->> 'deal_id')::bigint;
  if not found then
    raise exception 'Сделка не найдена' using errcode = 'PT404', hint = 'not_found';
  end if;
  if not exists (
    select 1 from public.messenger_integrations i where i.organization_id = org_id and i.api_key is not null
  ) and not exists (
    select 1 from public.telegram_bots b where b.organization_id = org_id and b.bot_token is not null
  ) then
    raise exception 'Мессенджеры не подключены (Настройки → Мессенджеры)' using errcode = '23514';
  end if;
  insert into public.automessages (organization_id, deal_id, rule_id, template_id, stage_id, timing, send_at, text)
  values (org_id, deal.id, null, null, deal.stage_id, 'after_stage', now(), message_text)
  returning * into saved;
  return jsonb_build_object('data', jsonb_build_object('id', saved.id, 'deal_id', saved.deal_id,
    'status', 'queued', 'text', saved.text, 'send_at', saved.send_at));
end;
$$;

