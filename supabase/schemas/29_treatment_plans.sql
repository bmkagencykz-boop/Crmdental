-- The patients with the light patient card (first declared in
-- 19_custom_fields.sql; the new columns come last)
create or replace view public.patients_summary with (security_invoker = on) as
select
    p.id,
    p.organization_id,
    p.first_name,
    p.last_name,
    p.middle_name,
    p.phone_jsonb,
    p.phones,
    p.birth_date,
    p.city,
    p.whatsapp,
    p.instagram,
    p.telegram,
    p.source_id,
    p.tags,
    p.sales_id,
    p.gender,
    p.avatar,
    p.background,
    p.status,
    p.first_seen,
    p.last_seen,
    array_to_string(p.phones, ' ') as phone_fts,
    (
        select count(*)
        from public.deals d
        where d.organization_id = p.organization_id and d.patient_id = p.id
    ) as nb_deals,
    (
        select count(*)
        from public.deals d
            join public.stages s on s.id = d.stage_id
        where d.organization_id = p.organization_id and d.patient_id = p.id and s.kind = 'open'
    ) as nb_open_deals,
    (
        select count(*)
        from public.tasks t
            join public.deals d on d.organization_id = t.organization_id and d.id = t.deal_id
        where d.organization_id = p.organization_id and d.patient_id = p.id and t.done_date is null
    ) as nb_tasks,
    p.custom_values,
    p.allergies,
    p.contraindications,
    p.chronic_diseases,
    p.preferred_doctor_id
from public.patients p;

-- Plans with their totals and progress (deal page, patient card, estimate)
create or replace view public.treatment_plans_summary with (security_invoker = on) as
select
    tp.id,
    tp.organization_id,
    tp.deal_id,
    tp.patient_id,
    tp.name,
    tp.status,
    tp.is_main,
    tp.discount_percent,
    tp.discount_amount,
    tp.note,
    tp.doctor_id,
    tp.created_by,
    tp.agreed_at,
    tp.created_at,
    tp.updated_at,
    t.items_count,
    t.done_count,
    t.gross_amount,
    t.subtotal_amount,
    t.done_amount,
    private.treatment_plan_total(t.subtotal_amount, tp.discount_percent, tp.discount_amount) as total_amount,
    t.gross_amount - private.treatment_plan_total(t.subtotal_amount, tp.discount_percent, tp.discount_amount) as discount_total,
    d.name as deal_name,
    d.paid_amount as deal_paid_amount
from public.treatment_plans tp
    join public.deals d on d.organization_id = tp.organization_id and d.id = tp.deal_id
    cross join lateral (
        select
            count(i.id)::integer as items_count,
            (count(i.id) filter (where i.done))::integer as done_count,
            coalesce(sum(i.quantity * i.unit_price), 0)::bigint as gross_amount,
            coalesce(sum(i.line_total), 0)::bigint as subtotal_amount,
            coalesce(sum(i.line_total) filter (where i.done), 0)::bigint as done_amount
        from public.treatment_plan_items i
        where i.organization_id = tp.organization_id and i.plan_id = tp.id
    ) t;

-- Subtotal of every stage of a plan
create or replace view public.treatment_plan_stages with (security_invoker = on) as
select
    i.organization_id,
    i.plan_id,
    i.stage_no,
    count(*)::integer as items_count,
    (count(*) filter (where i.done))::integer as done_count,
    sum(i.line_total)::bigint as subtotal_amount
from public.treatment_plan_items i
group by i.organization_id, i.plan_id, i.stage_no;

