--
-- Row Level Security
--

alter table public.treatment_plans enable row level security;
alter table public.treatment_plan_items enable row level security;

-- Plans follow the visibility of their deal; the integrator sees no money
create policy "Rows of visible deals can be read" on public.treatment_plans for select to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) <> 'integrator'
        and exists (select 1 from public.deals d where d.organization_id = treatment_plans.organization_id and d.id = treatment_plans.deal_id));
create policy "Staff can insert on visible deals" on public.treatment_plans for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head', 'manager')
        and exists (select 1 from public.deals d where d.organization_id = treatment_plans.organization_id and d.id = treatment_plans.deal_id));
create policy "Staff can update on visible deals" on public.treatment_plans for update to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head', 'manager')
        and exists (select 1 from public.deals d where d.organization_id = treatment_plans.organization_id and d.id = treatment_plans.deal_id))
    with check (organization_id = (select private.current_organization_id()));
create policy "Staff can delete on visible deals" on public.treatment_plans for delete to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head', 'manager')
        and exists (select 1 from public.deals d where d.organization_id = treatment_plans.organization_id and d.id = treatment_plans.deal_id));

-- Items follow their plan (the sub-query applies the plans policy)
create policy "Items of visible plans can be read" on public.treatment_plan_items for select to authenticated
    using (organization_id = (select private.current_organization_id())
        and exists (select 1 from public.treatment_plans p where p.organization_id = treatment_plan_items.organization_id and p.id = treatment_plan_items.plan_id));
create policy "Staff can insert items" on public.treatment_plan_items for insert to authenticated
    with check (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head', 'manager')
        and exists (select 1 from public.treatment_plans p where p.organization_id = treatment_plan_items.organization_id and p.id = treatment_plan_items.plan_id));
create policy "Staff can update items" on public.treatment_plan_items for update to authenticated
    using (organization_id = (select private.current_organization_id()) and (select private.current_user_role()) in ('owner', 'head', 'manager')
        and exists (select 1 from public.treatment_plans p where p.organization_id = treatment_plan_items.organization_id and p.id = treatment_plan_items.plan_id))
