-- The total of a plan from its subtotal (Σ line_total) and its discounts,
-- whole tenge, never below zero. Twin: planTotal() in planMath.ts
CREATE OR REPLACE FUNCTION "private"."treatment_plan_total"("subtotal" bigint, "discount_percent" numeric, "discount_amount" bigint) RETURNS bigint
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select greatest(0, subtotal - round(subtotal * discount_percent / 100)::bigint - discount_amount);
$$;

-- «Хронические: …» of two merged patients: one text, or both
CREATE OR REPLACE FUNCTION "private"."merge_note_text"("kept" "text", "merged" "text") RETURNS "text"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select case
    when nullif(btrim(kept), '') is null then nullif(btrim(merged), '')
    when nullif(btrim(merged), '') is null or btrim(merged) = btrim(kept) then kept
    else kept || E'\n' || btrim(merged)
  end;
$$;

-- The discount limit of the clinic, for an employee who is not the owner or
-- the head (a system write has no role: no limit). Raises 42501.
CREATE OR REPLACE FUNCTION "private"."check_treatment_discount"("org_id" bigint, "discount_percent" numeric, "subtotal" bigint, "discount_amount" bigint) RETURNS "void"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  role text := private.current_user_role();
  max_percent numeric;
begin
  if role is null or role in ('owner', 'head')
    or current_setting('crm.treatment_copy', true) = 'on' then
    return;
  end if;
  select s.max_discount_percent into max_percent
  from public.organization_settings s where s.organization_id = org_id;
  max_percent := coalesce(max_percent, 10);
  -- percent and amount together, against the subtotal
  if discount_percent > max_percent
    or coalesce(subtotal, 0) * discount_percent + coalesce(discount_amount, 0) * 100 > max_percent * coalesce(subtotal, 0) then
    raise exception 'Скидка больше % %% — только владелец или руководитель', trim_scale(max_percent)
      using errcode = '42501', hint = 'discount_limit';
  end if;
end;
$$;

-- deals.plan_amount = the total of the main plan of the deal
CREATE OR REPLACE FUNCTION "private"."sync_treatment_plan_amount"("target_plan_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  plan public.treatment_plans;
  total bigint;
begin
  select * into plan from public.treatment_plans p where p.id = target_plan_id;
  if not found or not plan.is_main then
    return;
  end if;
  select private.treatment_plan_total(coalesce(sum(i.line_total), 0)::bigint, plan.discount_percent, plan.discount_amount)
  into total
  from public.treatment_plan_items i
  where i.organization_id = plan.organization_id and i.plan_id = plan.id;
  update public.deals d
  set plan_amount = total
  where d.organization_id = plan.organization_id and d.id = plan.deal_id
    and d.plan_amount is distinct from total;
end;
$$;

-- An agreed plan moves its deal forward to «План согласован» of the deal's
-- pipeline (when the pipeline has it), like the digital pipeline: never
-- backwards, never out of a closed deal or «Неразобранное». A refused move
-- (stage checklist) is skipped and written to the deal feed.
CREATE OR REPLACE FUNCTION "private"."treatment_plan_move_stage"("plan" "public"."treatment_plans") RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  current_stage public.stages;
  target_stage public.stages;
  reason text;
  previous_source text := coalesce(current_setting('crm.audit_source', true), '');
begin
  if current_setting('crm.importing', true) = 'on' then
    return null;
  end if;
  select * into deal from public.deals d where d.organization_id = plan.organization_id and d.id = plan.deal_id;
  if not found or deal.archived_at is not null or deal.unsorted_at is not null then
    return null;
  end if;
  select * into current_stage from public.stages s where s.id = deal.stage_id;
  select * into target_stage from public.stages s
  where s.organization_id = deal.organization_id and s.pipeline_id = deal.pipeline_id
    and s.kind = 'open' and s.name = 'План согласован'
  order by s.position, s.id
  limit 1;
  if target_stage.id is null or current_stage.kind <> 'open'
    or target_stage.position <= current_stage.position then
    return null;
  end if;

  perform set_config('crm.audit_source', 'automation', true);
  begin
    update public.deals d
    set stage_id = target_stage.id
    where d.organization_id = deal.organization_id and d.id = deal.id;
  exception when others then
    get stacked diagnostics reason = message_text;
  end;
  perform set_config('crm.audit_source', previous_source, true);

  insert into public.stage_trigger_runs (organization_id, deal_id, trigger_id, trigger_name, event, event_key, action, status, details, error)
  values (deal.organization_id, deal.id, null, 'План лечения «' || plan.name || '»', 'treatment_plan',
    'treatment_plan:' || plan.id || ':' || extract(epoch from clock_timestamp()),
    'move_stage', case when reason is null then 'done' else 'skipped' end,
    jsonb_build_object('from_stage_id', deal.stage_id, 'to_stage_id', target_stage.id, 'plan_id', plan.id),
    left(reason, 500));
  return case when reason is null then 'done' else 'skipped' end;
end;
$$;

-- Before a plan is written: the patient and the doctor of the deal, the
-- status rules (agreed → main plan of the deal, agreed_at), the discount
-- limit
CREATE OR REPLACE FUNCTION "private"."handle_treatment_plan_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  deal public.deals;
  subtotal bigint;
begin
  if tg_op = 'UPDATE' and new.deal_id is distinct from old.deal_id then
    raise exception 'План лечения не переносится в другую сделку' using errcode = '22023';
  end if;
  select * into deal from public.deals d where d.organization_id = new.organization_id and d.id = new.deal_id;
  if tg_op = 'INSERT' then
    new.patient_id := deal.patient_id;
    new.doctor_id := coalesce(new.doctor_id, deal.doctor_id);
  end if;
  new.name := coalesce(nullif(btrim(new.name), ''), 'План лечения');

  if new.status in ('draft', 'presented', 'declined') then
    new.is_main := false;
    if new.status <> 'declined' then
      new.agreed_at := null;
    end if;
  elsif tg_op = 'INSERT' then
    new.agreed_at := coalesce(new.agreed_at, now());
    new.is_main := true;
  elsif old.status in ('draft', 'presented', 'declined') then
    -- Agreed now: the main plan of the deal
    new.agreed_at := now();
    new.is_main := true;
  end if;
  if new.is_main and (tg_op = 'INSERT' or not old.is_main) then
    update public.treatment_plans p
    set is_main = false
    where p.organization_id = new.organization_id and p.deal_id = new.deal_id
      and p.is_main and p.id <> new.id;
  end if;

  if (tg_op = 'INSERT' and (new.discount_percent > 0 or new.discount_amount > 0))
    or (tg_op = 'UPDATE' and (new.discount_percent <> old.discount_percent or new.discount_amount <> old.discount_amount)) then
    select coalesce(sum(i.line_total), 0) into subtotal
    from public.treatment_plan_items i
    where i.organization_id = new.organization_id and i.plan_id = new.id;
    perform private.check_treatment_discount(new.organization_id, new.discount_percent, subtotal, new.discount_amount);
  end if;
  new.updated_at := now();
  return new;
end;
$$;

-- After a plan is written: the plan amount of the deal, and the stage when
-- the plan was just agreed
CREATE OR REPLACE FUNCTION "private"."handle_treatment_plan_after_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if new.is_main and (tg_op = 'INSERT' or not old.is_main
    or new.discount_percent <> old.discount_percent or new.discount_amount <> old.discount_amount) then
    perform private.sync_treatment_plan_amount(new.id);
  end if;
  if new.status = 'agreed' and (tg_op = 'INSERT' or old.status in ('draft', 'presented', 'declined')) then
    perform private.treatment_plan_move_stage(new);
  end if;
  return null;
end;
$$;

-- Before an item is written: the name of the service, the done time, the
-- discount limit and the price list for the managers
CREATE OR REPLACE FUNCTION "private"."handle_treatment_item_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  role text := private.current_user_role();
  service public.services;
begin
  if tg_op = 'UPDATE' and new.plan_id is distinct from old.plan_id then
    raise exception 'Позиция не переносится в другой план' using errcode = '22023';
  end if;
  if new.service_id is not null then
    select * into service from public.services s
    where s.organization_id = new.organization_id and s.id = new.service_id;
  end if;
  new.name := coalesce(nullif(btrim(new.name), ''), service.name);
  new.tooth := nullif(btrim(new.tooth), '');
  if new.done and (tg_op = 'INSERT' or not old.done) then
    new.done_at := now();
  elsif not new.done then
    new.done_at := null;
  end if;

  if role is not null and role not in ('owner', 'head')
    and current_setting('crm.treatment_copy', true) is distinct from 'on' then
    if new.discount_percent > 0 and (tg_op = 'INSERT' or new.discount_percent <> old.discount_percent) then
      perform private.check_treatment_discount(new.organization_id, new.discount_percent, 0, 0);
    end if;
    if service.price is not null and new.unit_price < round(service.price)
      and (tg_op = 'INSERT' or new.unit_price <> old.unit_price or new.service_id is distinct from old.service_id) then
      raise exception 'Цена ниже прайса (% ₸) — только владелец или руководитель', private.format_tenge(service.price)
        using errcode = '42501', hint = 'price_below_list';
    end if;
  end if;
  return new;
end;
$$;

-- After items change: the progress of an agreed plan (some done: in
-- progress, all done: completed) and the plan amount of the deal
CREATE OR REPLACE FUNCTION "private"."handle_treatment_item_after_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := coalesce(new.organization_id, old.organization_id);
  target_plan_id bigint := coalesce(new.plan_id, old.plan_id);
  plan public.treatment_plans;
  total_items integer;
  done_items integer;
  next_status text;
begin
  select * into plan from public.treatment_plans p
  where p.organization_id = org_id and p.id = target_plan_id;
  if not found then
    return null;
  end if;
  if plan.status in ('agreed', 'in_progress', 'completed') then
    select count(*), count(*) filter (where i.done) into total_items, done_items
    from public.treatment_plan_items i
    where i.organization_id = org_id and i.plan_id = plan.id;
    next_status := case
      when total_items > 0 and done_items = total_items then 'completed'
      when plan.status = 'completed' then 'in_progress'
      when done_items > 0 and plan.status = 'agreed' then 'in_progress'
      else plan.status
    end;
    if next_status <> plan.status then
      update public.treatment_plans p set status = next_status
      where p.organization_id = org_id and p.id = plan.id;
    end if;
  end if;
  if plan.is_main then
    perform private.sync_treatment_plan_amount(plan.id);
  end if;
  return null;
end;
$$;

-- A deal moved to another patient (patients merged) takes its plans along
CREATE OR REPLACE FUNCTION "private"."handle_deal_patient_plans"() RETURNS "trigger"
