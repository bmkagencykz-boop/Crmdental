--
-- Treatment plans with an estimate («План лечения и смета», stage 29), the
-- price list and the light patient card
--
-- Elements of a MIS, not a MIS: no medical record, no tooth chart, no
-- inventory, no receipts. What a sales CRM of a dental clinic needs to sell
-- a treatment:
--
--   services               the price list: the same table as before (the
--                          deal's «Услуга» picker, reports), with a code, a
--                          category (free text with suggestions in the app)
--                          and the price of stage 24. «Активна» is
--                          not is_archived. Only the owner and the head (and
--                          the integrator of stage 25) edit it (05_policies).
--   treatment_plans        several plans per deal («Вариант эконом /
--                          премиум»): status draft → presented → agreed →
--                          in_progress → completed, or declined; discounts of
--                          the plan (percent and/or amount); the doctor
--                          (the deal's by default). The patient is the
--                          deal's (set by the trigger, moved with the deal).
--   treatment_plan_items   the positions: stage of the treatment (1..n,
--                          «Этап 1, 2…»), the service (optional) and its name
--                          (a copy, editable), the tooth as free text
--                          («36», «11-13»), quantity, unit price, discount,
--                          done. line_total is computed by the database.
--
-- Totals, in whole tenge (the TS twin is src/components/atomic-crm/treatment/
-- planMath.ts):
--   line_total = round(quantity × unit_price × (100 − discount %) / 100)
--   subtotal   = Σ line_total (per stage: public.treatment_plan_stages)
--   total      = max(0, subtotal − round(subtotal × plan discount % / 100)
--                − plan discount amount)      (private.treatment_plan_total)
-- public.treatment_plans_summary gives every plan with its totals and
-- progress (items done).
--
-- The main plan of the deal: a plan that becomes agreed is the deal's main
-- plan (is_main, one per deal: a unique index; the previous main plan keeps
-- its status). deals.plan_amount follows the total of the main plan (when
-- it is agreed, and when its items or discounts change), and the deal moves
-- forward to the stage «План согласован» of its pipeline when there is one,
-- with the rules of the digital pipeline: forward only, never out of a
-- closed deal; the stage checklist may refuse the move — the refusal is
-- written to the deal feed (stage_trigger_runs, without trigger). Marking
-- items done moves an agreed plan to in_progress, all items done to
-- completed.
--
-- Rights: whoever sees the deal sees its plans (not the integrator: no
-- money); owner, head and manager create and edit them. A discount above
-- organization_settings.max_discount_percent (10 % by default) — of an item,
-- or of the plan (percent and amount together, against its subtotal) — and
-- a price below the price list are for the owner and the head only.
--
-- The light patient card: allergies, contraindications, chronic diseases
-- (free text) and the preferred doctor. Merging patients keeps both texts.
--
-- Template variable {сумма_плана} (08_automessages.sql): the plan amount of
-- the deal, i.e. the total of its agreed plan.
--

