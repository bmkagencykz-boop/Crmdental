--
-- Marketing analytics («Маркетинговая аналитика», stage 32): the UTM tags of
-- a deal, the utm_source → lead source mapping, the ad spend, and the
-- report «Маркетинг» (spend, leads, cost per lead, came, paid, revenue, ROMI
-- per source and per campaign).
--
--   deals.utm_source … utm_term   the tags of the website form that brought
--   deals.referrer, landing_page  the request (public.ingest_lead: first touch,
--                                 an open deal keeps its tags), editable on
--                                 the deal page («Источник/UTM»)
--   lead_sources.utm_sources      utm_source values of a lead source
--                                 (Settings → Заявки с сайта): a deal with
--                                 such a utm_source gets that source
--   public.ad_spend               spend on advertising: a source, an optional
--                                 campaign (matched with deals.utm_campaign,
--                                 case-insensitive), a date range (a month
--                                 by default), an amount in tenge
--
-- utm_source → lead source (private.utm_lead_source): a source listing the
-- value in utm_sources, else a source whose code or name is the value
-- (utm_source=instagram → «Instagram»). In public.ingest_lead the mapped
-- source wins over the form's `source` field (the tag names the advert that
-- paid for the click); a deal written without a source (deal page, import)
-- gets it too (BEFORE trigger deal_attribution).
--
-- public.report_marketing(period_from, period_to, filter_source_id), in the
-- style of 09_reports.sql (owner and head only, periods half-open, dates of
-- money in the clinic's time zone). Per source, per campaign and in total:
--   spend    the ad spend of the period; a range crossing a bound of the
--            period counts pro rata of its days (rounded per row)
--   leads    deals created in the period
--   came     among them, deals that reached «Пришёл на консультацию» (the
--            key stage of the reports) or have a visit date (a visit of the
--            schedule marked «Пришёл» / «Приём завершён» sets it)
--   paid     among them, deals with a payment dated in the period
--   revenue  those payments
--   cpl, cost_per_came, cost_per_paid   spend / count (null without spend)
--   romi     (revenue − spend) / spend, in whole percent (null without spend)
-- The TS twin for the demo is src/components/atomic-crm/marketing/
-- marketingMath.ts.
--
-- Rights: the ad spend is money: the owner and the head read and write it
-- (RLS), like the reports; managers and the integrator see none of it. The
-- UTM tags of a deal follow the deal. The mapping is edited by whoever
-- edits the lead sources.
--

