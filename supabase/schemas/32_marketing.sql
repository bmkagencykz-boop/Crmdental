-- The lead source of an utm_source value: listed in a source's utm_sources,
-- else the code or the name of a source (case-insensitive); null if none
CREATE OR REPLACE FUNCTION "private"."utm_lead_source"("org_id" bigint, "utm_value" "text") RETURNS bigint
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
  select s.id
  from public.lead_sources s
  where s.organization_id = org_id
    and nullif(btrim(utm_value), '') is not null
    and (
      exists (select 1 from unnest(s.utm_sources) u where lower(btrim(u)) = lower(btrim(utm_value)))
      or lower(s.code) = lower(btrim(utm_value))
      or lower(s.name) = lower(btrim(utm_value))
    )
  order by
    exists (select 1 from unnest(s.utm_sources) u where lower(btrim(u)) = lower(btrim(utm_value))) desc,
    s.is_archived, s.position, s.id
  limit 1
$$;

-- UTM tags of a deal: trimmed (blank is null), at most 500 characters; a
-- deal without a source takes the one its utm_source maps to
CREATE OR REPLACE FUNCTION "private"."handle_deal_attribution"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.utm_source := left(nullif(btrim(new.utm_source), ''), 500);
  new.utm_medium := left(nullif(btrim(new.utm_medium), ''), 500);
  new.utm_campaign := left(nullif(btrim(new.utm_campaign), ''), 500);
  new.utm_content := left(nullif(btrim(new.utm_content), ''), 500);
  new.utm_term := left(nullif(btrim(new.utm_term), ''), 500);
  new.referrer := left(nullif(btrim(new.referrer), ''), 2000);
  new.landing_page := left(nullif(btrim(new.landing_page), ''), 2000);
  if new.source_id is null and new.utm_source is not null
    and (tg_op = 'INSERT' or new.utm_source is distinct from old.utm_source) then
    new.source_id := private.utm_lead_source(new.organization_id, new.utm_source);
  end if;
  return new;
end;
$$;

-- utm_sources of a lead source: trimmed, lower case, without blanks and
-- repeats
CREATE OR REPLACE FUNCTION "private"."handle_lead_source_utm"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.utm_sources := coalesce((
    select array_agg(v order by first_at)
    from (
      select lower(btrim(u)) as v, min(n) as first_at
      from unnest(new.utm_sources) with ordinality as t(u, n)
      where nullif(btrim(u), '') is not null
      group by lower(btrim(u))
    ) cleaned
  ), '{}'::text[]);
  return new;
end;
$$;

-- Marketing: spend, leads, came, paid, revenue, cost per lead / came /
-- paid and ROMI of the period, per source (with its campaigns) and in
-- total. See the header of this file.
CREATE OR REPLACE FUNCTION "public"."report_marketing"("period_from" timestamp with time zone DEFAULT NULL::timestamp with time zone, "period_to" timestamp with time zone DEFAULT NULL::timestamp with time zone, "filter_source_id" bigint DEFAULT NULL::bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  clinic_tz text;
  first_day date;
  after_last_day date;
  report jsonb;
begin
  perform private.report_check_access();
  select o.timezone into clinic_tz
  from public.organizations o
  where o.id = org_id;
  first_day := (period_from at time zone coalesce(clinic_tz, 'Asia/Almaty'))::date;
  after_last_day := (period_to at time zone coalesce(clinic_tz, 'Asia/Almaty'))::date;

  with spend as (
    -- A range crossing a bound of the period counts pro rata of its days
    select
      a.source_id,
      nullif(lower(btrim(a.campaign)), '') as campaign,
      round(
        a.amount::numeric
        * (least(a.spent_to + 1, coalesce(after_last_day, a.spent_to + 1)) - greatest(a.spent_from, coalesce(first_day, a.spent_from)))
        / (a.spent_to + 1 - a.spent_from)
      )::bigint as amount
    from public.ad_spend a
    where a.organization_id = org_id
      and (filter_source_id is null or a.source_id = filter_source_id)
      and (first_day is null or a.spent_to >= first_day)
      and (after_last_day is null or a.spent_from < after_last_day)
  ),
  leads as (
    select
      d.source_id,
      nullif(lower(btrim(dl.utm_campaign)), '') as campaign,
      (d.reached_visit or dl.visit_at is not null) as came,
      coalesce((
        select sum(p.amount)
        from public.deal_payments p
        where p.organization_id = org_id and p.deal_id = d.deal_id
          and (first_day is null or p.paid_at >= first_day)
          and (after_last_day is null or p.paid_at < after_last_day)
      ), 0) as revenue
    from private.report_deal_progress(null, null, filter_source_id, null) d
      join public.deals dl on dl.organization_id = org_id and dl.id = d.deal_id
    where (period_from is null or d.created_at >= period_from)
      and (period_to is null or d.created_at < period_to)
  ),
  facts as (
    select s.source_id, s.campaign, s.amount as spend, 0 as leads, 0 as came, 0 as paid, 0::numeric as revenue
    from spend s
    union all
    select l.source_id, l.campaign, 0, 1, l.came::integer, (l.revenue > 0)::integer, l.revenue
    from leads l
  ),
  grouped as (
    select
      grouping(f.source_id) as all_sources,
      grouping(f.campaign) as all_campaigns,
      f.source_id,
      f.campaign,
      coalesce(sum(f.spend), 0)::bigint as spend,
      coalesce(sum(f.leads), 0)::bigint as leads,
      coalesce(sum(f.came), 0)::bigint as came,
      coalesce(sum(f.paid), 0)::bigint as paid,
      coalesce(sum(f.revenue), 0)::bigint as revenue
    from facts f
    group by grouping sets ((), (f.source_id), (f.source_id, f.campaign))
  ),
  metrics as (
    select g.*, jsonb_build_object(
      'spend', g.spend,
      'leads', g.leads,
      'came', g.came,
      'paid', g.paid,
      'revenue', g.revenue,
      'cpl', case when g.spend > 0 and g.leads > 0 then round(g.spend::numeric / g.leads) end,
      'cost_per_came', case when g.spend > 0 and g.came > 0 then round(g.spend::numeric / g.came) end,
      'cost_per_paid', case when g.spend > 0 and g.paid > 0 then round(g.spend::numeric / g.paid) end,
      'romi', case when g.spend > 0 then round((g.revenue - g.spend)::numeric * 100 / g.spend) end
    ) as row_json
    from grouped g
  )
  select jsonb_build_object(
    -- The grand total row exists even without any fact
    'totals', (select m.row_json from metrics m where m.all_sources = 1),
    'by_source', (
      select coalesce(jsonb_agg(
        jsonb_build_object('id', m.source_id, 'name', ls.name) || m.row_json
        || jsonb_build_object('campaigns', (
          select coalesce(jsonb_agg(
            jsonb_build_object('campaign', c.campaign) || c.row_json
            order by c.spend desc, c.leads desc, c.campaign nulls last
          ), '[]'::jsonb)
          from metrics c
          where c.all_sources = 0 and c.all_campaigns = 0
            and c.source_id is not distinct from m.source_id
        ))
        order by m.spend desc, m.leads desc, ls.position, ls.id
      ), '[]'::jsonb)
      from metrics m
        left join public.lead_sources ls on ls.id = m.source_id
      where m.all_sources = 0 and m.all_campaigns = 1
    )
  ) into report;
  return report;
end;
$$;

