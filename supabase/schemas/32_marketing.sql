-- Before deal_before_write (alphabetical order): the source is set before
-- the distribution and the stage rules read it
create or replace trigger deal_attribution
    before insert or update on public.deals
    for each row execute function private.handle_deal_attribution();

create or replace trigger lead_source_utm
    before insert or update of utm_sources on public.lead_sources
    for each row execute function private.handle_lead_source_utm();

create or replace trigger audit_ad_spend
    after insert or update or delete on public.ad_spend
    for each row execute function private.audit_row('ad_spend', 'source_id,campaign,spent_from,spent_to,amount,comment');

