--
-- Branches «Филиалы» (stage 33): a clinic network with several addresses.
--
--   public.branches          dictionary of the clinic: name, address, phone,
--                            active switch, order (owner and head)
--   public.sales_branches    the branches an employee works in (one or several)
--   branch_id                of a deal (where the patient goes), a doctor, a
--                            chair, a visit, a task (the branch of its deal,
--                            kept by triggers, for the lists) and a messenger
--                            channel (new leads of the channel land there)
--
-- Nullable everywhere: a clinic without branches (or with one) works exactly
-- as before, the interface shows the branches from the second one on. A row
-- without a branch is «общий»: a doctor or a chair of every branch, a deal
-- or a visit of the whole network (a lead of a channel mapped to no branch).
-- No default branch is created: every writer (forms, import, API, salesbot,
-- MIS) keeps working without knowing about branches, and nothing is moved
-- in existing clinics. When a clinic opens its second address, the owner
-- attaches the existing deals and visits to the first branch in one click
-- (public.assign_branch_to_unassigned).
--
-- The branch of a new deal: the one given (deal form, website form field
-- `branch`, the channel of a message, the clinic number of a call), else the
-- doctor's, else the branch of its responsible (or of the employee creating
-- it) when they work in one branch only (trigger deal_assign_branch, before
-- the distribution). A visit takes the branch of its chair, else of its
-- doctor, else of its deal.
--
-- Leads of a branch are distributed among the chosen employees who work in
-- that branch (round robin, «first to answer», notifications); when none of
-- them does, among all the chosen ones (private.branch_pool), so no lead is
-- lost.
--
-- Rights: the scope «Мой филиал» ('branch', 30_access_rights.sql) for deals
-- and tasks: own rows, rows of the employee's branches and rows without a
-- branch (private.current_branch_ids(), declared in 01_tables.sql because
-- the policies of 05_policies.sql use it). Patients are shared by the
-- network (one card). The dictionary and the employees' branches: the owner
-- and the head write, everybody reads. A channel's branch: the owner and the
-- head (column grant).
--
-- Reports take an optional filter_branch_id (09_reports.sql,
-- 29_treatment_plans.sql).
--

--
-- Tables and columns
--

create table public.branches (
    id bigint generated by default as identity primary key,
    organization_id bigint not null default private.current_organization_id(),
    name text not null,
    address text,
    phone text,
    is_active boolean not null default true,
    position integer not null default 0,
    created_at timestamp with time zone not null default now(),
    constraint branches_name_not_blank check (btrim(name) <> ''),
    constraint branches_address_length check (address is null or char_length(address) <= 500),
    constraint branches_phone_length check (phone is null or char_length(phone) <= 50)
);

create table public.sales_branches (
