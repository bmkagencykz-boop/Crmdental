-- Before deal_attribution and deal_before_write (alphabetical order)
create or replace trigger deal_assign_branch
    before insert or update on public.deals
    for each row execute function private.handle_deal_branch();

create or replace trigger deal_branch_changed
    after update of branch_id on public.deals
    for each row
    when (old.branch_id is distinct from new.branch_id)
    execute function private.handle_deal_branch_changed();

create or replace trigger task_branch
    before insert or update of deal_id, branch_id on public.tasks
    for each row execute function private.handle_task_branch();

create or replace trigger visit_branch
    before insert or update on public.visits
    for each row execute function private.handle_visit_branch();

create or replace trigger audit_branch
    after insert or update or delete on public.branches
    for each row execute function private.audit_row('branch', 'name,address,phone,is_active');

