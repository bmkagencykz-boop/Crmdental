-- A branch of the clinic by its id or its name (case-insensitive; an active
-- one first), null when nothing matches: the `branch` field of a website form
CREATE OR REPLACE FUNCTION "private"."find_branch"("org_id" bigint, "value" "text") RETURNS bigint
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  wanted text := nullif(btrim(value), '');
begin
  if wanted is null then
    return null;
  end if;
  return (
    select b.id
    from public.branches b
    where b.organization_id = org_id
      and (lower(btrim(b.name)) = lower(wanted) or (wanted ~ '^[0-9]{1,18}$' and b.id = wanted::bigint))
    order by b.is_active desc, b.position, b.id
    limit 1
  );
end;
$$;

-- The employees a lead of a branch goes to, among the candidates (in their
-- order): those who work in the branch; all the candidates when the lead has
-- no branch or none of them works there
CREATE OR REPLACE FUNCTION "private"."branch_pool"("org_id" bigint, "branch" bigint, "candidates" bigint[]) RETURNS bigint[]
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  in_branch bigint[];
begin
  if branch is null or candidates is null then
    return coalesce(candidates, '{}'::bigint[]);
  end if;
  select coalesce(array_agg(c.sales_id order by c.position), '{}'::bigint[]) into in_branch
  from unnest(candidates) with ordinality as c(sales_id, position)
  where exists (
    select 1 from public.sales_branches sb
    where sb.organization_id = org_id and sb.sales_id = c.sales_id and sb.branch_id = branch
  );
  return case when cardinality(in_branch) > 0 then in_branch else candidates end;
end;
$$;

-- The branch of a deal written without one: the doctor's, else (a new deal)
-- the branch of its responsible, or of the employee creating it, when they
-- work in one branch only. Runs before deal_attribution and deal_before_write
-- (alphabetical order): the distribution knows the branch. An explicit
-- branch, or a branch removed by hand, is kept.
CREATE OR REPLACE FUNCTION "private"."handle_deal_branch"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  responsible bigint;
begin
  if new.branch_id is not null then
    return new;
  end if;
  if tg_op = 'UPDATE' and (old.branch_id is not null or new.doctor_id is not distinct from old.doctor_id) then
    return new;
  end if;
  if new.doctor_id is not null then
    select d.branch_id into new.branch_id
    from public.doctors d
    where d.organization_id = new.organization_id and d.id = new.doctor_id;
  end if;
  if new.branch_id is null and tg_op = 'INSERT' then
    responsible := coalesce(new.sales_id, private.current_sales_id());
    if responsible is not null then
      select min(sb.branch_id) into new.branch_id
      from public.sales_branches sb
      where sb.organization_id = new.organization_id and sb.sales_id = responsible
      having count(*) = 1;
    end if;
  end if;
  return new;
end;
$$;

-- The tasks of a deal follow its branch
CREATE OR REPLACE FUNCTION "private"."handle_deal_branch_changed"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  update public.tasks t
  set branch_id = new.branch_id
  where t.organization_id = new.organization_id and t.deal_id = new.id
    and t.branch_id is distinct from new.branch_id;
  return null;
end;
$$;

-- tasks.branch_id is always the branch of the task's deal (the lists filter
-- on it, the policies of «Мой филиал» read it)
CREATE OR REPLACE FUNCTION "private"."handle_task_branch"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  new.branch_id := (
    select d.branch_id
    from public.deals d
    where d.organization_id = new.organization_id and d.id = new.deal_id
  );
  return new;
end;
$$;

-- The branch of a visit: the one chosen, else of its chair, else of its
-- doctor, else of its deal; moving the visit to another chair or doctor
-- takes their branch
CREATE OR REPLACE FUNCTION "private"."handle_visit_branch"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'INSERT' and new.branch_id is not null then
    return new;
  end if;
  if tg_op = 'UPDATE' and (
    new.branch_id is distinct from old.branch_id
    or (new.chair_id is not distinct from old.chair_id and new.doctor_id is not distinct from old.doctor_id)
  ) then
    return new;
  end if;
  new.branch_id := coalesce(
    (select c.branch_id from public.chairs c where c.organization_id = new.organization_id and c.id = new.chair_id),
    (select d.branch_id from public.doctors d where d.organization_id = new.organization_id and d.id = new.doctor_id),
    case when tg_op = 'UPDATE' then new.branch_id end,
    (select d.branch_id from public.deals d where d.organization_id = new.organization_id and d.id = new.deal_id)
  );
  return new;
end;
$$;

-- «Привязать к филиалу»: the deals and visits without a branch go to this
-- one (a clinic opening its second address). Owner and head. A system write:
-- no automations, no notifications. Returns { deals, visits }.
CREATE OR REPLACE FUNCTION "public"."assign_branch_to_unassigned"("target_branch_id" bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := private.current_organization_id();
  moved_deals integer;
  moved_visits integer;
  previous_importing text := current_setting('crm.importing', true);
  previous_notifications text := current_setting('crm.notifications', true);
begin
  if org_id is null or private.current_user_role() is distinct from 'owner'
    and private.current_user_role() is distinct from 'head' then
    raise exception 'Филиалы настраивают владелец и руководитель'
      using errcode = '42501', hint = 'branches_forbidden';
  end if;
  if not exists (select 1 from public.branches b where b.organization_id = org_id and b.id = target_branch_id) then
    raise exception 'Филиал не найден' using errcode = '22023', hint = 'branches_not_found';
  end if;
  perform set_config('crm.importing', 'on', true);
  perform set_config('crm.notifications', 'off', true);
  update public.deals d
  set branch_id = target_branch_id
  where d.organization_id = org_id and d.branch_id is null;
  get diagnostics moved_deals = row_count;
  update public.visits v
  set branch_id = target_branch_id
  where v.organization_id = org_id and v.branch_id is null;
  get diagnostics moved_visits = row_count;
  perform set_config('crm.importing', coalesce(previous_importing, ''), true);
  perform set_config('crm.notifications', coalesce(previous_notifications, ''), true);
  return jsonb_build_object('deals', moved_deals, 'visits', moved_visits);
end;
$$;

