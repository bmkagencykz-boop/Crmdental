-- «Сохранить как шаблон этапа»: the stage without teeth — identical lines
-- (same service, name, price, discount) merged, quantities added up. Runs
-- with the caller's rights.
CREATE OR REPLACE FUNCTION "public"."save_stage_template"("source_stage_id" bigint, "template_name" "text" DEFAULT NULL::"text") RETURNS bigint
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  stage public.treatment_stages;
  new_template_id bigint;
begin
  select * into stage from public.treatment_stages s
  where s.organization_id = private.current_organization_id() and s.id = source_stage_id;
  if not found then
    raise exception 'Этап не найден' using errcode = 'P0002';
  end if;
  insert into public.treatment_stage_templates (organization_id, name, direction_id, description, items)
  values (stage.organization_id, coalesce(nullif(btrim(template_name), ''), stage.name), stage.direction_id, stage.description,
    coalesce((
      select jsonb_agg(jsonb_build_object('service_id', l.service_id, 'name', l.name, 'quantity', l.quantity,
        'unit_price', l.unit_price, 'discount_percent', l.discount_percent) order by l.first_position, l.first_id)
      from (
        select i.service_id, i.name, i.unit_price, i.discount_percent,
          least(sum(i.quantity), 1000)::integer as quantity, min(i.position) as first_position, min(i.id) as first_id
        from public.treatment_plan_items i
        where i.organization_id = stage.organization_id and i.stage_id = stage.id
        group by i.service_id, i.name, i.unit_price, i.discount_percent
      ) l
    ), '[]'::jsonb))
  returning id into new_template_id;
  return new_template_id;
end;
$$;

-- «Добавить этап из шаблона»: a new stage at the end of the plan with the
-- template's items, at the prices of the current price list (the saved
-- price when the service is gone, archived or without a price). The
-- discounts are copied as they were saved. Runs with the caller's rights.
CREATE OR REPLACE FUNCTION "public"."add_stage_from_template"("target_plan_id" bigint, "source_template_id" bigint) RETURNS bigint
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  plan public.treatment_plans;
  template public.treatment_stage_templates;
  new_stage_id bigint;
begin
  select * into plan from public.treatment_plans p
  where p.organization_id = private.current_organization_id() and p.id = target_plan_id;
  if not found then
    raise exception 'План не найден' using errcode = 'P0002';
  end if;
  select * into template from public.treatment_stage_templates t
  where t.organization_id = plan.organization_id and t.id = source_template_id;
  if not found then
    raise exception 'Шаблон не найден' using errcode = 'P0002';
  end if;
  insert into public.treatment_stages (organization_id, plan_id, name, direction_id, description)
  values (plan.organization_id, plan.id, template.name, template.direction_id, template.description)
  returning id into new_stage_id;

  perform set_config('crm.treatment_copy', 'on', true);
  insert into public.treatment_plan_items (organization_id, plan_id, stage_id, service_id, name, quantity, unit_price, discount_percent, position)
  select plan.organization_id, plan.id, new_stage_id, sv.id,
    coalesce(nullif(btrim(x.item ->> 'name'), ''), sv.name, 'Услуга'),
    least(greatest(coalesce((x.item ->> 'quantity')::integer, 1), 1), 1000),
    coalesce(case when sv.id is not null and not sv.is_archived then round(sv.price)::bigint end,
      (x.item ->> 'unit_price')::bigint, 0),
    least(greatest(coalesce((x.item ->> 'discount_percent')::numeric, 0), 0), 100),
    (x.n - 1)::integer
  from jsonb_array_elements(template.items) with ordinality as x(item, n)
    left join public.services sv on sv.organization_id = plan.organization_id and sv.id = (x.item ->> 'service_id')::bigint
  order by x.n;
  perform set_config('crm.treatment_copy', '', true);
  return new_stage_id;
end;
$$;

