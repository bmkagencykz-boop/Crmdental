--
-- The treatment plan editor as a full page («План лечения», stage 34), like
-- the plan of a dental MIS: a header, stages as tabs, a dental chart and the
-- items of every stage. Evolves stage 29 (29_treatment_plans.sql): the same
-- plans and items, now with real stages.
--
--   treatment_plan_types      «Тип плана»: Основной, Альтернативный,
--                             Эконом, Премиум — a clinic dictionary
--   treatment_directions      «Направление» of a stage: Терапия, Хирургия,
--                             Ортопедия… — a clinic dictionary
--   treatment_plans           + plan_type_id, complaints («Основные
--                             жалобы»), insurance_policy («Страховой
--                             полис», text: there is no insurance module).
--                             «Дополнительная скидка» is the discount of the
--                             plan of stage 29 (percent or tenge).
--   treatment_stages          the stages of a plan (tabs «Этап 1, 2…»): name,
--                             doctor, direction, deadline, description,
--                             status (new → in_progress → done, or
--                             cancelled), a discount of the stage (%).
--                             position is the stage number, 1..20.
--   treatment_plan_items      + stage_id (not null). stage_no of stage 29
--                             stays: it follows the position of the stage;
--                             an item written with a stage number only
--                             (stage 29 clients, the API) goes to the stage
--                             with this number, created when missing.
--   treatment_stage_templates «Сохранить как шаблон этапа»: a stage without
--                             teeth (name, direction, description, items as
--                             jsonb, identical lines merged) that «Добавить
--                             этап из шаблона» copies into a plan with the
--                             prices of the current price list.
--
-- A new plan gets «Этап 1» (not a copy: «Дублировать план» copies the
-- stages). The stage-29 items were moved to stages by their stage number
-- (the migration).
--
-- Totals, whole tenge (the TS twin is treatment/planMath.ts):
--   line_total  = round(quantity × price × (100 − discount %) / 100)
--   stage total = Σ line_total − round(Σ line_total × stage discount % / 100)
--                                                (private.treatment_stage_total)
--   subtotal    = Σ stage totals of the stages not cancelled
--                                                (private.treatment_plan_subtotal)
--   total       = max(0, subtotal − round(subtotal × plan % / 100) − plan ₸)
--                                  (private.treatment_plan_total, stage 29)
--   «Итого» is Σ quantity × price, «Скидка в этапах» = «Итого» − subtotal,
--   «Дополнительная скидка» = subtotal − total.
-- Items of a cancelled stage count neither in the totals nor in the
-- progress of the plan. A stage follows its items: some done → in progress,
-- all done → done (a cancelled stage stays cancelled).
--
-- Rights: stages and templates follow the plans (whoever sees the deal;
-- owner, head and manager write; not the integrator: no money). A stage
-- discount above the clinic limit is for the owner and the head
-- (private.check_treatment_discount). The dictionaries are read by every
-- employee and edited by whoever configures the clinic (owner, head,
-- integrator).
--

