-- The total of a stage from the sum of its line totals and its discount.
-- Twin: stageTotal() in planMath.ts
CREATE OR REPLACE FUNCTION "private"."treatment_stage_total"("lines_total" bigint, "discount_percent" numeric) RETURNS bigint
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select lines_total - round(lines_total * discount_percent / 100)::bigint;
$$;

-- The subtotal of a plan: the totals of its stages, cancelled ones aside
CREATE OR REPLACE FUNCTION "private"."treatment_plan_subtotal"("org_id" bigint, "target_plan_id" bigint) RETURNS bigint
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  subtotal bigint;
begin
  select coalesce(sum(private.treatment_stage_total(t.lines_total, t.discount_percent)), 0)::bigint
  into subtotal
  from (
    select s.id, s.discount_percent, coalesce(sum(i.line_total), 0)::bigint as lines_total
    from public.treatment_stages s
      left join public.treatment_plan_items i on i.organization_id = s.organization_id and i.stage_id = s.id
    where s.organization_id = org_id and s.plan_id = target_plan_id and s.status <> 'cancelled'
    group by s.id, s.discount_percent
  ) t;
  return subtotal;
end;
$$;

-- The stage of a plan with this number, created («Этап N») when missing:
-- items written with a stage number only (stage 29)
CREATE OR REPLACE FUNCTION "private"."treatment_stage_at"("org_id" bigint, "target_plan_id" bigint, "stage_number" integer) RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  found_id bigint;
begin
  select s.id into found_id
  from public.treatment_stages s
  where s.organization_id = org_id and s.plan_id = target_plan_id and s.position = stage_number;
  if found_id is null then
    insert into public.treatment_stages (organization_id, plan_id, position, name)
    values (org_id, target_plan_id, stage_number, 'Этап ' || stage_number)
    returning id into found_id;
  end if;
  return found_id;
end;
$$;

-- A stage follows its items: some done → in progress, all done → done,
-- no longer all done → in progress. A cancelled stage stays cancelled.
-- Twin: stageStatusAfterProgress() in planMath.ts
CREATE OR REPLACE FUNCTION "private"."treatment_stage_progress"("org_id" bigint, "target_stage_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  stage public.treatment_stages;
  total_items integer;
  done_items integer;
  next_status text;
begin
  select * into stage from public.treatment_stages s
  where s.organization_id = org_id and s.id = target_stage_id;
  if not found or stage.status = 'cancelled' then
    return;
  end if;
  select count(*), count(*) filter (where i.done) into total_items, done_items
  from public.treatment_plan_items i
  where i.organization_id = org_id and i.stage_id = stage.id;
  next_status := case
    when total_items > 0 and done_items = total_items then 'done'
    when stage.status = 'done' then 'in_progress'
    when done_items > 0 and stage.status = 'new' then 'in_progress'
    else stage.status
  end;
  if next_status <> stage.status then
    update public.treatment_stages s set status = next_status
    where s.organization_id = org_id and s.id = stage.id;
  end if;
end;
$$;

-- After items or stages change: the progress of an agreed plan (some done:
-- in progress, all done: completed; cancelled stages aside) and the plan
-- amount of the deal
CREATE OR REPLACE FUNCTION "private"."refresh_treatment_plan"("org_id" bigint, "target_plan_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  plan public.treatment_plans;
  total_items integer;
  done_items integer;
  next_status text;
begin
  select * into plan from public.treatment_plans p
  where p.organization_id = org_id and p.id = target_plan_id;
  if not found then
    return;
  end if;
  if plan.status in ('agreed', 'in_progress', 'completed') then
    select count(*), count(*) filter (where i.done) into total_items, done_items
    from public.treatment_plan_items i
      join public.treatment_stages s on s.organization_id = i.organization_id and s.id = i.stage_id
    where i.organization_id = org_id and i.plan_id = plan.id and s.status <> 'cancelled';
    next_status := case
      when total_items > 0 and done_items = total_items then 'completed'
      when plan.status = 'completed' then 'in_progress'
      when done_items > 0 and plan.status = 'agreed' then 'in_progress'
      else plan.status
    end;
    if next_status <> plan.status then
      update public.treatment_plans p set status = next_status
      where p.organization_id = org_id and p.id = plan.id;
    end if;
  end if;
  if plan.is_main then
    perform private.sync_treatment_plan_amount(plan.id);
  end if;
end;
$$;

-- Before a stage is written: its plan never changes, the next number and
-- «Этап N» by default, the doctor of the plan, the discount limit
CREATE OR REPLACE FUNCTION "private"."handle_treatment_stage_before_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  plan_doctor_id bigint;
begin
  if tg_op = 'UPDATE' and new.plan_id is distinct from old.plan_id then
    raise exception 'Этап не переносится в другой план' using errcode = '22023';
  end if;
  if tg_op = 'INSERT' then
    if coalesce(new.position, 0) < 1 then
      select coalesce(max(s.position), 0) + 1 into new.position
      from public.treatment_stages s
      where s.organization_id = new.organization_id and s.plan_id = new.plan_id;
    end if;
    if new.position > 20 then
      raise exception 'В плане не больше 20 этапов' using errcode = '23514', hint = 'too_many_stages';
    end if;
    if new.doctor_id is null then
      select p.doctor_id into plan_doctor_id from public.treatment_plans p
      where p.organization_id = new.organization_id and p.id = new.plan_id;
      new.doctor_id := plan_doctor_id;
    end if;
  end if;
  new.name := coalesce(nullif(btrim(new.name), ''), 'Этап ' || new.position);
  new.description := nullif(btrim(new.description), '');
  if new.discount_percent > 0 and (tg_op = 'INSERT' or new.discount_percent <> old.discount_percent) then
    perform private.check_treatment_discount(new.organization_id, new.discount_percent, 0, 0);
  end if;
  new.updated_at := now();
  return new;
end;
$$;

-- After a stage is written: the stage number of its items, the totals and
-- the progress of the plan (status, discount, a deleted stage)
CREATE OR REPLACE FUNCTION "private"."handle_treatment_stage_after_write"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  org_id bigint := coalesce(new.organization_id, old.organization_id);
  target_plan_id bigint := coalesce(new.plan_id, old.plan_id);
begin
  if tg_op = 'UPDATE' and new.position <> old.position then
    update public.treatment_plan_items i
    set stage_no = new.position
    where i.organization_id = org_id and i.stage_id = new.id and i.stage_no <> new.position;
  end if;
  if tg_op = 'DELETE'
    or (tg_op = 'UPDATE' and (new.status <> old.status or new.discount_percent <> old.discount_percent)) then
    perform private.refresh_treatment_plan(org_id, target_plan_id);
  end if;
  return null;
end;
$$;

