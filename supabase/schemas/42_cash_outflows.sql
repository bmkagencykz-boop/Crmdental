--
-- Money going out of the cash desk (stage 42): «Расход» — rent, materials,
-- salaries, the lab — plus the links of the payroll payouts (stage 39) and
-- of the new lab payments (stage 40) with the cash desk (stage 36).
--
--   cash_expense_categories  «статьи расходов» of a clinic: Зарплата
--                            (code salary), Лаборатория (lab), Материалы
--                            (materials), Аренда (rent), Прочее (other) —
--                            seeded for every clinic; the owner and the head
--                            add their own and archive them. A category with
--                            a code is a system one: not deleted, its code
--                            never changes.
--   account_operations       a new kind 'expense': money out of the till
--                            (cash, card, Kaspi, transfer), with a category
--                            (category_id), NOT tied to a patient
--                            (patient_id is null exactly for an expense), a
--                            deal, a plan or a visit. till_delta = − amount:
--                            the expected cash of the shift goes down by the
--                            cash of an expense (private.cash_shift_expected
--                            is unchanged: it follows till_delta). The
--                            column till_delta is redefined here (a generated
--                            column cannot be altered in place), together
--                            with the view account_operations_summary (left
--                            join of the patient, the category at the end).
--   payroll_adjustments      account_operation_id: a payout («выплата»)
--                            given from the cash desk («Выдать из кассы»,
--                            public.record_payroll_payout) is linked to its
--                            expense (category Зарплата). A payout paid by
--                            bank transfer has no operation.
--   lab_payments             «Оплата лаборатории»: lab, month of the
--                            settlement, amount, method, moment, comment,
--                            optionally its expense (category Лаборатория,
--                            public.record_lab_payment); the settlement
--                            (public.report_lab_settlement, 40_lab_orders.sql)
--                            shows owed / paid / balance per lab.
--
-- The links stay consistent: the operation is the money. Cancelling
-- (deleting) the operation deletes the payout or the lab payment (FK on
-- delete cascade); deleting the payout or the lab payment cancels its
-- operation (private.handle_cash_link_deleted). The amount, the method and
-- the day of a linked payout or lab payment are those of the operation:
-- they change in the cash desk (the method and the time sync over,
-- private.handle_expense_link_sync), not on the linked side.
--
-- Rights: expenses — the owner and the head; an administrator only when
-- the clinic allows it (organization_settings.manager_cash_expenses,
-- «Администраторы проводят расходы», default no; private.can_record_expense).
-- Expenses are read by the owner and the head, by an administrator with the
-- «Отчёты» right, and by the administrator who recorded them; never by the
-- integrator. Changing and cancelling: owner and head (the rules of stage
-- 36). Lab payments and payouts: owner and head (money). Everything goes to
-- the audit log (the operation, the categories, the lab payments; payouts
-- already are).
--
-- Twins: payments/paymentMath.ts (till_delta, expected cash, totals,
-- rights), lab/labMath.ts (the settlement with payments), the FakeRest
-- demo (providers/fakerest/payments.ts, payroll.ts, labOrders.ts).
--

