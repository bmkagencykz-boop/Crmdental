create or replace view public.account_operations_summary with (security_invoker = on) as
select
    o.id,
    o.organization_id,
    o.patient_id,
    o.kind,
    o.account,
    o.amount,
    o.method,
    o.parts,
    o.cash_received,
    o.prepayment,
    o.occurred_at,
    o.sales_id,
    o.branch_id,
    o.shift_id,
    o.deal_id,
    o.plan_id,
    o.plan_item_ids,
    o.visit_id,
    o.comment,
    o.source,
    o.deal_payment_id,
    o.created_at,
    o.deposit_delta,
    o.paid_delta,
    o.till_delta,
    nullif(btrim(concat_ws(' ', p.last_name, p.first_name, p.middle_name)), '') as patient_name,
    p.phones[1] as patient_phone,
    nullif(btrim(concat_ws(' ', s.first_name, s.last_name)), '') as cashier_name,
    d.name as deal_name,
    tp.name as plan_name,
    b.name as branch_name,
    o.category_id,
    c.name as category_name,
    c.code as category_code,
    pa.id as payroll_adjustment_id,
    lp.id as lab_payment_id
from public.account_operations o
    left join public.patients p on p.organization_id = o.organization_id and p.id = o.patient_id
    left join public.sales s on s.organization_id = o.organization_id and s.id = o.sales_id
    left join public.deals d on d.organization_id = o.organization_id and d.id = o.deal_id
    left join public.treatment_plans tp on tp.organization_id = o.organization_id and tp.id = o.plan_id
    left join public.branches b on b.organization_id = o.organization_id and b.id = o.branch_id
    left join public.cash_expense_categories c on c.organization_id = o.organization_id and c.id = o.category_id
    left join public.payroll_adjustments pa on pa.organization_id = o.organization_id and pa.account_operation_id = o.id
    left join public.lab_payments lp on lp.organization_id = o.organization_id and lp.account_operation_id = o.id;

